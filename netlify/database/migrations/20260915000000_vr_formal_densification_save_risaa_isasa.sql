-- Verification. Vote-row SHAPE only: there is no politicians table to join
-- against — vr_member_votes.politician_id is a text slug with no foreign key,
-- resolved in application code through db/vr-member-map.json, and
-- scripts/test-vr-vote-seed.mjs is what proves every slug resolves.
DO $$
DECLARE
  want record;
  n integer;
BEGIN
  FOR want IN
    SELECT * FROM (VALUES
      ('H.R. 8281', 118, 'states_federal_power'),
      ('H.R. 7888', 118, 'congress_oversight'),
      ('H.R. 8369', 118, 'power_of_purse')
    ) AS t(number, congress, issue_key)
  LOOP
    IF NOT EXISTS (SELECT 1 FROM vr_measures WHERE number = want.number AND congress = want.congress) THEN
      RAISE NOTICE 'Verification: % (%th) is not in this database; its row was skipped.',
        want.number, want.congress;
      CONTINUE;
    END IF;

    SELECT count(*) INTO n FROM vr_measures me
      JOIN vr_measure_issues mi ON mi.measure_id = me.id
     WHERE me.number = want.number AND me.congress = want.congress
       AND mi.issue_key = want.issue_key;
    IF n = 0 THEN
      RAISE EXCEPTION 'Verification: % (%th) did not receive its % row.',
        want.number, want.congress, want.issue_key;
    END IF;

    SELECT count(*) INTO n FROM vr_measures me
      JOIN vr_rollcalls rc ON rc.measure_id = me.id
      JOIN vr_member_votes mv ON mv.rollcall_id = rc.id
     WHERE me.number = want.number AND me.congress = want.congress
       AND (mv.politician_id IS NULL
            OR btrim(mv.politician_id) = ''
            OR mv.position NOT IN ('yea', 'nay', 'present', 'not_voting'));
    IF n > 0 THEN
      RAISE EXCEPTION 'Verification: % member vote(s) on % (%th) have a blank member or an unreadable position.',
        n, want.number, want.congress;
    END IF;
  END LOOP;

  -- The one row this pass codes against the grain must stay that way. A later
  -- flip to yea_supports would invert every member's score on the axis.
  SELECT count(*) INTO n FROM vr_measures me
    JOIN vr_measure_issues mi ON mi.measure_id = me.id
   WHERE me.number = 'H.R. 8281' AND me.congress = 118
     AND mi.issue_key = 'states_federal_power' AND mi.support_meaning = 'yea_opposes';
  IF n = 0 AND EXISTS (SELECT 1 FROM vr_measures WHERE number = 'H.R. 8281' AND congress = 118) THEN
    RAISE EXCEPTION 'Verification: the H.R. 8281 states_federal_power row is missing or not coded yea_opposes.';
  END IF;

  -- checks_balances is the general key and this pass declined it on scope. The
  -- assertion is deliberately scoped to H.R. 7888 rather than to the whole table:
  -- a table-wide count = 0 would guard the August 2026 split's leftovers, which
  -- are not this migration's subject, and would fail a deploy over someone else's
  -- row.
  SELECT count(*) INTO n FROM vr_measures me
    JOIN vr_measure_issues mi ON mi.measure_id = me.id
   WHERE me.number = 'H.R. 7888' AND me.congress = 118
     AND mi.issue_key = 'checks_balances';
  IF n > 0 THEN
    RAISE EXCEPTION 'Verification: H.R. 7888 picked up a checks_balances row; that key was declined on scope and the mechanism key is congress_oversight.';
  END IF;
END $$;
