-- ─────────────────────────────────────────────────────────────────────────────
-- Formal densification: the SAVE Act, RISAA, and the Israel Security Assistance
-- Support Act — three high-vote 118th-Congress measures that were carrying fewer
-- axes than their text supports.
--
-- DOCTRINE (runbook rule 22, unchanged). If the measure's primary text contains a
-- provision that clearly implicates a live issue key, it is mapped. A yea advances
-- the package as written; a nay blocks it. Weight is the key's share of the bill,
-- the rationale names the sections, and direction is what the instrument DOES on
-- the key, not why anyone voted for it. Nothing here changes the Direction Match
-- formula, a floor, an existing weight, or a guard. No new issue keys. No stances.
--
-- TARGETS, in the order the brief set them.
--
--   1 · H.R. 8281 (118th), the SAVE Act — house 118/2 roll 345, 221-198
--       (R 216-0, D 5-198), 62 attributed member-votes. Carried election_security
--       100 primary and voting_access 70. Read for immig_balance and
--       states_federal_power against the engrossed text.
--   2 · H.R. 7888 (118th), the Reforming Intelligence and Securing America Act,
--       P.L. 118-49 — house 118/2 roll 119, 273-147 (R 126-88, D 147-59); senate
--       118/2 roll 150, 60-34. Carried privacy_rights 85 primary and
--       strong_defense 65. Read for checks_balances against the enrolled text.
--   3 · H.R. 8369 (118th), the Israel Security Assistance Support Act — house
--       118/2 roll 217, 224-187 (R 208-3, D 16-184), 62 attributed member-votes.
--       Carried israel_support 100 alone. Chosen as the optional third because it
--       is the highest-vote measure still on ONE key after (1) and (2), it is a
--       policy bill rather than an amendment, and it is not the cross-NDAA work
--       the brief reserved for its own pass.
--
--   None of the three is near-unanimous, so rule 2 does not reach any of them.
--
-- MAPPED — three rows, all secondary. No existing primary or weight is touched.
--
--   H.R. 8281 · states_federal_power 45, yea_opposes.
--     The bill is a preemption instrument as well as a citizenship instrument. New
--     NVRA section 4(b) (bill sec. 2(b)) tells a State it "shall not accept and
--     process" a federal-election registration application without documentary
--     proof, "[u]nder any method of voter registration in a State"; new section
--     8(j) (sec. 2(f)(3)) repeats it "[n]otwithstanding any other provision of this
--     Act"; sec. 2(a) fixes the acceptable-document list federally. Sec. 2(k) then
--     narrows the section 4(c) exemption that had kept the NVRA off certain States
--     altogether, and new section 4(d) lets such a State escape only by adopting
--     "identical" requirements. Sec. 2(i) opens a federal private right of action
--     against a State election official, sec. 2(j) makes the same act a federal
--     crime, and sec. 3 has the EAC push implementing guidance to every chief State
--     election official in 10 days. The state-side provisions were read and are
--     named in the rationale — sec. 2(f)(1)'s "applicable State law" removal
--     ground, sec. 2(g)'s clarification of State removal authority, sec. 7's
--     savings clause for exemptions from OTHER federal laws — and each one
--     accommodates the federal rule rather than letting the State's choice stand.
--     Weight 45: real and pervasive, but below the citizenship purpose the bill is
--     actually for. Coded yea_opposes, which the key already carries elsewhere in
--     the record; the chip's Official Record % stays directional either way.
--
--   H.R. 7888 · congress_oversight 45, yea_supports.
--     See the DECLINED note on checks_balances below: that key is the general one
--     and takes no roll-call mappings by design, and the mechanism this act names
--     is oversight. Sec. 11(a) revokes the FBI's statutory reporting exemption
--     under 50 U.S.C. 1873 and adds a mandatory annual report to the House and
--     Senate intelligence and judiciary committees plus a new quarterly report;
--     sec. 9 sends a DOJ Inspector General report on Bureau querying practices to
--     the appropriate congressional committees; sec. 18(a) gives the DNI 7 days to
--     notify the intelligence committees of a significant unauthorized disclosure
--     of section 702 information; sec. 18(b) sends a compliance-monitoring study to
--     the same committees; sec. 14(b) adds FISC contempt usage to the annual
--     transparency report. Nothing in the act reduces an existing duty to report to
--     Congress, so one honest direction describes the instrument.
--
--   H.R. 8369 · power_of_purse 60, yea_supports.
--     Secs. 4, 5 and 6 are the whole operative bill and all three are purse
--     instruments: no appropriated DoD or State funds may be used to withhold or
--     cancel a delivery or to pay anyone who supports doing so; the Secretaries
--     must ensure prompt delivery of articles supported by prior appropriations
--     Acts, with 15 days for already-withheld items; and the unobligated Office of
--     the Secretary balances at both departments are frozen until each Secretary
--     certifies to the Appropriations Committees that the deadline was met.
--     Sec. 3(3) says it outright — "utilize all congressionally appropriated funds
--     ... as Congress intended". This REVERSES a documented refusal: the seed note
--     on this measure declined the old checks_balances umbrella because "a member
--     voting to force out bombs the administration had paused is voting about
--     Israel". That is a motive reading, which the product rule excludes, and the
--     note predates the August 2026 split that created power_of_purse. It is not a
--     duplicate of israel_support either: whether the United States should back
--     Israel and whether the executive may sit on money Congress appropriated are
--     questions a member can answer independently, which is exactly the distinction
--     the split was made to draw.
--
-- DECLINED, with buckets. Each was read against the text, not waved off.
--
--   H.R. 8281 · immig_balance — [no_provision]. The chip is a PAIRING chip:
--     "Pair strong border security with earned legal pathways." The engrossed text
--     has neither half. It contains no border measure and no pathway; its
--     immigration-adjacent content is noncitizen-registration enforcement — sec.
--     2(f)(1) and 2(g) removal grounds, sec. 2(h)(2) and 2(c)(5) letting the
--     registration form's information be used as evidence in an immigration
--     proceeding against a false declarant, sec. 2(j)(B)'s penalty for an executive
--     employee who materially assists a noncitizen registrant, and sec. 5's DHS
--     naturalization notice. Mapping a pairing chip to an enforcement-only bill
--     because the word "immigration" appears is the slogan-level fit the brief said
--     to refuse. border_security and deportations were checked for the same reason
--     and fail the same way: nothing in the bill removes anyone from the country or
--     builds anything at the border.
--
--   H.R. 7888 · checks_balances — [no_provision, on the key's own scope]. Not a
--     two-flank refusal, and the two-flank question was asked anyway; both answers
--     are recorded here because the brief asked for both.
--       · Scope, which is dispositive. The August 2026 split left checks_balances
--         as the GENERAL key and moved every named mechanism to one of five others.
--         alignment-tool.js says so in terms: it "has no roll-call mappings and is
--         expected to keep none — a general-posture claim cannot be settled by any
--         single vote", and it sits on the receipt-card hold list for that reason.
--         RISAA names its mechanism, so it belongs to congress_oversight above.
--       · Two-flank, asked and answered NO on the oversight axis. The 147 nays are
--         88 Republicans and 59 Democrats, which is the shape rule 5 exists to
--         catch. But the two flanks were not opposed: the thing the nay bloc wanted
--         added was a warrant requirement — Biggs amendment No. 1, house 118/2 roll
--         114, failed on a 212-212 tie the same day — and both flanks wanted more
--         constraint on executive querying, not less. Read per key, as rule 23
--         requires: no provision of the act reduces a reporting duty to Congress,
--         so the instrument points one way on congress_oversight whatever the nays
--         wanted. A nay still blocks the reporting duties, which is what the
--         product rule scores.
--
--   H.R. 7888 · judicial_check — [no_provision]. Sec. 5's FISC amicus changes and
--     sec. 14's contempt power do strengthen a court against the executive, but the
--     key as scoped is about federal courts halting unlawful executive action,
--     including nationwide. A specialised court's contempt authority over its own
--     proceedings is not that question, and stretching it there would put FISA
--     rolls into the nationwide-injunction percentage.
--
--   H.R. 7888 · civil_service_control — [below_floor]. Secs. 12 and 17 do reach
--     removal and adverse personnel actions for Bureau employees who violate FISA,
--     which is the classification-and-removal mechanism that key names. Two
--     sections of twenty-five, aimed at one agency's FISA misconduct rather than at
--     the competitive service, is below the share the record maps.
--
--   H.R. 8369 · war_powers and restraint — [no_provision]. The bill commits no
--     United States forces to hostilities and takes no position on whether to
--     intervene; it moves already-approved articles to a partner. Neither key has
--     a provision to rest on.
--
--   H.R. 8369 · congress_oversight — [duplicate]. The certify-and-report duty to
--     the Appropriations Committees in sec. 6 is the release condition on the same
--     purse freeze already read under power_of_purse. It is the same provision, so
--     it does not get counted twice.
--
--   H.R. 6126 (118th, 61 member-votes, israel_support + cut_spending) was the
--     runner-up for the third slot and is left for a later pass rather than mapped
--     thin here; see the runbook follow-up list.
--
