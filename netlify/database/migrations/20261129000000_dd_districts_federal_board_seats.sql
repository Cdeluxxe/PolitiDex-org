-- decision, a comment or a vote on one of those boards would fail at the
-- foreign key instead of landing.
--
-- WHAT IT CHANGES. Rows only — NO NEW TABLE AND NO SCHEMA CHANGE. The seat-key
-- and number checks already admit 'house' (number above zero) and 'us-senate'
-- (number 0), and the state check already admits any two-letter code. A U.S.
-- House district_id is <code>-house-<n>; a U.S. Senate one is the board key,
-- <code>-us-senate-<pid>, as Utah's two are. ON CONFLICT DO NOTHING: a row that
-- already exists keeps its label.
--
-- It writes no residency, take or vote. Opening a seat to the gate is not a
-- verification; only the signed Didit webhook writes method = 'vendor'.
