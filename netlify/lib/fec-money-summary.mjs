// ─────────────────────────────────────────────────────────────────────────────
// fec-money-summary.mjs — the FEC money summary the offline discovery job saves
// ─────────────────────────────────────────────────────────────────────────────
// scripts/discover-raw-ingest-sources-2026-11.mjs already opens each federal
// candidate's principal campaign committee on the FEC to read its `website`.
// While that committee is open, the job also keeps the public money summary the
// FEC publishes for it — and nothing else:
//
//   receipts        total receipts for the cycle
//   disbursements   total disbursements for the cycle
//   cashOnHand      cash on hand at the end of the last report
//   coverageEnd     the last report's coverage end date (YYYY-MM-DD)
//
// The rows land in the FTM_FEC_SUMMARY table inside ftm-data.js, which is the
// finance data the letterhead 💰 receipts chip already reads. A row is written
// only when the person has no money figure on their profile yet, or the one
// they have is OLDER than the FEC report's coverage end date. A hand-verified
// figure with no date of its own is never replaced.
//
// Pure: nothing in this module fetches, and the live cron imports none of it.
// ─────────────────────────────────────────────────────────────────────────────

export const FEC_SUMMARY_BEGIN = "    // ── BEGIN FTM_FEC_SUMMARY (generated by scripts/discover-raw-ingest-sources-2026-11.mjs; do not edit by hand) ──";
export const FEC_SUMMARY_END = "    // ── END FTM_FEC_SUMMARY ──";

/** The office strings the discovery job treats as federal (U.S. House / Senate). */
export function isFederalOffice(office) {
  return /\bU\.S\.\s+(?:House|Senate)|\bU\.S\. (?:Representative|Senator)|\bCongress/i.test(String(office || ""));
}

const money = (v) => {
  if (v === null || v === undefined || v === "") return null;
  const n = Number(v);
  return Number.isFinite(n) ? Math.round(n * 100) / 100 : null;
};
const pick = (rec, keys) => {
  for (const k of keys) { const n = money(rec?.[k]); if (n !== null) return n; }
  return null;
};
/** "2026-10-14T00:00:00" → "2026-10-14"; anything unreadable → "". */
export function isoDate(v) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(v || "").trim());
  if (!m) return "";
  const d = new Date(`${m[1]}-${m[2]}-${m[3]}T00:00:00Z`);
  return Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== `${m[1]}-${m[2]}-${m[3]}` ? "" : `${m[1]}-${m[2]}-${m[3]}`;
}

/**
 * The money summary carried on an FEC committee record, or null when the record
 * carries none. Reads the FEC's own field names (the committee totals record:
 * `receipts`, `disbursements`, `last_cash_on_hand_end_period`,
 * `coverage_end_date`) and their longer spellings. A summary needs a positive
 * receipts figure; the other three are kept only when the record has them.
 */
export function fecMoneySummary(rec, { committeeId = "", candidateId = "" } = {}) {
  if (!rec || typeof rec !== "object") return null;
  const receipts = pick(rec, ["receipts", "total_receipts"]);
  if (!(receipts > 0)) return null;
  const disbursements = pick(rec, ["disbursements", "total_disbursements"]);
  const cashOnHand = pick(rec, ["last_cash_on_hand_end_period", "cash_on_hand_end_period", "cash_on_hand"]);
  const coverageEnd = isoDate(rec.coverage_end_date || rec.last_coverage_end_date);
  const cid = String(committeeId || rec.committee_id || "").toUpperCase();
  if (!/^C\d{8}$/.test(cid)) return null;
  const out = { receipts };
  if (disbursements !== null) out.disbursements = disbursements;
  if (cashOnHand !== null) out.cashOnHand = cashOnHand;
  if (coverageEnd) out.coverageEnd = coverageEnd;
  const cycle = Number(rec.cycle);
  if (Number.isInteger(cycle) && cycle > 1970) out.cycle = cycle;
  out.committeeId = cid;
  if (/^[HSP]\w{8}$/.test(String(candidateId || ""))) out.candidateId = String(candidateId);
  out.source = `https://www.fec.gov/data/committee/${cid}/`;
  return out;
}

/** Of several committee summaries for one person, the one with the latest coverage end date. */
export function latestSummary(list) {
  return (list || []).filter(Boolean).reduce((best, s) => (!best || (s.coverageEnd || "") > (best.coverageEnd || "") ? s : best), null);
}

const MONTHS = ["january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november", "december"];
/** "2026-07-01" or "July 2026" → an ISO date (month-end for "Month YYYY"), else "". */
function looseDate(v) {
  const iso = isoDate(v);
  if (iso) return iso;
  const m = /^([A-Za-z]+)\s+(\d{4})$/.exec(String(v || "").trim());
  const mi = m ? MONTHS.indexOf(m[1].toLowerCase()) : -1;
  if (mi < 0) return "";
  return new Date(Date.UTC(Number(m[2]), mi + 1, 0)).toISOString().slice(0, 10);
}

/**
 * The date of the money figure a profile already carries, from either kind of
 * record: a hand-verified filing (its own `asOf`, else the end of its `cycle`)
 * or an earlier FEC summary row (its `coverageEnd`). "" when the record carries
 * a figure but no readable date — which counts as current and is never replaced.
 */
export function figureDate(rec) {
  if (!rec) return "";
  if (rec.coverageEnd) return isoDate(rec.coverageEnd);
  const asOf = looseDate(rec.funding?.asOf || rec.asOf);
  if (asOf) return asOf;
  const cycle = String(rec.funding?.cycle || rec.cycle || "");
  return /^\d{4}$/.test(cycle) ? `${cycle}-12-31` : "";
}
const hasFigure = (rec) => !!rec && (Number(rec.totalRaised) > 0 || Number(rec.receipts) > 0 || Number(rec.funding?.receipts) > 0);

/**
 * Whether an FEC summary may be written for a person, given the money figures
 * already on their profile (`existing`: their hand-verified filing and/or an
 * earlier FEC row). Yes when they have no figure; otherwise only when every
 * figure they have is dated and older than the summary's coverage end date.
 */
export function fecSummaryWins(summary, existing = []) {
  if (!summary || !(summary.receipts > 0)) return false;
  const figures = (Array.isArray(existing) ? existing : [existing]).filter(hasFigure);
  if (!figures.length) return true;
  if (!summary.coverageEnd) return false;
  return figures.every((r) => { const d = figureDate(r); return d && d < summary.coverageEnd; });
}

/**
 * The FTM_FEC_SUMMARY table after one discovery run. `found` maps each looked-up
 * pid to its summary; `hand(pid)` returns the hand-verified filing on their
 * profile, if any. Rows for people the run did not look up are carried over
 * unchanged. Returns the table and what happened to each looked-up person.
 */
export function mergeFecSummaries(previous, found, hand = () => null) {
  const table = { ...(previous || {}) };
  const outcome = { attached: [], kept_existing: [] };
  for (const [pid, summary] of found instanceof Map ? found : Object.entries(found || {})) {
    if (!summary) continue;
    if (fecSummaryWins(summary, [hand(pid), table[pid]])) { table[pid] = summary; outcome.attached.push(pid); }
    else outcome.kept_existing.push(pid);
  }
  return { table: Object.fromEntries(Object.keys(table).sort().map((k) => [k, table[k]])), outcome };
}

/** The table as ftm-data.js carries it: one JSON row per person, between the markers. */
export function renderFecSummaryBlock(table) {
  const rows = Object.keys(table || {}).sort().map((pid) => `      ${JSON.stringify(pid)}: ${JSON.stringify(table[pid])}`);
  return [FEC_SUMMARY_BEGIN, `    var FTM_FEC_SUMMARY = {${rows.length ? `\n${rows.join(",\n")}\n    ` : ""}};`, FEC_SUMMARY_END].join("\n");
}

function blockBounds(src) {
  const a = src.indexOf(FEC_SUMMARY_BEGIN);
  const b = src.indexOf(FEC_SUMMARY_END, a);
  if (a < 0 || b < 0) throw new Error("ftm-data.js has no FTM_FEC_SUMMARY block between its markers");
  return [a, b + FEC_SUMMARY_END.length];
}
/** The table currently committed in ftm-data.js. */
export function readFecSummaryBlock(src) {
  const [a, b] = blockBounds(src);
  const body = src.slice(a, b);
  const open = body.indexOf("{"), close = body.lastIndexOf("}");
  return JSON.parse(body.slice(open, close + 1).replace(/^\s*\/\/.*$/gm, ""));
}
/** ftm-data.js with its FTM_FEC_SUMMARY block replaced by `table`. */
export function replaceFecSummaryBlock(src, table) {
  const [a, b] = blockBounds(src);
  return src.slice(0, a) + renderFecSummaryBlock(table) + src.slice(b);
}
