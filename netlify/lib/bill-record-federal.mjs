// ─────────────────────────────────────────────────────────────────────────────
// bill-record-federal.mjs — one federal bill-record entry, from Congress.gov
// ─────────────────────────────────────────────────────────────────────────────
// The federal half of scripts/fetch-bill-record.mjs, shared with the scheduled
// bill-record job (netlify/lib/congress-sync-core.mjs) so both build the same
// entry from the same reads. Nothing here touches the network directly: the
// caller hands in `getJson(path, cacheName)`, which returns the parsed answer
// for an api.congress.gov/v3 path, null for a 404, and throws on anything else.
//
// The entry shape is db/bill-record.json's (see fetch-bill-record.mjs):
//   { src, ch, in, sp: [{ r, id, n, h }], a: [{ d, s, c, x }] }
// ─────────────────────────────────────────────────────────────────────────────
import { clean, day, chamberOf, billStage, amendmentStage, pickActions } from "./bill-record-stages.mjs";

// The nominations on file are printed under a short label ("Bondi — AG"), not
// under their PN citation. Each label → the citation Congress.gov files it under,
// checked against the nomination's own description on Congress.gov.
export const NOMINATION_PN = {
  "Bondi — AG": "11-2",
  "Gabbard — DNI": "11-16",
  "Kennedy — HHS": "11-8",
  "McMahon — ED": "11-10",
  "Patel — FBI": "12-35",
  "PN11-7": "11-7",
  "Rubio — State": "11-13",
  "Vought — OMB": "11-22",
};

export const FED_TYPES = {
  "H.R.": "hr", "S.": "s", "H.J.Res.": "hjres", "S.J.Res.": "sjres",
  "H.Con.Res.": "hconres", "S.Con.Res.": "sconres", "H.Res.": "hres", "S.Res.": "sres",
};
export const AMDT_TYPES = { "H.Amdt.": "hamdt", "S.Amdt.": "samdt" };

export const BILL_RECORD_COMMENT = "GENERATED by scripts/fetch-bill-record.mjs from the official record (Congress.gov API for federal measures, le.utah.gov bill files for Utah) — do not edit by hand. Per bill document: the record page (src), chamber of origin (ch), date introduced (in), sponsors and co-sponsors as the record names them (sp), and the key actions with their dates and the record's own text (a). Roster ids and status are derived from this file by scripts/gen-bill-docs.mjs.";

// The whole file, byte for byte as fetch-bill-record.mjs writes it.
export function renderBillRecord(records, fetchedOn) {
  const sorted = Object.fromEntries(Object.keys(records).sort((a, b) => a.localeCompare(b, undefined, { numeric: true })).map((k) => [k, records[k]]));
  return JSON.stringify({ _comment: BILL_RECORD_COMMENT, fetchedOn, records: sorted }, null, 1) + "\n";
}

// A Utah key ("2025GS|H.B. 1") is read from le.utah.gov, not Congress.gov.
export const isUtahKey = (key) => /^\d{4}[A-Z0-9]*GS\|/i.test(String(key || ""));

// Is this "<sitting>|<number>" a measure this module can read?
export function isFederalTarget(sitting, number) {
  if (/GS$/i.test(sitting)) return false;
  if (NOMINATION_PN[number]) return true;
  const pre = String(number).split(" ")[0];
  return !!(AMDT_TYPES[pre] || FED_TYPES[pre]);
}

const person = (p, r) => ({
  r,
  id: String(p.bioguideId || ""),
  n: clean(p.fullName || [p.firstName, p.lastName].filter(Boolean).join(" ")),
  h: /^Sen\./.test(p.fullName || "") ? "S" : "H",
});

const nominationStage = (a) => {
  const t = clean(a.text);
  if (/^Received in the Senate/i.test(t)) return ["received", "senate", t];
  if (/^Committee on .* Reported|Reported by Senator/i.test(t)) return ["reported", "senate", t];
  if (/^Confirmed by the Senate/i.test(t)) return ["confirmed", "senate", t];
  if (/^(Rejected|Not confirmed)/i.test(t)) return ["rejected", "senate", t];
  if (/withdrawal of nomination/i.test(t)) return ["withdrawn", "senate", t];
  if (/^Returned to the President/i.test(t)) return ["returned", "senate", t];
  return null;
};

// getJson(path, cacheName, query) → parsed JSON | null (404) | throws.
// `strict` (the scheduled job) refuses an answer missing the list it pages
// through instead of reading it as empty.
export function federalReader(getJson, { strict = false } = {}) {
  const page = (p, offset) => getJson(p, `${p}-${offset}`, `&offset=${offset}`);
  async function all(p, field) {
    const out = [];
    for (let offset = 0; offset < 5000; offset += 250) {
      const j = await page(p, offset);
      if (strict && j && !Array.isArray(j[field])) throw new Error(`${p}: answer has no ${field} list`);
      const rows = (j && j[field]) || [];
      out.push(...rows);
      if (rows.length < 250) break;
    }
    return out;
  }

  async function bill(sitting, number) {
    const [pre, num] = number.split(" ");
    const t = FED_TYPES[pre];
    const base = `bill/${sitting}/${t}/${num}`;
    const b = ((await getJson(base, base, "")) || {}).bill;
    if (!b) return null;
    const cos = await all(`${base}/cosponsors`, "cosponsors");
    const acts = (await all(`${base}/actions`, "actions"))
      .filter((a) => !a.sourceSystem || String(a.sourceSystem.code) === "9" || a.sourceSystem.name === "Senate");
    const typeWord = { hr: "house-bill", s: "senate-bill", hjres: "house-joint-resolution", sjres: "senate-joint-resolution",
      hconres: "house-concurrent-resolution", sconres: "senate-concurrent-resolution", hres: "house-resolution", sres: "senate-resolution" }[t];
    return {
      src: `https://www.congress.gov/bill/${sitting}th-congress/${typeWord}/${num}`,
      ch: chamberOf(b.originChamber),
      in: day(b.introducedDate),
      sp: [
        ...(b.sponsors || []).map((p) => person(p, "sponsor")),
        ...cos.filter((p) => !p.sponsorshipWithdrawnDate).map((p) => person(p, "cosponsor")),
      ],
      a: pickActions(acts, billStage),
    };
  }

  async function amendment(sitting, number) {
    const [pre, num] = number.split(" ");
    const t = AMDT_TYPES[pre];
    const base = `amendment/${sitting}/${t}/${num}`;
    const am = ((await getJson(base, base, "")) || {}).amendment;
    if (!am) return null;
    // An amendment's co-sponsor list is optional on Congress.gov (a 404 reads
    // as none). The CLI has always read any other failure as none too; the
    // scheduled job (strict) fails the pass instead.
    const cosRead = all(`${base}/cosponsors`, "cosponsors");
    const cos = strict ? await cosRead : await cosRead.catch(() => []);
    const acts = await all(`${base}/actions`, "actions");
    const ch = chamberOf(am.chamber);
    const a = pickActions(acts, amendmentStage).map((x) => ({ ...x, c: ch }));
    const when = day(am.submittedDate || am.proposedDate || (acts[acts.length - 1] || {}).actionDate);
    return {
      src: `https://www.congress.gov/amendment/${sitting}th-congress/${t === "hamdt" ? "house-amendment" : "senate-amendment"}/${num}`,
      ch,
      in: when,
      sp: [
        ...(am.sponsors || []).map((p) => person(p, "sponsor")),
        ...cos.filter((p) => !p.sponsorshipWithdrawnDate).map((p) => person(p, "cosponsor")),
      ],
      // Same-day steps in the order they happen: offered, then decided.
      a: a.map((x, i) => ({ x, i })).sort((p, q) => p.x.d.localeCompare(q.x.d) || (p.x.s === "offered" ? -1 : 0) - (q.x.s === "offered" ? -1 : 0) || p.i - q.i).map((o) => o.x),
    };
  }

  async function nomination(sitting, number) {
    const pn = NOMINATION_PN[number];
    if (!pn) return null;
    const base = `nomination/${sitting}/${pn}`;
    const n = ((await getJson(base, base, "")) || {}).nomination;
    if (!n) return null;
    const acts = await all(`${base}/actions`, "actions");
    const [num, part] = pn.split("-");
    return {
      src: `https://www.congress.gov/nomination/${sitting}th-congress/${num}${part ? "/" + part : ""}`,
      ch: "senate",
      in: day(n.receivedDate),
      sp: [],
      a: pickActions(acts, nominationStage),
    };
  }

  // One target → its entry, or null when the record has none.
  return async function one(t) {
    if (t.type === "nomination" || NOMINATION_PN[t.number]) return nomination(t.sitting, t.number);
    const pre = String(t.number).split(" ")[0];
    if (AMDT_TYPES[pre]) return amendment(t.sitting, t.number);
    if (FED_TYPES[pre]) return bill(t.sitting, t.number);
    return null;
  };
}
