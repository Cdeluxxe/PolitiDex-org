#!/usr/bin/env node
// gen-related-issue-keys.mjs — writes netlify/lib/related-issue-keys.mjs: the
// issue keys of the related-issues map (MAP in related-issues.js), so the
// raw-ingest suggestions log can flag scorer keys the map does not cover yet.
// A function cannot read related-issues.js at runtime, hence the generated copy;
// scripts/test-raw-ingest-suggestions.mjs fails when the two drift.
// Run: node scripts/gen-related-issue-keys.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function relatedIssueKeysFromSource(src) {
  const m = String(src).match(/var MAP = \{([\s\S]*?)\n  \};/);
  if (!m) throw new Error("related-issues.js: MAP not found");
  const keys = new Set();
  for (const line of m[1].matchAll(/^\s*([a-z0-9_]+):\s*\[([^\]]*)\]/gm)) {
    keys.add(line[1]);
    for (const k of line[2].matchAll(/'([a-z0-9_]+)'/g)) keys.add(k[1]);
  }
  return [...keys].sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const keys = relatedIssueKeysFromSource(readFileSync(path.join(root, "related-issues.js"), "utf8"));
  const out = `// @generated by scripts/gen-related-issue-keys.mjs — do not edit by hand; rerun it after related-issues.js's MAP changes.\n// Every issue key the related-issues map names (as a key or as a related key).\nexport const RELATED_ISSUE_KEYS = ${JSON.stringify(keys, null, 0).replace(/","/g, '", "')};\n`;
  writeFileSync(path.join(root, "netlify/lib/related-issue-keys.mjs"), out);
  console.log(`related-issue-keys: ${keys.length} key(s)`);
}
