#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-aipac-tracker.mjs — AIPAC Tracker's own pages and figures, per roster person
// ─────────────────────────────────────────────────────────────────────────────
// Writes the AIPAC_TRACKER block inside pdx-aipac.js between its BEGIN/END
// markers. Nothing is typed by hand: every slug and figure is read from AIPAC
// Tracker's (trackaipac.com) own published listing.
//
//   node scripts/gen-aipac-tracker.mjs \
//     --listing <saved https://www.trackaipac.com/tracker?role=everyone> \
//     [--pages <dir of saved /tracker/people/<slug> pages, named <slug>.html>] \
//     --as-of YYYY-MM-DD [--check]
//
// WHAT IS READ. Each person card on the listing: the tracker's own page slug,
// the person's name, the office line, and the figure the tracker prints under
// "Israel Lobby Total" (or "Lobby Total"). A card with no figure is kept with a
// null amount: the tracker has a page for the person but shows no total.
//
// HOW A CARD MEETS A ROSTER ROW (cmp-data.js). Conservative on purpose — a card
// that cannot be placed is left out, and that profile reads "No data on AIPAC
// Tracker", which is true of what this site can show.
//   House member    same district code (e.g. NC-12) and same surname.
//   Senator         same state, a Senate office, and the same full name — or,
//                   failing that, the same surname on a non-candidate row.
//   Anyone else     same first and last name, AND a state named on the card or
//                   on the person's own tracker page (--pages) that matches the
//                   roster row's state. No state, no match.
// A roster pid takes a sitting-member card over a candidate card.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BEGIN = "  // BEGIN AIPAC_TRACKER (generated by scripts/gen-aipac-tracker.mjs — do not edit by hand)\n";
const END = "  // END AIPAC_TRACKER\n";

const args = process.argv.slice(2);
const one = (flag) => { const i = args.indexOf(flag); return i >= 0 ? args[i + 1] : null; };
const listing = one("--listing");
const pages = one("--pages");
const asOf = one("--as-of");
const check = args.includes("--check");
if (!listing || !/^\d{4}-\d{2}-\d{2}$/.test(asOf || "")) {
  console.error("usage: --listing <html> [--pages <dir>] --as-of YYYY-MM-DD [--check]");
  process.exit(2);
}

const ST = { Alabama: "AL", Alaska: "AK", Arizona: "AZ", Arkansas: "AR", California: "CA", Colorado: "CO", Connecticut: "CT", Delaware: "DE", Florida: "FL", Georgia: "GA", Hawaii: "HI", Idaho: "ID", Illinois: "IL", Indiana: "IN", Iowa: "IA", Kansas: "KS", Kentucky: "KY", Louisiana: "LA", Maine: "ME", Maryland: "MD", Massachusetts: "MA", Michigan: "MI", Minnesota: "MN", Mississippi: "MS", Missouri: "MO", Montana: "MT", Nebraska: "NE", Nevada: "NV", "New Hampshire": "NH", "New Jersey": "NJ", "New Mexico": "NM", "New York": "NY", "North Carolina": "NC", "North Dakota": "ND", Ohio: "OH", Oklahoma: "OK", Oregon: "OR", Pennsylvania: "PA", "Rhode Island": "RI", "South Carolina": "SC", "South Dakota": "SD", Tennessee: "TN", Texas: "TX", Utah: "UT", Vermont: "VT", Virginia: "VA", Washington: "WA", "West Virginia": "WV", Wisconsin: "WI", Wyoming: "WY" };
const unesc = (s) => String(s || "").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&#39;|&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">");
const norm = (s) => String(s || "").normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[-.]/g, " ").replace(/[^a-z ]/g, "");
const SUF = new Set(["jr", "sr", "ii", "iii", "iv"]);
const toks = (n) => norm(n).split(/\s+/).filter((t) => t.length > 1 && !SUF.has(t));
const surnameMatch = (a, b) => {
  const ta = toks(a), tb = toks(b);
  if (!ta.length || !tb.length) return false;
  const la = ta[ta.length - 1], lb = tb[tb.length - 1];
  return la === lb || tb.includes(la) || ta.includes(lb);
};
const fullMatch = (a, b) => {
  const ta = toks(a), tb = toks(b);
  return ta.length > 0 && tb.length > 0 && ta[0] === tb[0] && ta[ta.length - 1] === tb[tb.length - 1];
};
const statesIn = (text) => {
  const out = new Set();
  for (const [name, code] of Object.entries(ST)) {
    const re = name === "Virginia" ? /(?<!West )\bVirginia\b/ : name === "Washington" ? /\bWashington\b(?!, D)/ : new RegExp("\\b" + name + "\\b");
    if (re.test(text)) out.add(code);
  }
  return out;
};

// ── roster ─────────────────────────────────────────────────────────────────
const roster = (() => {
  const w = {}; w.window = w;
  vm.runInNewContext(readFileSync(join(ROOT, "cmp-data.js"), "utf8"), w, { filename: "cmp-data.js" });
  const out = {};
  for (const [k, v] of Object.entries(w.CMP_DATA || {})) {
    out[k] = { name: v.name || "", office: v.office || "", state: v.state || "", district: v.district || "" };
  }
  return out;
})();
const rState = (r) => {
  const s = r.state.split(" · ")[0].trim();
  if (ST[s]) return ST[s];
  const m = /\b([A-Z]{2})-/.exec(r.district + " " + r.state);
  return m ? m[1] : null;
};
const distCode = (st, d) => st + "-" + (/^(AL|0|00)$/.test(d) ? "AL" : String(parseInt(d, 10)).padStart(2, "0"));
const rDist = (r) => {
  const t = r.district + " " + r.state;
  let m = /\b([A-Z]{2})-(\d+|AL)\b/.exec(t);
  if (m) return distCode(m[1], m[2]);
  const st = rState(r);
  m = /District (\d+)/.exec(t);
  if (m && st) return distCode(st, m[1]);
  if (/At[- ]Large/.test(t) && st) return st + "-AL";
  return null;
};
const federal = (r) => !/\bState\b|Assembly|Mayor|Council|County|Commission|Legislat/.test(r.office);

// ── the tracker's cards ───────────────────────────────────────────────────
const html = readFileSync(listing, "utf8");
const cards = html.split('<li id="person-').slice(1).map((c) => {
  const slug = c.slice(0, c.indexOf('"'));
  const nm = /aria-label="([^"]*?)(?:, ([A-Za-z ]+))?" class="text-inherit/.exec(c);
  const off = /<p class="mt-2[^>]*>([\s\S]*?)<\/p>/.exec(c);
  const dd = /<dt[^>]*>(?:Israel )?Lobby Total<\/dt><dd[^>]*>([\s\S]*?)<\/dd>/.exec(c);
  const fig = dd ? unesc(dd[1]).trim() : "";
  return {
    slug,
    name: nm ? unesc(nm[1]) : "",
    office: off ? unesc(off[1].replace(/<[^>]+>/g, "")) : "",
    amount: /^\$[\d,]+(\.\d+)?$/.test(fig) ? Math.round(Number(fig.slice(1).replace(/,/g, ""))) : null,
  };
}).filter((c) => /^[a-z0-9-]+$/.test(c.slug) && c.name);
if (cards.length < 100) { console.error(`only ${cards.length} cards on the listing — wrong file?`); process.exit(1); }

const res = new Map();
const misses = [];
for (const c of cards) {
  let cand = [];
  const house = /U\.S\. House Representative for ([A-Z]{2})-(\d+|AL)/.exec(c.office);
  if (house) {
    const d = distCode(house[1], house[2]);
    cand = Object.keys(roster).filter((p) => federal(roster[p]) && rDist(roster[p]) === d && surnameMatch(roster[p].name, c.name));
    if (!cand.length) cand = Object.keys(roster).filter((p) => federal(roster[p]) && rState(roster[p]) === d.slice(0, 2) && !/Senat/.test(roster[p].office) && fullMatch(roster[p].name, c.name));
  } else if (/^Current U\.S\. Senator for /.test(c.office)) {
    const st = ST[c.office.split(" for ")[1].trim()];
    const pool = Object.keys(roster).filter((p) => /Senat/.test(roster[p].office) && federal(roster[p]) && rState(roster[p]) === st);
    cand = pool.filter((p) => fullMatch(roster[p].name, c.name));
    if (!cand.length) cand = pool.filter((p) => !/Candidate/.test(roster[p].office) && surnameMatch(roster[p].name, c.name));
  } else {
    let text = c.office;
    const f = pages && join(pages, c.slug + ".html");
    if (f && existsSync(f)) {
      const s = readFileSync(f, "utf8");
      const m = /<main[\s\S]*?<\/main>/.exec(s);
      text += " " + unesc((m ? m[0] : "").replace(/<[^>]+>/g, " "));
    }
    const sts = statesIn(text);
    cand = sts.size ? Object.keys(roster).filter((p) => fullMatch(roster[p].name, c.name) && sts.has(rState(roster[p]))) : [];
  }
  if (!cand.length) { misses.push(c.slug); continue; }
  for (const p of cand) {
    const cur = res.get(p);
    if (cur && cur.slug.startsWith("member-") && !c.slug.startsWith("member-")) continue;
    res.set(p, c);
  }
}

const rows = [...res].sort(([a], [b]) => (a < b ? -1 : 1));
const n = { pos: 0, zero: 0, none: 0 };
for (const [, c] of rows) n[c.amount == null ? "none" : c.amount > 0 ? "pos" : "zero"]++;
let block = BEGIN +
  "  // Per roster person: [the AIPAC Tracker page slug, the dollar figure the\n" +
  "  // tracker prints as its Israel Lobby Total, or null when its page shows none].\n" +
  "  // Read from trackaipac.com/tracker on TRACKER_AS_OF; these are the tracker's\n" +
  "  // figures, not this site's, and the chip says so.\n" +
  `  // ${rows.length} people: ${n.pos} with a figure above zero, ${n.zero} at $0, ${n.none} with no figure.\n` +
  `  var TRACKER_AS_OF = '${asOf}';\n` +
  "  var AIPAC_TRACKER = {\n" +
  rows.map(([p, c]) => `    ${p}: ['${c.slug}', ${c.amount == null ? "null" : c.amount}]`).join(",\n") +
  "\n  };\n" + END;

const path = join(ROOT, "pdx-aipac.js");
const src = readFileSync(path, "utf8");
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a < 0 || b < a) { console.error("pdx-aipac.js has no AIPAC_TRACKER markers"); process.exit(1); }
const next = src.slice(0, a) + block + src.slice(b + END.length);
console.error(`${cards.length} cards, ${rows.length} roster people placed, ${misses.length} cards not placed`);
if (check) { if (next !== src) { console.error("AIPAC_TRACKER block is stale"); process.exit(1); } }
else writeFileSync(path, next);
