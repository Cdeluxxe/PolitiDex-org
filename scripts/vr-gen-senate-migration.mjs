// ─────────────────────────────────────────────────────────────────────────────
// vr-gen-senate-migration.mjs — generate the deploy-time Senate seed migration
// ─────────────────────────────────────────────────────────────────────────────
// The Senate source layer (netlify/lib/vr-senate-source.ts) serves the curated seed
// through the RUNTIME ingest path (POST /api/vr-ingest {chamber:"senate"} and the
// daily cron). This script emits the equivalent DEPLOY-TIME migration so the same
// real votes are present the moment the branch database is provisioned — no manual
// ingest call needed — exactly how the House seed migrations work.
//
// It reads the SAME single source of truth the runtime path reads (db/vr-senate-
// seed.json) plus the curated issue map (db/vr-issue-seed.json) and the member map,
// computes party-crossover flags from the FULL chamber tally (so a subset never
// mislabels with/against party), filters member votes to the mapped roster, and
// prints an idempotent SQL migration to stdout. Regenerate after editing the seed:
//
//   node scripts/vr-gen-senate-migration.mjs > \
//     netlify/database/migrations/20260724120000_seed_senate_voting_record.sql
//
// The migration is additive + re-runnable: measures are find-or-create by natural
// key, roll calls use ON CONFLICT (chamber,congress,session,roll_number) DO NOTHING,
// member votes ON CONFLICT (rollcall_id,politician_id) DO NOTHING, and issue mappings
// ON CONFLICT (measure_id,issue_key) DO NOTHING — so it never clobbers a curated row.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const seed = JSON.parse(readFileSync(resolve(REPO, "db/vr-senate-seed.json"), "utf8"));
const issueSeed = JSON.parse(readFileSync(resolve(REPO, "db/vr-issue-seed.json"), "utf8"));
const memberMap = JSON.parse(readFileSync(resolve(REPO, "db/vr-member-map.json"), "utf8"));
const MAP = memberMap.map || {};

// SQL string literal (single-quote escaped).
const q = (s) => "'" + String(s == null ? "" : s).replace(/'/g, "''") + "'";
const qOrNull = (s) => (s == null ? "NULL" : q(s));

// Party-crossover flag from the majority position within each party — identical logic
// to crossoverFlags() in vr-normalize.ts, run over the FULL member list.
function crossover(memberVotes) {
  const byParty = {};
  for (const m of memberVotes) {
    if (!m.party || (m.position !== "yea" && m.position !== "nay")) continue;
    (byParty[m.party] = byParty[m.party] || {})[m.position] = (byParty[m.party]?.[m.position] || 0) + 1;
  }
  const majority = {};
  for (const p of Object.keys(byParty)) majority[p] = (byParty[p].yea || 0) >= (byParty[p].nay || 0) ? "yea" : "nay";
  const flag = (m) => {
    if (!m.party || (m.position !== "yea" && m.position !== "nay") || !majority[m.party]) return null;
    return m.position === majority[m.party] ? "with_party" : "against_party";
  };
  return flag;
}

// Match a seed measure to its curated issue-seed entry (same natural-key + canonical
// number rule applyCuratedIssueSeed uses). Light canonicalization is enough here since
// the seed already stores canonical numbers.
function issuesFor(measure) {
  const entry = (issueSeed.measures || []).find(
    (e) => e.measureType === measure.measureType && e.congress === measure.congress &&
      e.chamber === measure.chamber && e.number === measure.number
  );
  return entry ? entry.issues || [] : [];
}

// A stable SQL identifier for each measure's DECLARE variable.
const varName = (m) => "m_" + m.number.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
const statusFor = (m, v) => {
  if (m.number === "H.R. 1") return "enacted";
  if (m.measureType === "amendment") return v.result === "passed" || v.result === "agreed_to" ? "passed_senate" : "failed";
  if (m.measureType === "resolution") return v.result === "passed" || v.result === "agreed_to" ? "passed_senate" : "failed";
  return v.result === "passed" ? "passed_senate" : "failed";
};

const votes = seed.votes || [];
const measures = [];
const seenM = new Set();
for (const v of votes) {
  const key = varName(v.measure);
  if (!seenM.has(key)) { seenM.add(key); measures.push({ v, m: v.measure, var: key }); }
}

const L = [];
L.push("-- ─────────────────────────────────────────────────────────────────────────────");
L.push("-- Voting Record — Senate seed (data-only) · Phase 13B scaffold");
L.push("-- ─────────────────────────────────────────────────────────────────────────────");
L.push("-- GENERATED by scripts/vr-gen-senate-migration.mjs from db/vr-senate-seed.json —");
L.push("-- do not hand-edit; regenerate from the seed. Every roll call, position, and total");
L.push("-- traces to an official senate.gov roll-call XML document (source_url below); no");
L.push("-- vote is invented. This is the deploy-time twin of the runtime Senate ingest path");
L.push("-- (netlify/lib/vr-senate-source.ts): both load the same curated seed idempotently.");
L.push("--");
L.push("-- The Congress.gov API has no Senate roll-call resource, so the Senate side is");
L.push("-- seeded here until the automated senate.gov XML ingest (VR_SENATE_XML) lands.");
L.push("-- Changes NO schema. Additive + idempotent; rolls forward, never edits a prior");
L.push("-- migration. Attaches a Senate roll call to the existing House-originated H.R. 1");
L.push("-- measure (one measure, votes in both chambers).");
L.push("DO $$");
L.push("DECLARE");
for (const mm of measures) L.push(`  ${mm.var} integer;`);
L.push("  rc integer;");
L.push("BEGIN");

// Measures: find-or-create by natural key.
for (const mm of measures) {
  const m = mm.m;
  const chamberCond = m.chamber ? `chamber = ${q(m.chamber)}` : "chamber IS NULL";
  const numCond = m.number ? `number = ${q(m.number)}` : "number IS NULL";
  L.push("");
  L.push(`  -- ${m.number} — ${m.title}`);
  L.push(`  SELECT id INTO ${mm.var} FROM vr_measures WHERE measure_type = ${q(m.measureType)} AND congress = ${m.congress} AND ${chamberCond} AND ${numCond} LIMIT 1;`);
  L.push(`  IF ${mm.var} IS NULL THEN`);
  L.push(`    INSERT INTO vr_measures (measure_type, congress, chamber, number, title, source_url, source_label, status)`);
  L.push(`    VALUES (${q(m.measureType)}, ${m.congress}, ${qOrNull(m.chamber)}, ${qOrNull(m.number)}, ${q(m.title)}, ${q(m.sourceUrl)}, ${q(m.sourceLabel || "Congress.gov")}, ${q(statusFor(m, mm.v))})`);
  L.push(`    RETURNING id INTO ${mm.var};`);
  L.push(`  END IF;`);
}

// Roll calls + member votes.
for (const v of votes) {
  const mv = measures.find((x) => x.var === varName(v.measure)).var;
  const flag = crossover(v.memberVotes);
  const mapped = v.memberVotes
    .filter((m) => m.bioguideId && MAP[m.bioguideId])
    .map((m) => ({ pid: MAP[m.bioguideId], position: m.position, isParty: flag(m) }));
  const totals = JSON.stringify(v.totals || {});
  L.push("");
  L.push(`  -- Senate roll call ${v.rollNumber} (${v.result}) — ${v.measure.number}`);
  L.push(`  INSERT INTO vr_rollcalls (measure_id, chamber, congress, session, roll_number, vote_date, question, action_type, result, required_majority, totals, source_url, source_label)`);
  L.push(`  VALUES (${mv}, 'senate', ${v.congress}, ${v.session}, ${v.rollNumber}, TIMESTAMPTZ ${q(v.voteDate)}, ${qOrNull(v.question)}, ${q(v.actionType)}, ${qOrNull(v.result)}, ${q(v.requiredMajority || "simple")}, ${q(totals)}::jsonb, ${q(v.sourceUrl)}, ${q(v.sourceLabel || "U.S. Senate")})`);
  L.push(`  ON CONFLICT (chamber, congress, session, roll_number) DO NOTHING;`);
  L.push(`  SELECT id INTO rc FROM vr_rollcalls WHERE chamber = 'senate' AND congress = ${v.congress} AND session = ${v.session} AND roll_number = ${v.rollNumber} LIMIT 1;`);
  const rows = mapped.map((r) => `    (rc, ${q(r.pid)}, ${q(r.position)}, ${r.isParty ? q(r.isParty) : "NULL"})`);
  L.push(`  INSERT INTO vr_member_votes (rollcall_id, politician_id, position, is_party) VALUES`);
  L.push(rows.join(",\n"));
  L.push(`  ON CONFLICT (rollcall_id, politician_id) DO NOTHING;`);
}

// Curated issue mappings for the seeded measures (idempotent; never clobbers a
// curated row — existing H.R. 1 mappings are left as-is).
L.push("");
L.push("  -- Curated measure→issue mappings (additive; existing rows untouched)");
for (const mm of measures) {
  const issues = issuesFor(mm.m);
  for (const iss of issues) {
    const support = iss.supportMeaning === "yea_opposes" ? "yea_opposes" : "yea_supports";
    L.push(`  INSERT INTO vr_measure_issues (measure_id, issue_key, weight, is_primary, support_meaning, rationale, source_url)`);
    L.push(`  VALUES (${mm.var}, ${q(iss.issueKey)}, ${iss.weight ?? 100}, ${!!iss.isPrimary}, ${q(support)}, ${q(iss.rationale || "")}, ${qOrNull(iss.sourceUrl || mm.m.sourceUrl)})`);
    L.push(`  ON CONFLICT (measure_id, issue_key) DO NOTHING;`);
  }
}

L.push("END $$;");
L.push("");
process.stdout.write(L.join("\n"));
