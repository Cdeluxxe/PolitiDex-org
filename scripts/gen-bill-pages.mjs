#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-bill-pages.mjs — which federal measures have a bill page, for the client
// ─────────────────────────────────────────────────────────────────────────────
// WHAT THIS WRITES
//
//   bill-pages.js   window.PDX_BILL_PAGES, one key per FEDERAL /b/ address the
//                   sitemap already publishes: "<congress>/<number>", the number
//                   spelled exactly as the row prints it ("119/H.R. 6644").
//
// WHY IT EXISTS
//
// On a person file the bill panel is not loaded, so the issue drawer prints a
// federal measure's number as an outbound Congress.gov link and nothing else.
// The bill's own page at /b/<congress>/<number> exists for 200 of those
// measures, and nothing on the page knew which 200. A door built from any
// number the drawer holds would point at measures that have no page, so the
// drawer needs the list, and the list is this file.
//
// THE SAME SET AS THE SITEMAP, NOT A SECOND RULE. The rows come from
// measureAddresses() in vr-measure-addresses.mjs, the function gen-sitemap.mjs
// lists bills from, filtered to a numeric sitting (a congress). A Utah bill has
// no Congress.gov door to sit beside, so it is not here. No address is minted:
// scripts/test-internal-hops.mjs holds every key here to a /b/ line already in
// sitemap.xml.
//
// USAGE
//   node scripts/gen-bill-pages.mjs           # write bill-pages.js
//   node scripts/gen-bill-pages.mjs --check   # exit 1 if it is stale
// ─────────────────────────────────────────────────────────────────────────────
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { measureAddresses } from "./vr-measure-addresses.mjs";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "bill-pages.js");
const CHECK = process.argv.includes("--check");

export function federalBillPages(root) {
  return measureAddresses(root || ROOT).published
    .filter((a) => /^\d{2,3}$/.test(String(a.sitting)))
    .map((a) => `${a.sitting}/${a.number}`);
}

function render(keys) {
  const rows = keys.map((k) => `  ${JSON.stringify(k)}: 1`).join(",\n");
  return `// GENERATED by scripts/gen-bill-pages.mjs — do not edit by hand.
// The federal measures that have a bill page at /b/<congress>/<number>: the
// same set sitemap.xml lists, keyed "<congress>/<number>". Read by consistency.js
// on a page without the bill panel, to put an in-site door beside the
// Congress.gov one. A measure not keyed here gets no in-site door.
window.PDX_BILL_PAGES = {
${rows}
};
`;
}

if (import.meta.url === url.pathToFileURL(process.argv[1]).href) {
  const out = render(federalBillPages(ROOT));
  if (CHECK) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (cur !== out) {
      console.error("✗ bill-pages.js is stale — run node scripts/gen-bill-pages.mjs");
      process.exit(1);
    }
    console.log("✓ bill-pages.js is current");
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`wrote bill-pages.js (${federalBillPages(ROOT).length} federal bill pages)`);
  }
}
