#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-aipac-pac.mjs — AIPAC PAC's own reported contributions, per roster person
// ─────────────────────────────────────────────────────────────────────────────
// Writes the AIPAC_PAC block inside pdx-aipac.js between its BEGIN/END markers.
// Nothing is typed by hand: every figure is summed from FEC's own bulk file of
// committee-to-candidate contributions.
//
//   node scripts/gen-aipac-pac.mjs \
//     --pas2 <2024 itpas2.txt> --pas2 <2026 itpas2.txt> \
//     --legislators <legislators-current.json> --legislators <legislators-historical.json> \
//     [--check]
//
// Inputs, all public:
//   itpas2.txt      fec.gov/files/bulk-downloads/<year>/pas2<yy>.zip — "Contributions
//                   from committees to candidates & independent expenditures"
//   legislators     unitedstates.github.io/congress-legislators — bioguide → FEC ids
// The roster side (pid → bioguide) is read from this repo: cmp-data.js portrait
// URLs and the bioguideId/politicianId pairs in the db/ vote seeds.
//
// WHAT COUNTS. Rows filed by one of COMMITTEES below, transaction type 24K
// (contribution to a candidate committee), not memo entries, and NOT earmarks:
// a memo naming an EARMARK / ERMK is an individual's donation the PAC passed
// along as a conduit (or the void of one), which is that person's money, not
// the PAC's. What remains is the PAC's own contributions and its own refunds.
// They are netted per person AND PER COMMITTEE across the two cycles the chip
// treats as current (2024, 2026); a committee is on a person's file only when
// its own net is above zero, so money refunded in full is not on file.
//
// THE COMMITTEES. AIPAC PAC, NORPAC and Pro-Israel America PAC — the three
// regular (contributing) pro-Israel PACs named for this lane. IDs are the
// FEC's own, looked up by name: NORPAC is C00247403 and Pro-Israel America
// PAC is C00699470 (the ids first proposed, C00145340 and C00676082, are not
// FEC committees and appear in no FEC file). Pro-Israel America PAC files no
// committee-to-candidate rows in either cycle, so it adds no one; it stays
// listed so a later filing is picked up. United Democracy Project is not
// here: it is a super PAC, and every row it files is an independent
// expenditure (24E / 24A), never a contribution.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => readFileSync(join(ROOT, f), "utf8");
const COMMITTEES = {
  C00797670: "aipac",      // American Israel Public Affairs Committee PAC
  C00247403: "norpac",     // NORPAC
  C00699470: "proisrael",  // Pro-Israel America PAC
};
const CYCLES = ["2024", "2026"];
const BEGIN = "  // BEGIN AIPAC_PAC (generated by scripts/gen-aipac-pac.mjs — do not edit by hand)\n";
const END = "  // END AIPAC_PAC\n";

const args = process.argv.slice(2);
const many = (flag) => args.flatMap((a, i) => (a === flag ? [args[i + 1]] : []));
const pas2 = many("--pas2");
const legs = many("--legislators");
const check = args.includes("--check");
if (pas2.length !== CYCLES.length || !legs.length) {
  console.error("usage: --pas2 <2024 itpas2.txt> --pas2 <2026 itpas2.txt> --legislators <json> [...] [--check]");
  process.exit(2);
}

// ── roster: pid → bioguide ──────────────────────────────────────────────────
const pidBg = new Map();
const addPair = (pid, bg) => {
  const had = pidBg.get(pid);
  if (had && had !== bg) throw new Error(`${pid} maps to two bioguide ids: ${had}, ${bg}`);
  pidBg.set(pid, bg);
};
{
  const src = R("cmp-data.js");
  const heads = [...src.matchAll(/\n\s*"([a-z0-9_]+)":\s*\{/g)];
  heads.forEach((m, i) => {
    const block = src.slice(m.index, i + 1 < heads.length ? heads[i + 1].index : src.length);
    const ph = /congress\/450x550\/([A-Z]\d{6})\.jpg/.exec(block);
    if (ph) addPair(m[1], ph[1]);
  });
  for (const f of readdirSafe(join(ROOT, "db"))) {
    if (!f.endsWith(".json")) continue;
    const s = R("db/" + f);
    for (const m of s.matchAll(/"bioguideId":\s*"([A-Z]\d{6})",\s*"politicianId":\s*"([a-z0-9_]+)"/g)) addPair(m[2], m[1]);
  }
}
function readdirSafe(d) { try { return readdirSync(d); } catch (e) { return []; } }

// ── bioguide → FEC candidate ids ────────────────────────────────────────────
const fecPid = new Map();
const bgPid = new Map([...pidBg].map(([p, b]) => [b, p]));
for (const f of legs) {
  for (const L of JSON.parse(readFileSync(f, "utf8"))) {
    const pid = bgPid.get(L.id && L.id.bioguide);
    if (!pid) continue;
    for (const c of L.id.fec || []) fecPid.set(c, pid);
  }
}

// ── each committee's own 24K rows, netted per person per committee ──────────
const people = new Map();
const sum = (o) => Object.values(o).reduce((a, b) => a + b, 0);
pas2.forEach((file, i) => {
  const cycle = CYCLES[i];
  for (const line of readFileSync(file, "latin1").split("\n")) {
    const f = line.split("|");
    const key = COMMITTEES[f[0]];
    if (!key || f[5] !== "24K" || f[19] === "X") continue;
    if (/EARMARK|ERMK/i.test(f[20] || "")) continue;
    const pid = fecPid.get(f[16]);
    if (!pid) continue;
    const p = people.get(pid) || { fec: f[16], pacs: {} };
    const c = (p.pacs[key] ||= {});
    c[cycle] = Math.round(((c[cycle] || 0) + Number(f[14] || 0)) * 100) / 100;
    people.set(pid, p);
  }
});
// Drop every committee whose net is not above zero, then every person left with none.
for (const p of people.values()) for (const k of Object.keys(p.pacs)) if (!(sum(p.pacs[k]) > 0)) delete p.pacs[k];
const onFile = [...people].filter(([, p]) => Object.keys(p.pacs).length)
  .sort(([a], [b]) => (a < b ? -1 : 1));
const byPac = Object.fromEntries(Object.values(COMMITTEES).map((k) => [k, onFile.filter(([, p]) => p.pacs[k]).length]));

// ── the block ───────────────────────────────────────────────────────────────
let block = BEGIN +
  "  // Per roster person: the FEC candidate id the contributions were filed\n" +
  "  // against, and each committee's net direct contributions per cycle, as\n" +
  "  // reported — aipac: AIPAC PAC, norpac: NORPAC, proisrael: Pro-Israel America PAC.\n" +
  "  // Held for provenance and for the on-file test only; the chip prints none of it.\n" +
  `  // ${onFile.length} people with a net above zero across ${CYCLES.join(" + ")} ` +
  `(${Object.entries(byPac).map(([k, n]) => `${k} ${n}`).join(", ")}).\n` +
  "  var AIPAC_PAC = {\n";
const cyc = (o) => `{ ${CYCLES.filter((c) => c in o).map((c) => `'${c}': ${o[c]}`).join(", ")} }`;
block += onFile.map(([pid, p]) =>
  `    ${pid}: { fec: '${p.fec}', ${Object.values(COMMITTEES).filter((k) => p.pacs[k]).map((k) => `${k}: ${cyc(p.pacs[k])}`).join(", ")} }`
).join(",\n") + "\n  };\n" + END;

const path = join(ROOT, "pdx-aipac.js");
const src = readFileSync(path, "utf8");
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a < 0 || b < a) { console.error("pdx-aipac.js has no AIPAC_PAC markers"); process.exit(1); }
const next = src.slice(0, a) + block + src.slice(b + END.length);
if (check) {
  if (next !== src) { console.error("✗ AIPAC_PAC block is stale"); process.exit(1); }
  console.log(`✓ AIPAC_PAC block is current (${onFile.length} people)`);
} else {
  writeFileSync(path, next);
  console.log(`wrote AIPAC_PAC: ${onFile.length} people (${JSON.stringify(byPac)}), ${people.size - onFile.length} netted to zero or below`);
}
