// Federal wave F6 — migration generator
// ════════════════════════════════════════════════════════════════════════════
//
// Reads db/vr-federal-mapping-seed-f6.json (the decisions) and
// db/vr-federal-wave-f6-vote-seed.json (the chamber record) and emits
// netlify/database/migrations/20261022000000_vr_federal_wave_f6.sql.
//
// The seeds are the source of truth. Nothing here re-decides anything, and no
// number in the SQL is typed by hand: tallies, dates, questions, source URLs and
// every member position come out of the vote seed, which came out of the clerk's
// own XML. Regenerate rather than hand-editing the SQL.
//
// The verification block at the end is deliberately scoped to THIS WAVE'S ROLLS.
// A session-wide committee or corpus total would fail the next time any other
// wave lands, and a guard that fails for reasons unrelated to the change it
// guards gets deleted by whoever is unlucky enough to hit it. So every count
// below is taken over the eleven roll calls and eleven measures named here.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEED = JSON.parse(readFileSync(join(ROOT, "db", "vr-federal-mapping-seed-f6.json"), "utf8"));
const VOTES = JSON.parse(readFileSync(join(ROOT, "db", "vr-federal-wave-f6-vote-seed.json"), "utf8"));

const q = (s) => s === null || s === undefined ? "NULL" : `'${String(s).replace(/'/g, "''")}'`;
const varName = (num) => "m_" + num.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
const wrap = (text, width, lead) => {
  const out = [];
  for (const para of String(text).split("\n")) {
    let line = "";
    for (const word of para.split(/\s+/).filter(Boolean)) {
      if (line && (line + " " + word).length > width) { out.push(lead + line); line = word; }
      else line = line ? line + " " + word : word;
    }
    out.push(lead + line);
  }
  return out.join("\n");
};

const rollOf = (num) => {
  const r = VOTES.votes.find((x) => x.measure.number === num);
  if (!r) throw new Error(`vote seed has no roll for ${num}`);
  return r;
};
// The seed already carries an ISO timestamp with the Eastern offset in force on the
// day of the vote, so the calendar date is a slice rather than a parse. It is still
// asserted: vr_rollcalls.vote_date is a DATE, and handing Postgres anything the
// builder had not already validated would let a display string through to be parsed
// by locale luck.
const isoDate = (s) => {
  const m = /^(\d{4}-\d{2}-\d{2})T/.exec(String(s));
  if (!m) throw new Error(`vote seed carries a non-ISO voteDate '${s}'`);
  return m[1];
};
// The measured read effect, quoted from the seed rather than restated, so the SQL
// header and the decision record cannot disagree about what this wave cost.
const ME = SEED.readDisclosure.measuredEffect;

