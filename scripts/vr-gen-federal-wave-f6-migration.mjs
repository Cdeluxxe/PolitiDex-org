p("  -- smaller set because the roster admits 221 slugs. Recomputing a tally from the rows");
p("  -- would publish a vote that never happened, so the two live in separate places and");
p("  -- the guards at the end assert the tally against the source figure.");
p("  -- Attribution is fail-closed: the clerk's own name-id → db/vr-member-map.json, and");
