// ── verification, scoped to this wave ────────────────────────────────────────
const rollTuples = VOTES.votes.map((r) => `(${r.congress},${r.session},${r.rollNumber})`).join(", ");
const numList = SEED.measures.map((m) => q(m.number)).join(", ");
p("-- ────────────────────────────────────────────────────────────────────────────");
p("-- VERIFICATION — scoped to THIS WAVE'S eleven rolls and eleven measures.");
p("-- Nothing below counts a session-wide or corpus-wide total. A guard that fails");
p("-- because some other wave landed is a guard that gets deleted, so every count here");
p("-- is taken over the named rolls and the named measures only.");
p("-- ────────────────────────────────────────────────────────────────────────────");
p("DO $$");
p("DECLARE");
p("  n_measures integer; n_rolls integer; n_votes integer; n_orphan integer; n_issues integer;");
p("  n_nonprimary integer; n_badpos integer; n_thin integer; n_tally integer; n_hr1069 integer;");
p("  n_keys integer; n_newkeys integer;");
// The eleven roll ids are held in an ARRAY, not a temp table. A data-only migration
// that sorts after the newest drizzle snapshot may not declare an object — a later
// `generate` diffs against that snapshot and would re-emit the DDL it finds newer
// than it — and scripts/test-vr-corrections.mjs enforces exactly that, reading any
// CREATE/DROP of a TABLE as a declaration regardless of how temporary it is. An
// array is a local variable, so there is nothing for a snapshot to have missed. The
// element type is the serial vr_rollcalls.id, integer, so nothing is cast on the way in.
p("  roll_ids integer[];");
p("BEGIN");
p(`  SELECT count(*) INTO n_measures FROM vr_measures`);
p(`   WHERE measure_type = 'bill' AND congress = 119 AND chamber = 'house' AND number IN (${numList});`);
p(`  IF n_measures <> ${SEED.measures.length} THEN`);
p(`    RAISE EXCEPTION 'Federal wave F6: expected ${SEED.measures.length} measures on file, found %', n_measures;`);
p("  END IF;");
p();
p("  SELECT array_agg(id) INTO roll_ids FROM vr_rollcalls WHERE chamber = 'house'");
p(`    AND (congress, session, roll_number) IN (${rollTuples});`);
p("  n_rolls := coalesce(array_length(roll_ids, 1), 0);");
p(`  IF n_rolls <> ${VOTES.votes.length} THEN`);
p(`    RAISE EXCEPTION 'Federal wave F6: expected ${VOTES.votes.length} roll calls, found %', n_rolls;`);
p("  END IF;");
p();
p("  SELECT count(*) INTO n_votes FROM vr_member_votes WHERE rollcall_id = ANY(roll_ids);");
p(`  IF n_votes < ${VOTES._counts.attributedMemberVotes} THEN`);
p(`    RAISE EXCEPTION 'Federal wave F6: expected at least ${VOTES._counts.attributedMemberVotes} member votes on these rolls, found %', n_votes;`);
p("  END IF;");
p();
p("  -- Fail-closed attribution, asserted rather than assumed. A politician_id on one of");
p("  -- these rolls that is not in the roster means the generator guessed at somebody,");
p("  -- which is the one failure mode surname matching would have introduced.");
p("  SELECT count(*) INTO n_orphan FROM vr_member_votes v");
p("   WHERE v.rollcall_id = ANY(roll_ids)");
p(`     AND v.politician_id NOT IN (${[...new Set(VOTES.votes.flatMap((r) => r.memberVotes.map((x) => x.politicianId)))].sort().map(q).join(", ")});`);
p("  IF n_orphan > 0 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: % member vote(s) on these rolls carry a politician_id outside db/vr-member-map.json. Attribution here is fail-closed, so this is a bug, not a roster gap.', n_orphan;");
p("  END IF;");
p();
p("  SELECT count(*) INTO n_badpos FROM vr_member_votes");
p("   WHERE rollcall_id = ANY(roll_ids)");
p("     AND position NOT IN ('yea','nay','present','not_voting');");
p("  IF n_badpos > 0 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: % member vote(s) carry a position outside the closed vocabulary.', n_badpos;");
p("  END IF;");
p();
p("  -- The tally is the chamber's, not the roster's. If these ever match the attributed");
p("  -- row count, somebody recomputed a total from the rows and the site is publishing a");
p("  -- vote that did not happen.");
p("  SELECT count(*) INTO n_tally FROM vr_rollcalls r");
p("   WHERE r.id = ANY(roll_ids)");
p("     AND (r.totals->>'yea')::int + (r.totals->>'nay')::int");
p("         <= (SELECT count(*) FROM vr_member_votes v WHERE v.rollcall_id = r.id);");
p("  IF n_tally > 0 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: % roll(s) have a yea+nay pool no larger than their attributed row count. Totals must be the full chamber, never the roster subset.', n_tally;");
p("  END IF;");
p();
p("  SELECT count(*) INTO n_issues FROM vr_measure_issues");
p(`   WHERE measure_id IN (SELECT id FROM vr_measures WHERE measure_type = 'bill' AND congress = 119 AND chamber = 'house' AND number IN (${numList}));`);
p(`  IF n_issues <> ${SEED._counts.issueRows} THEN`);
p(`    RAISE EXCEPTION 'Federal wave F6: expected exactly ${SEED._counts.issueRows} issue mappings on this wave''s measures, found %. A higher count means somebody added a row to feed coverage; the seed refuses 22 keys on these eleven measures in writing.', n_issues;`);
p("  END IF;");
p();
p("  -- Rule 30's wall, asserted. Every row this wave writes is primary on purpose.");
p("  SELECT count(*) INTO n_nonprimary FROM vr_measure_issues");
p(`   WHERE measure_id IN (SELECT id FROM vr_measures WHERE measure_type = 'bill' AND congress = 119 AND chamber = 'house' AND number IN (${numList}))`);
p("     AND is_primary = false;");
p("  IF n_nonprimary > 0 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: % row(s) on this wave''s measures are non-primary. Rule 30: a fourth non-primary act on a key flips a member from thin-but-one-sided to not-about-this-issue, so this wave supplies only primaries.', n_nonprimary;");
p("  END IF;");
p();
p("  -- No new vocabulary. Every key used here must already appear on a measure outside");
p("  -- this wave, which is the strongest available assertion that nothing was invented.");
p(`  SELECT count(DISTINCT issue_key) INTO n_keys FROM vr_measure_issues`);
p(`   WHERE measure_id IN (SELECT id FROM vr_measures WHERE measure_type = 'bill' AND congress = 119 AND chamber = 'house' AND number IN (${numList}));`);
p(`  IF n_keys <> ${SEED._counts.keysUsed.length} THEN`);
p(`    RAISE EXCEPTION 'Federal wave F6: this wave writes % distinct keys, expected ${SEED._counts.keysUsed.length} (${SEED._counts.keysUsed.join(", ")}).', n_keys;`);
p("  END IF;");
p("  SELECT count(*) INTO n_newkeys FROM (");
p(`    SELECT DISTINCT i.issue_key FROM vr_measure_issues i`);
p(`     WHERE i.measure_id IN (SELECT id FROM vr_measures WHERE measure_type = 'bill' AND congress = 119 AND chamber = 'house' AND number IN (${numList}))`);
p("       AND NOT EXISTS (");
p("         SELECT 1 FROM vr_measure_issues j WHERE j.issue_key = i.issue_key");
p(`          AND j.measure_id NOT IN (SELECT id FROM vr_measures WHERE measure_type = 'bill' AND congress = 119 AND chamber = 'house' AND number IN (${numList})))`);
p("  ) t;");
p("  IF n_newkeys > 0 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: % key(s) exist only on this wave''s measures. This wave adds NO vocabulary — the District of Columbia key it considered is refused in writing under vocab rule 5 — so a key with no prior instrument means one was invented here.', n_newkeys;");
p("  END IF;");
p();
p("  -- The standing refusal, re-asserted where it can actually be checked.");
p("  SELECT count(*) INTO n_hr1069 FROM vr_measure_issues");
p("   WHERE measure_id IN (SELECT id FROM vr_measures WHERE congress = 119 AND number IN ('H.R. 1069','H.R. 973'));");
p("  IF n_hr1069 > 0 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: H.R. 1069 / H.R. 973 now carry % issue row(s). Both are deliberately unmapped — F1 argued and refused the public_schools row, and rule 3 refuses gov_regulation on H.R. 973. No vocab decision in F6 reopens either.', n_hr1069;");
p("  END IF;");
p();
p("  -- The conversion this wave exists for, asserted on the eight named members. The");
p("  -- member floor counts MAPPED records, so this counts mapped ones.");
p("  SELECT min(c) INTO n_thin FROM (");
p("    SELECT count(DISTINCT r.measure_id) AS c");
p("      FROM vr_member_votes v");
p("      JOIN vr_rollcalls r ON r.id = v.rollcall_id");
p("     WHERE v.politician_id IN ('adrian_smith','dina_titus','gabe_vasquez','melanie_stansbury','russ_fulcher','susie_lee','teresa_leger_fernandez','zach_nunn')");
p("       AND EXISTS (SELECT 1 FROM vr_measure_issues i WHERE i.measure_id = r.measure_id)");
p("     GROUP BY v.politician_id");
p("  ) t;");
p("  IF n_thin IS NULL OR n_thin < 12 THEN");
p("    RAISE EXCEPTION 'Federal wave F6: the thinnest of the eight named House members holds % mapped act(s), below the member floor of 12. The wave''s whole purpose is that conversion; _PDX_RD_MEMBER_FLOOR is never lowered to meet it.', n_thin;");
p("  END IF;");
p();
p("  RAISE NOTICE 'Federal wave F6 verified: % measures, % rolls, % member votes, % issue rows, thinnest of the eight named members at % mapped acts.', n_measures, n_rolls, n_votes, n_issues, n_thin;");
p("END $$;");
p();

