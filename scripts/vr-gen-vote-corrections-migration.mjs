#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// PolitiDex Voting Record — stored-vote correction migration
// ─────────────────────────────────────────────────────────────────────────────
// Emits the one migration in this tree that is allowed to change a stored vote, from
// db/vr-vote-corrections-seed.json. Everything about its shape is chosen so that it can
// only do the eighteen things it says it does.
//
// CELL BY CELL, NAMED IN FULL
// There is no set-based UPDATE here — no "fix every cell where the totals disagree", no
// join, no subquery over a roll. Each correction is its own block naming one roll call by
// natural key and one politician_id, and the header above it prints the member, the value
// we stored, the value the official document publishes, and the URL of that document. A
// mass update is how a data-quality pass becomes a rewrite of history that nobody can
// review; eighteen enumerated blocks can be read.
//
// IT CHECKS BEFORE IT WRITES, AND IT IS RE-RUNNABLE
// Each block reads the cell's current value first and then decides:
//   • it holds the value the verification examined → correct it, and count it
//   • it already holds the corrected value        → a previous run did this; leave it
//   • there is no cell at all                     → RAISE, because the target moved
//   • it holds anything else                      → RAISE, because someone else changed
//     it after the verification and this migration is no longer entitled to an opinion
// The UPDATE itself also carries the old value in its WHERE clause, so even in isolation
// it cannot fire twice or land on a cell in an unexpected state.
//
// is_party TRAVELS WITH THE POSITION
// A correction that moved a member to present or not voting sets is_party back to NULL:
// somebody who did not cast a recorded vote has no side to be with or against, and
// leaving a stale 'with_party' behind would be a second, quieter error. Where the
// corrected position is a yea or a nay, is_party is recomputed from that same document's
// own party split by the rule the Slice 2 backfill used.
//
// WHAT IT DOES NOT DO
// No INSERT, no DELETE, no vote created, no roll call, measure, issue mapping, stated
// position or profile touched. vr_member_votes is the only table named.
//
//   node scripts/vr-gen-vote-corrections-migration.mjs > netlify/database/migrations/<ts>_vr_vote_corrections.sql
//
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { assertSeedPidsMatchMap } from "./vr-seed-pid-guard.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEED_PATH = "db/vr-vote-corrections-seed.json";
const seed = JSON.parse(readFileSync(join(ROOT, SEED_PATH), "utf8"));
const memberMap = JSON.parse(readFileSync(join(ROOT, "db", "vr-member-map.json"), "utf8"));

// Correcting the wrong person's vote is worse than leaving the wrong vote alone, so the
// seed's cached slugs are re-checked against the live map before a line is emitted.
const pidCheck = assertSeedPidsMatchMap({ votes: [{ memberVotes: seed.corrections }] }, memberMap, SEED_PATH);

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const L = [];
const rows = seed.corrections;
const chambers = [...new Set(rows.map((r) => r.chamber))].sort();
const members = new Set(rows.map((r) => r.politicianId));
const rollsTouched = new Set(rows.map((r) => `${r.chamber}|${r.congress}|${r.session}|${r.rollNumber}`));
const kinds = {};
rows.forEach((r) => { const k = `${r.storedPosition} → ${r.officialPosition}`; kinds[k] = (kinds[k] || 0) + 1; });

L.push("-- ---------------------------------------------------------------------------");
L.push("-- Stored vote corrections — each cell named, each cell cited");
L.push("-- ---------------------------------------------------------------------------");
L.push(`-- Generated by scripts/vr-gen-vote-corrections-migration.mjs from ${SEED_PATH}.`);
L.push("-- Do not hand-edit: regenerate, or roll forward with a new migration.");
L.push("--");
L.push(`-- ${rows.length} stored member votes corrected across ${rollsTouched.size} roll calls · ${members.size} members`);
L.push(`-- ${chambers.join(" + ")} · 0 votes created · 0 votes deleted · 0 roll calls, measures, mappings,`);
L.push("-- stated positions or profiles touched");
L.push("--");
L.push("-- WHERE THESE CAME FROM");
L.push("-- The August 2026 attribution backfill re-read the official documents for every roll");
L.push("-- call it filled, and re-checked the cells we ALREADY held against them as it went.");
L.push("-- 7,931 stored cells agreed. These did not. The backfill was ON CONFLICT DO NOTHING");
L.push("-- throughout and deliberately refused to touch them, on the grounds that correcting a");
L.push("-- stored vote is a deliberate act with its own citation. This is that act.");
L.push("--");
L.push("-- Most of them trace to attribution by inference in earlier seed waves — a member's");
L.push("-- position filled in from a party's overall split rather than read off the roll — which");
L.push("-- is exactly the failure mode that makes a not-voting member look like a voting one.");
L.push("--");
L.push("-- WHAT WAS VERIFIED BEFORE EACH LINE WAS WRITTEN");
L.push(`-- Every one of the ${seed.reported} reported disagreements was re-checked from scratch by`);
L.push("-- scripts/vr-verify-vote-corrections.mjs: the roll call resolves to exactly one stored");
L.push("-- row; the document identifies itself as that roll; the member is found in it by");
L.push("-- published identifier (Bioguide via name-id for the House, LIS member id — confirmed");
L.push("-- twice — for the Senate) and never by name; a fresh parse reproduces the official");
L.push("-- position exactly; and the database still holds the value that was examined. A row");
L.push("-- failing any of those is left alone and reported rather than corrected.");
L.push(`-- Verified: ${rows.length} · left uncorrected: ${seed.refusedCount}`);
(seed.refused?.rows || []).forEach((r) => {
  L.push(`--   ${r.chamber} roll ${r.roll} · ${r.slug}: ${r.why}`);
});
L.push("--");
L.push("-- THE SHAPE OF THE CORRECTIONS");
Object.entries(kinds).sort((a, b) => b[1] - a[1]).forEach(([k, n]) => {
  L.push(`--   ${String(n).padStart(2)} × stored ${k}`);
});
const intoNoVote = rows.filter((r) => r.officialPosition === "present" || r.officialPosition === "not_voting").length;
L.push(`--   ${intoNoVote} of the ${rows.length} move a member INTO present-or-not-voting, which is the direction`);
L.push("-- that matters most: a vote we recorded for someone who was not there is a sentence");
L.push("-- about them that the record does not support.");
L.push("--");
L.push("-- is_party IS CORRECTED WITH THE POSITION");
L.push("-- Where a member moves to not voting, is_party goes to NULL — no recorded vote, no side");
L.push("-- to be with or against. Where the corrected position is a yea or a nay, is_party is");
L.push("-- recomputed from that document's own party split, by the rule the backfill used.");
L.push("--");
L.push("-- IDEMPOTENT, AND FAIL-CLOSED");
L.push("-- Each block reads the stored value first. It corrects only a cell still holding the");
L.push("-- value the verification examined, treats a cell already holding the corrected value as");
L.push("-- done, and RAISEs on a missing cell or on any third value — because at that point");
L.push("-- something changed underneath this migration and it should stop, not overwrite.");
L.push("--");
L.push(`-- Seed → member-map agreement: ${pidCheck.checked} cached politicianId(s) re-checked against`);
L.push("-- db/vr-member-map.json at generation time; 0 stale, 0 unresolvable.");
L.push("");
L.push("DO $$");
L.push("DECLARE");
L.push("  rc BIGINT;");
L.push("  cur TEXT;");
L.push("  fixed INT := 0;");
L.push("  already INT := 0;");
L.push("BEGIN");

for (const r of rows) {
  const where = `${r.chamber} ${r.congress}/${r.session} roll ${r.rollNumber}`;
  const who = `${r.politicianId} (${r.bioguideId})`;
  L.push("");
  L.push(`  -- ${where} · ${r.measure} · ${r.question} · ${r.voteDate}`);
  L.push(`  --   ${who} stored '${r.storedPosition}'${r.storedIsParty ? ` / ${r.storedIsParty}` : " / is_party NULL"};` +
    ` the document says '${r.officialPosition}'${r.officialIsParty ? ` / ${r.officialIsParty}` : " / no side"}`);
  L.push(`  --   ${r.sourceLabel} — ${r.sourceUrl}`);
  L.push("  SELECT id INTO rc FROM vr_rollcalls");
  L.push(`   WHERE chamber = ${q(r.chamber)} AND congress = ${r.congress} AND session = ${r.session}`);
  L.push(`     AND roll_number = ${r.rollNumber} LIMIT 1;`);
  L.push("  IF rc IS NULL THEN");
  L.push(`    RAISE EXCEPTION ${q(`Vote correction: ${where} is not in vr_rollcalls, so there is no cell to correct.`)};`);
  L.push("  END IF;");
  L.push(`  SELECT position INTO cur FROM vr_member_votes WHERE rollcall_id = rc AND politician_id = ${q(r.politicianId)};`);
  L.push("  IF cur IS NULL THEN");
  L.push(`    RAISE EXCEPTION ${q(`Vote correction: ${where} holds no stored vote for ${r.politicianId}. This migration corrects cells that exist and creates none.`)};`);
  L.push(`  ELSIF cur = ${q(r.storedPosition)} THEN`);
  L.push("    UPDATE vr_member_votes");
  L.push(`       SET position = ${q(r.officialPosition)}, is_party = ${r.officialIsParty ? q(r.officialIsParty) : "NULL"}`);
  L.push(`     WHERE rollcall_id = rc AND politician_id = ${q(r.politicianId)} AND position = ${q(r.storedPosition)};`);
  L.push("    fixed := fixed + 1;");
  L.push(`  ELSIF cur = ${q(r.officialPosition)} THEN`);
  L.push("    already := already + 1;");
  L.push("  ELSE");
  L.push(`    RAISE EXCEPTION ${q(`Vote correction: ${where} holds '%' for ${r.politicianId}, which is neither the value this correction examined ('${r.storedPosition}') nor the value it would write ('${r.officialPosition}'). Something changed underneath this migration; refusing to overwrite it.`)}, cur;`);
  L.push("  END IF;");
}

L.push("");
L.push(`  RAISE NOTICE 'Vote corrections: % cell(s) corrected, % already correct (of ${rows.length} enumerated).', fixed, already;`);
L.push("END $$;");
L.push("");
process.stdout.write(L.join("\n"));
