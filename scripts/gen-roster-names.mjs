#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-roster-names.mjs — writes roster-names.js, the seat holders' own names
// ─────────────────────────────────────────────────────────────────────────────
// /voice carries no cmp-data.js, so on that document nothing held the roster
// row's own display name for a seat's roster id. When the live index files the
// officeholder under the slug of that name (`celeste_maloy`) rather than the
// roster id (`maloy`), the gate had no way to join the two except a hand-added
// PDX_PROFILE_ALIAS row. This writes the one fact the unique-slug rule in
// voter-hub-location.js needs instead: roster id → that roster row's own name.
//
// WHICH ROWS. Every pid seated-member.js can seat, with its cmp-data.js name.
// AND every OTHER roster row whose name slugs to the same thing as one of those
// (or whose id IS that slug),
// so that a slug shared by two people is visible on the lean document as two
// rows — the rule then answers nothing for it rather than picking one. Retired
// ids (db/vr-pid-aliases.json) are not people and are left out.
//
//   node scripts/gen-roster-names.mjs           # write roster-names.js
//   node scripts/gen-roster-names.mjs --check   # exit 1 if it is stale
//
// The output is byte-pinned to this generator by
// scripts/test-voice-name-slug.mjs, so edit cmp-data.js or ballot-breakdown.js
// and re-run this; never hand-edit roster-names.js.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => readFileSync(join(ROOT, f), "utf8");
const OUT = "roster-names.js";

export const slugOf = (name) => String(name == null ? "" : name).toLowerCase()
  .replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");

function loadRoster() {
  const ctx = { console: { log() {}, warn() {}, error() {} } };
  ctx.window = ctx; ctx.globalThis = ctx;
  vm.createContext(ctx);
  vm.runInContext(R("cmp-data.js"), ctx, { filename: "cmp-data.js" });
  return ctx.CMP_DATA || {};
}

function seatedPids() {
  const ctx = {};
  ctx.window = ctx;
  vm.createContext(ctx);
  // The three literal tables and nothing else; the function needs no running.
  const src = R("seated-member.js");
  const pids = new Set();
  for (const name of ["KR_CONGRESSIONAL_INCUMBENTS", "KR_STATE_HOUSE_INCUMBENTS", "KR_STATE_SENATE_INCUMBENTS"]) {
    const m = new RegExp(`var ${name} = (\\{[\\s\\S]*?\\n    \\});`).exec(src);
    if (!m) throw new Error(`seated-member.js: ${name} not found`);
    const t = vm.runInContext(`(${m[1]})`, ctx);
    for (const v of Object.values(t)) pids.add(typeof v === "string" ? v : v && v.pid);
  }
  pids.delete(undefined); pids.delete(null); pids.delete("");
  return [...pids];
}

export function buildRows() {
  const roster = loadRoster();
  let retired = {};
  try { retired = JSON.parse(R("db/vr-pid-aliases.json")).aliases || {}; } catch { retired = {}; }
  const live = (id) => roster[id] && typeof roster[id].name === "string" && roster[id].name.trim() &&
    !Object.prototype.hasOwnProperty.call(retired, id);
  const rows = new Map();
  const seated = seatedPids().filter(live);
  for (const pid of seated) rows.set(pid, roster[pid].name.trim());
  const wanted = new Set(seated.map((p) => slugOf(roster[p].name)));
  for (const id of Object.keys(roster)) {
    if (rows.has(id) || !live(id)) continue;
    // A roster row whose NAME slugs the same way, or whose ID is that slug: either
    // way the slug is not one person's alone, and the lean document must see it.
    if (wanted.has(slugOf(roster[id].name)) || wanted.has(id)) rows.set(id, roster[id].name.trim());
  }
  return [...rows.entries()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
}

export function render(rows) {
  const lit = rows.map(([k, v]) => `    ${k}: ${JSON.stringify(v).replace(/'/g, "\\'").replace(/^"|"$/g, "'")},`).join("\n");
  return `/* ═══════════════════════════════════════════════════════════════════════════
   roster-names.js — GENERATED by scripts/gen-roster-names.mjs. Do not edit.
   ────────────────────────────────────────────────────────────────────────────
   Roster id → that roster row's own display name, out of cmp-data.js, for every
   pid seated-member.js can seat (plus any other roster row whose name slugs the
   same way, so a shared slug reads as two people here too).

   ONE ADDRESS PER PERSON. /voice loads no cmp-data.js, and the live index files
   a few officeholders under the slug of their display name: \`celeste_maloy\`
   holds the document, \`maloy\` is the roster id the seat resolves to. The gate
   in voter-hub-location.js asks this table for the roster row's own name, slugs
   it, and accepts the live document filed under that slug only when exactly one
   roster row and exactly one live document carry it. The seat keeps the roster
   id, so the card links /p/maloy and never /p/celeste_maloy. A slug two people
   share answers nothing. Nothing here matches on a last name.

   It declares no resolver, reads no record and names no seat.
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';
  window.PDX_ROSTER_NAMES = window.PDX_ROSTER_NAMES || {
${lit}
  };
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = render(buildRows());
  if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = R(OUT); } catch { cur = ""; }
    if (cur !== out) { console.error(`✗ ${OUT} is stale — run node scripts/gen-roster-names.mjs`); process.exit(1); }
    console.log(`✓ ${OUT} is current`);
  } else {
    writeFileSync(join(ROOT, OUT), out);
    console.log(`wrote ${OUT}`);
  }
}
