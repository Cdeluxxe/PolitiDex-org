#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-baaja-migration.mjs — S. 5653 (BAAJA) into the Voting Record, from its ledger
// ─────────────────────────────────────────────────────────────────────────────
// Writes netlify/database/migrations/20261214000000_vr_seed_baaja_s5653.sql from
// db/bill-standard/119-s-5653.json and nothing else. The ledger stays the source
// of truth: every mapping row, roll call, member vote, sponsor and timeline line
// in the migration is copied from it, and scripts/test-baaja-bill-file.mjs reads
// both and fails if they ever differ.
//
//   node scripts/gen-baaja-migration.mjs          write the migration
//   node scripts/gen-baaja-migration.mjs --check  exit 1 if the file on disk differs
//
// The migration is applied once and is then immutable: after it ships, a ledger
// change rolls forward with a NEW migration. --check is how the test proves the
// applied file still says what the ledger says.
// ─────────────────────────────────────────────────────────────────────────────
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const LEDGER_FILE = "db/bill-standard/119-s-5653.json";
export const MIGRATION_FILE = "netlify/database/migrations/20261214000000_vr_seed_baaja_s5653.sql";

const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const POS = { Yea: "yea", Nay: "nay", "Not Voting": "not_voting", Present: "present" };
// The ledger's own stage words → the vr_measure_actions vocabulary
// (netlify/lib/vr-normalize.ts). A step taken on the vehicle H.R. 2347 or on the
// substitute S.Amdt. 6883 is filed as 'other' and names its measure in the text, so
// the timeline never says S. 5653 itself passed the House or moved on the floor.
const STAGE = { introduced: "introduced", in_committee: "referred_committee", reported: "reported_committee" };

// is_party exactly as crossoverFlags (netlify/lib/vr-normalize.ts) computes it:
// a yea/nay is with_party when it matches its party's majority on that roll.
function partyFlags(members) {
  const party = (m) => (/\(([A-Z])-[A-Z]{2}\)/.exec(m.name) || [])[1] || "";
  const by = {};
  for (const m of members) {
    const p = party(m), v = POS[m.vote];
    if (!p || (v !== "yea" && v !== "nay")) continue;
    (by[p] = by[p] || { yea: 0, nay: 0 })[v]++;
  }
  return members.map((m) => {
    const p = party(m), v = POS[m.vote];
    if (!p || (v !== "yea" && v !== "nay") || !by[p]) return null;
    return v === (by[p].yea >= by[p].nay ? "yea" : "nay") ? "with_party" : "against_party";
  });
}

function totalsJson(rc) {
  const byParty = {};
  for (const [p, t] of Object.entries(rc.byParty || {})) byParty[p] = { yea: t.Yea || 0, nay: t.Nay || 0 };
  return JSON.stringify({ yea: rc.totals.yea, nay: rc.totals.nay, present: rc.totals.present || 0, notVoting: rc.totals.notVoting || 0, byParty });
}

export function renderMigration(L) {
  const id = L.identity;
  const own = L.status.S5653;
  const ext = {
    congressGovId: "s5653-119",
    congressGovUrl: id.congressGovUrl,
    billStatusUrl: id.billStatusUrl,
    policyArea: id.policyArea,
    officialTitle: id.officialTitle,
    sponsorName: id.sponsor.recordName,
    acronym: id.acronym,
    floorVehicle: id.floorVehicle.number,
    floorVehicleAmendment: "S.Amdt. 6883",
    groundTruthLedger: LEDGER_FILE,
  };
  const V = "m_s5653";
  const out = [];
  const P = (s = "") => out.push(s);

  P("-- ---------------------------------------------------------------------------");
  P("-- S. 5653 (119th) — Bipartisan American Affordability and Jobs Act of 2026 (BAAJA)");
  P("-- ---------------------------------------------------------------------------");
  P(`-- Generated by scripts/gen-baaja-migration.mjs from ${LEDGER_FILE}.`);
  P("-- Do not hand-edit: once applied, roll forward with a new migration.");
  P("--");
  P(`-- 1 measure · ${L.issues.length} issue mappings · ${L.votes.rollcalls.length} roll calls · ` +
    `${L.votes.rollcalls.reduce((n, r) => n + r.members.length, 0)} member votes · ` +
    `${L.sponsors.length} sponsor rows · ${L.status.timeline.length} timeline rows`);
  P("--");
  P("-- WHY THIS EXISTS");
  P("-- BAAJA had a bill page built from its ground-truth ledger but no Voting Record row,");
  P("-- so the bill panel resolved nothing and printed \"Could not load this bill right now.\"");
  P("-- This adds the row and everything the panel reads, copied from the ledger.");
  P("--");
  P("-- ONE MAPPING ROW PER DIRECTION");
  P("-- The ledger records 18 rows over 15 keys: tribal_consultation, property_rights and");
  P("-- mine_cleanup each have a yea_supports row and a yea_opposes row, citing different");
  P("-- sections (the ledger's split-mapping rule). The unique index on vr_measure_issues");
  P("-- was (measure_id, issue_key), which cannot hold that. It is widened here, for every");
  P("-- measure, to (measure_id, issue_key, support_meaning). No existing row moves: every");
  P("-- pair the old index allowed is still unique under the new one.");
  P("--");
  P("-- THE ROLL CALLS ARE THE VEHICLE'S");
  P("-- S. 5653 has had no vote of its own. Its text is moving as S.Amdt. 6883, a full");
  P("-- substitute to H.R. 2347. The six Senate roll calls on that text are attached to this");
  P("-- measure, each with its real question, so the question names the vehicle. Roll 267");
  P("-- (S.Amdt. 6883 agreed to, 69-27) is the one vote on the BAAJA text itself; the other");
  P("-- five are cloture, motion-to-proceed and budget-waiver votes, typed as such so they");
  P("-- carry procedural weight downstream. All 100 senators on each roll are roster-linked.");
  P("-- The ledger gives each vote's date but not its time, so each is stamped at noon");
  P("-- Eastern on that date.");
  P("--");
  P("-- Idempotent: the measure is created only when absent; every other insert is");
  P("-- ON CONFLICT DO NOTHING.");
  P("-- ---------------------------------------------------------------------------");
  P();
  P("DROP INDEX IF EXISTS vr_measure_issues_unique;");
  P("CREATE UNIQUE INDEX IF NOT EXISTS vr_measure_issues_unique");
  P("  ON vr_measure_issues (measure_id, issue_key, support_meaning);");
  P();
  P("DO $$");
  P("DECLARE");
  P(`  ${V} integer;`);
  P("  rc integer;");
  P("BEGIN");
  P();
  P("  -- ── measure ───────────────────────────────────────────────────────────────");
  P(`  SELECT id INTO ${V} FROM vr_measures`);
  P(`   WHERE congress = 119 AND chamber = 'senate' AND number = 'S. 5653' LIMIT 1;`);
  P(`  IF ${V} IS NULL THEN`);
  P("    INSERT INTO vr_measures (measure_type, congress, chamber, number, title, short_title, summary, introduced_at, sponsor_id, status, source_url, source_label, external_ids)");
  P(`    VALUES ('bill', 119, 'senate', 'S. 5653', ${q(id.shortTitle)}, ${q(id.shortTitle)},`);
  P(`      ${q(L.overview.plainSummary)},`);
  P(`      DATE '2026-09-30', ${q(id.sponsor.politicianId)}, 'pending', ${q(id.congressGovUrl)}, 'Congress.gov',`);
  P(`      ${q(JSON.stringify(ext))}::jsonb)`);
  P(`    RETURNING id INTO ${V};`);
  P("  END IF;");
  P();
  P("  -- ── issue mappings: the ledger's 18 rows, in ledger order, verbatim ───────");
  P("  -- No weight, rank or primary flag: the ledger carries none (every row 100, none primary).");
  P("  INSERT INTO vr_measure_issues (measure_id, issue_key, weight, is_primary, support_meaning, rationale, source_url, review_status) VALUES");
  P(L.issues.map((x) =>
    `    (${V}, ${q(x.issueKey)}, 100, false, ${q(x.supportMeaning)},\n      ${q(x.rationale)},\n      ${q(x.sourceUrl)}, 'curated')`
  ).join(",\n"));
  P("  ON CONFLICT (measure_id, issue_key, support_meaning) DO NOTHING;");
  P();
  P("  -- ── sponsors ──────────────────────────────────────────────────────────────");
  P("  INSERT INTO vr_positions (measure_id, politician_id, action_type, supports, acted_at, source_url, note) VALUES");
  P(L.sponsors.map((s) =>
    `    (${V}, ${q(s.politicianId)}, ${q(s.role)}, true, TIMESTAMPTZ '${s.joinedOn}T00:00:00Z',\n` +
    `     'https://www.congress.gov/bill/119th-congress/senate-bill/5653/cosponsors', ` +
    q(`${s.recordName}. ${s.role === "sponsor" ? "Sponsor" : s.original ? "Original cosponsor" : "Cosponsor"}, joined ${s.joinedOn}.`) + ")"
  ).join(",\n"));
  P("  ON CONFLICT (measure_id, politician_id, action_type) DO NOTHING;");
  P();
  P("  -- ── timeline ──────────────────────────────────────────────────────────────");
  P("  INSERT INTO vr_measure_actions (measure_id, stage, chamber, action_date, text, source_url, source_label, sort_order) VALUES");
  P(L.status.timeline.map((t, i) => {
    const mine = t.measure === "S. 5653";
    const stage = (mine && STAGE[t.stage]) || "other";
    const chamber = /^H\.R\./.test(t.measure) && ["introduced", "reported", "passed_house"].includes(t.stage) ? "house" : "senate";
    const text = mine ? t.text : `${t.measure} (floor vehicle) — ${t.text}`;
    return `    (${V}, '${stage}', '${chamber}', TIMESTAMPTZ '${t.date}T00:00:00Z', ${q(text)}, ${q(t.sourceUrl)}, 'Congress.gov', ${i + 1})`;
  }).join(",\n"));
  P("  ;");
  P();
  P("  -- ── roll calls and member votes ───────────────────────────────────────────");
  for (const rc of L.votes.rollcalls) {
    const flags = partyFlags(rc.members);
    P(`  -- senate 119/2 roll ${rc.roll} · ${rc.measure} · ${rc.question}`);
    P(`  --   ${rc.result}`);
    P("  INSERT INTO vr_rollcalls (measure_id, chamber, congress, session, roll_number, vote_date, question, action_type, result, required_majority, totals, source_url, source_label)");
    P(`  VALUES (${V}, 'senate', 119, ${rc.session}, ${rc.roll}, TIMESTAMPTZ '${rc.date}T12:00:00-05:00', ${q(rc.question)}, ${q(rc.actionType)}, ${q(rc.result)}, ${q(rc.requiredMajority)},`);
    P(`    ${q(totalsJson(rc))}::jsonb, ${q(rc.sourceUrl)}, 'U.S. Senate')`);
    P("  ON CONFLICT (chamber, congress, session, roll_number) DO NOTHING;");
    P(`  SELECT id INTO rc FROM vr_rollcalls WHERE chamber = 'senate' AND congress = 119 AND session = ${rc.session} AND roll_number = ${rc.roll} LIMIT 1;`);
    P(`  IF rc IS NULL THEN RAISE EXCEPTION 'BAAJA: senate 119/${rc.session} roll ${rc.roll} could not be read back after insert.'; END IF;`);
    P("  INSERT INTO vr_member_votes (rollcall_id, politician_id, position, is_party) VALUES");
    P(rc.members.map((m, i) => `    (rc, ${q(m.politicianId)}, '${POS[m.vote]}', ${flags[i] ? `'${flags[i]}'` : "NULL"})`).join(",\n"));
    P("  ON CONFLICT (rollcall_id, politician_id) DO NOTHING;");
    P();
  }
  P("END $$;");
  P();
  P("-- ── verification ────────────────────────────────────────────────────────────");
  P("DO $$");
  P("DECLARE m integer; n_iss integer; n_rc integer; n_mv integer;");
  P("BEGIN");
  P("  SELECT id INTO m FROM vr_measures WHERE congress = 119 AND chamber = 'senate' AND number = 'S. 5653' LIMIT 1;");
  P("  IF m IS NULL THEN RAISE EXCEPTION 'BAAJA: S. 5653 is not in vr_measures.'; END IF;");
  P("  SELECT count(*) INTO n_iss FROM vr_measure_issues WHERE measure_id = m;");
  P(`  IF n_iss <> ${L.issues.length} THEN RAISE EXCEPTION 'BAAJA: expected ${L.issues.length} mapping rows, found %', n_iss; END IF;`);
  P("  SELECT count(*) INTO n_rc FROM vr_rollcalls WHERE measure_id = m;");
  P(`  IF n_rc <> ${L.votes.rollcalls.length} THEN RAISE EXCEPTION 'BAAJA: expected ${L.votes.rollcalls.length} roll calls, found %', n_rc; END IF;`);
  P("  SELECT count(*) INTO n_mv FROM vr_member_votes v JOIN vr_rollcalls r ON r.id = v.rollcall_id WHERE r.measure_id = m;");
  P(`  IF n_mv <> ${L.votes.rollcalls.reduce((n, r) => n + r.members.length, 0)} THEN RAISE EXCEPTION 'BAAJA: member vote count is %', n_mv; END IF;`);
  P("END $$;");
  return out.join("\n") + "\n";
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const L = JSON.parse(readFileSync(join(ROOT, LEDGER_FILE), "utf8"));
  const sql = renderMigration(L);
  const file = join(ROOT, MIGRATION_FILE);
  if (process.argv.includes("--check")) {
    const ok = existsSync(file) && readFileSync(file, "utf8") === sql;
    console.log(ok ? "✓ BAAJA migration matches its ledger" : "✗ BAAJA migration differs from its ledger");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(file, sql);
  console.log(`wrote ${MIGRATION_FILE}`);
}
