#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// gen-stance-person-names.mjs — writes netlify/lib/stance-person-names.mjs
//
// The person names R11(a) uses to decide that a possessive ("Trump’s",
// "Abbott’s") is a PERSON, so a he / she / his / her after it refers to that
// person and not to the page's politician. Source: every person in
// db/share-index.json (the site's people index). Places, organisations and
// generic nouns are never in it, so "Hollywood’s", "Ohio’s", "the state’s" do
// not reassign a pronoun.
//
// A few surnames are also common US place names (Austin, Houston, Jackson …) or
// everyday words (Hill, King, White …). Those count only as part of a full name ("Ronny Jackson’s") or after a
// title ("Mayor Jackson’s") — never bare — so "Austin’s NPR station" and
// "Capitol Hill’s" stay what they are. Re-run after the people index changes:
//   node scripts/gen-stance-person-names.mjs
// ═══════════════════════════════════════════════════════════════════════════
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const people = JSON.parse(fs.readFileSync(path.join(root, "db/share-index.json"), "utf8")).people;

// Common US place names that are also surnames in the index: bare use is a place.
const PLACE_NAMES = ["Austin", "Houston", "Jackson", "Lincoln", "Madison", "Washington", "Dallas", "Denver", "Phoenix",
  "Columbia", "Jefferson", "Charlotte", "Raleigh", "Lansing", "Salem", "Boise", "Tyler", "Irving", "Durham", "Cleveland",
  "Orlando", "Aurora", "Arlington", "Hollywood", "Hamilton", "Franklin", "Richmond", "Albany", "Trenton", "Helena",
  "Dover", "Augusta", "Frankfort", "Topeka", "Lafayette", "Marion", "Monroe", "Logan", "Ogden", "Provo", "Bountiful",
  "Layton", "Sandy", "Murray", "Eugene", "Reno", "Tempe", "Mesa", "Plano", "Laredo", "Odessa", "Midland", "Beaumont",
  "Waco", "Temple", "Chester", "Warren", "Lowell", "Quincy", "Springfield", "Kent", "York", "Carson", "Douglas", "Dakota"];
// Surnames that are also everyday capitalised words ("Capitol Hill’s", "the
// White House’s", "Ford’s" the company): same treatment as place names.
const WORD_NAMES = ["People", "West", "East", "North", "South", "Little", "Black", "White", "Green", "Brown", "Young", "King",
  "Love", "Rich", "Hill", "Wood", "Woods", "Banks", "Best", "Long", "Strong", "Day", "Fields", "Waters", "Ford", "Hope",
  "Grace", "Faith", "Price", "Bush", "Stone", "Rivers", "Lane", "Hunt", "Cash", "Gold", "Major", "Church", "Bell", "Bridges"];

const SUFFIX = /^(?:Jr|Sr|II|III|IV|V)\.?$/i;
const clean = (n) => String(n || "").replace(/["“”(][^"“”)]*["“”)]/g, " ").replace(/,/g, " ").split(/\s+/).filter(Boolean);
const surnames = new Set(), fullNames = new Set();
for (const v of Object.values(people)) {
  const w = clean(v.n).filter((x) => !SUFFIX.test(x));
  if (w.length < 2) continue;
  const last = w[w.length - 1].replace(/\.$/, "");
  if (!/^[A-Z][\p{L}'’-]+$/u.test(last) || last.length < 2) continue;
  surnames.add(last);
  const first = w[0].replace(/\.$/, "");
  if (/^[A-Z][\p{L}'’-]+$/u.test(first)) fullNames.add(`${first} ${last}`);
}
const places = new Set([...PLACE_NAMES, ...WORD_NAMES]);
const bare = [...surnames].filter((s) => !places.has(s)).sort();
const fullOnly = [...surnames].filter((s) => places.has(s)).sort();
const full = [...fullNames].filter((f) => places.has(f.split(" ").pop())).sort();

const out = `// @generated by scripts/gen-stance-person-names.mjs from db/share-index.json — do not edit by hand.
// Person names for R11(a) (stance-score-core.mjs): a possessive counts as another
// person only when it is one of these names, a title + name, or a person role.
/** Surnames that are a person on their own ("Trump’s", "Abbott’s"). */
export const PERSON_SURNAMES = new Set(${JSON.stringify(bare)});
/** Surnames that are also US place names or everyday words: a person only with the full name or a title. */
export const PLACE_SURNAMES = new Set(${JSON.stringify(fullOnly)});
/** Full names ("First Last") for the place-name surnames above. */
export const PLACE_SURNAME_FULL_NAMES = new Set(${JSON.stringify(full)});
`;
fs.writeFileSync(path.join(root, "netlify/lib/stance-person-names.mjs"), out);
console.log(`person names: ${bare.length} surnames, ${fullOnly.length} place-name surnames (${fullOnly.join(", ")}), ${full.length} full names for them`);
