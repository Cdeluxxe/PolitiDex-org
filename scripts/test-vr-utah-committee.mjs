const failures = [];
const ok = (cond, msg) => { if (cond) passed++; else failures.push(msg); };
const eq = (a, b, msg) =>
  ok(a === b, `${msg} — expected ${JSON.stringify(b)}, got ${JSON.stringify(a)}`);
const has = (hay, needle, msg) =>
  ok(String(hay).indexOf(needle) >= 0, `${msg} — "${needle}" missing`);
const lacks = (hay, needle, msg) =>
  ok(String(hay).indexOf(needle) < 0, `${msg} — "${needle}" present and must not be`);
const section = (t) => console.log(`\n   ── ${t}`);
// The surname a printed committee form and a confirming line share. A committee
// vote line prints "Rep. R. Walter"; a floor key prints "Walter, N."; a roster row
// prints "Walter, R. Neil · Representative · Republican · 74". All three reduce to
// "walter", which is the only part of the three strings that is allowed to be
// compared — the initials are what the human had to reconcile, not the machine.
const sur = (x) => String(x).replace(/^(Rep\.|Sen\.|President|Speaker)\.?\s+/, "")
  .replace(/,.*$/, "").split(/\s+/).pop().toLowerCase();
// A fixture that stopped offering a case is a silent pass, so the probes that
// establish one are fatal rather than counted.
const must = (cond, msg) => {
  if (cond) return;
  console.error(`✗ vr-utah-committee: ${msg}`);
  process.exit(1);
};

// EVERY SESSION IS A LIST OF MIGRATIONS, NOT A FILE. An applied migration is
// never edited, so when a shipped seed grows the new rows arrive in a forward
// delta and the session's SQL is the union of its files. The files are listed in
// the order Postgres will apply them, and what is asserted below is the union —
// a restated row collapses on the vr_positions unique index, exactly as it will
// in the database.
const MIGS = {
  "2025GS": ["netlify/database/migrations/20261004000000_vr_utah_2025gs_committee_votes.sql",
             "netlify/database/migrations/20261014000000_vr_utah_2025gs_committee_votes_v1_vocabulary_keys.sql"],
  "2024GS": ["netlify/database/migrations/20261005000000_vr_utah_2024gs_committee_votes.sql",
             "netlify/database/migrations/20261013000000_vr_utah_2024gs_committee_votes_roster_rows.sql"],
  "2023GS": ["netlify/database/migrations/20261012000000_vr_utah_2023gs_committee_votes.sql"],
};
const MIG = MIGS["2025GS"][0];
const SEED = J("db/vr-utah-committee-seed.json");
const CMAP = J("db/vr-utah-committee-map.json");
const FLOOR = J("db/vr-utah-vote-seed.json");
const ISSUE_KEYS = new Set(J("db/issue-keys.json").keys);
const SQL = MIGS["2025GS"].map((f) => R(f)).join("\n");
const VR = R("voting-record.js");
const SH = R("stance-helpers.js");
const FN = R("netlify/functions/voting-record.mts");

const measures = SEED.measures || [];
const acts = measures.flatMap((m) => (m.committeeActs || []).map((ca) => ({ m, ca })));
const rows = acts.flatMap(({ m, ca }) => (ca.votes || []).map((v) => ({ m, ca, v })));
must(measures.length > 0 && acts.length > 0 && rows.length > 0,
  "the committee seed carries no acts — nothing to pin");

// Parse a session's migrations into the executable shape Postgres will end up
// holding: measures keyed the way the DO block selects them, positions keyed by
// the vr_positions unique index. Restatement collapses here for the same reason
// it collapses in the database, which is what makes a delta safe to ship.
function sqlRows(session) {
  const measures = new Map(), positions = new Set();
  for (const f of MIGS[session]) {
    for (const b of R(f).split(/^DO \$\$$/m).slice(1)) {
      // The last DO block in every file is the verification block: it looks up no
      // measure and inserts nothing, so it is not part of the executable shape.
      if (!b.includes("SELECT id INTO m_id FROM vr_measures")) continue;
      const num = /number = '([^']+)'/.exec(b), ch = /chamber = '([^']+)'/.exec(b);
      must(num && ch, `${session}: a DO block in ${f} does not select its measure by number and chamber`);
      const key = `${ch[1]}|${num[1]}`;
      measures.set(key, (measures.get(key) || 0) + 1);
      for (const m of b.matchAll(/\(m_id, '([a-z0-9_]+)', 'committee_vote'/g)) {
        positions.add(`${key}|${m[1]}`);
      }
    }
  }
  return { measures, positions };
}

