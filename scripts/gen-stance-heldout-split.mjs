#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// gen-stance-heldout-split.mjs — the tuning / held-out split of the 77
// expansion ground-truth records (db/stance-ground-truth-expansion-2026-11.json)
//
// The benchmark (scripts/test-stance-heldout-benchmark.mjs) scores all 77. About
// a third of them are HELD OUT: no scoring rule, vocabulary entry or stance
// test may be written against them, so their numbers stay an honest read of
// how the scorer does on records nobody tuned it on.
//
// THE RULE (deterministic; the committed file must equal what it produces):
//   1. Not eligible for the held-out side (they go to tuning):
//        · the six records the scorer read on the wrong side when the split was
//          made — they are now the targets of scripts/test-stance-error-patterns.mjs;
//        · any record whose stance_id or a verbatim excerpt fragment (> 30
//          chars) already appears in a stance-rule file (scripts/test-stance-*.mjs,
//          netlify/lib/stance-*.mjs) — it has been looked at while tuning.
//   2. The eligible records are grouped by their human position (support /
//      oppose / mixed). Inside each group they are ordered by
//      sha256("heldout-v1|" + stance_id) and the first ceil(n / 3) are held out.
//
// FROZEN once written: the committed file is the split. Re-splitting changes
// which records count as unseen, so the generator refuses to overwrite it
// without --force (do that only on purpose, and say so). The benchmark checks
// the partition and that no held-out record has leaked into a stance-rule file;
// it does not recompute the split, so quoting a TUNING record later is fine.
//
// Read-only over the ground-truth file. Writes db/stance-heldout-split-2026-11.json.
//   node scripts/gen-stance-heldout-split.mjs [--check] [--force]
// ═══════════════════════════════════════════════════════════════════════════
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const GT_PATH = path.join(root, "db/stance-ground-truth-expansion-2026-11.json");
export const SPLIT_PATH = path.join(root, "db/stance-heldout-split-2026-11.json");
export const SPLIT_VERSION = "heldout-v1";

// The six wrong-side reads on the held-out set (phase9-v3, 2026-11-25).
export const ERROR_TARGETS = [
  "kclark|healthcare|gt-019",
  "bryan_steil|edu_college_cost|gt-078",
  "russ_fulcher|lands_preserve|gt-083",
  "rick_crawford|ukraine_aid|gt-008",
  "khanna|cut_spending|gt-021",
  "casar|econ_workers|gt-048",
];

/** The stance-rule files a held-out record must never appear in. */
export function tuningFiles() {
  const pick = (dir, re) => fs.readdirSync(path.join(root, dir)).filter((n) => re.test(n)).sort().map((n) => path.join(dir, n));
  return [...pick("scripts", /^test-stance-.*\.mjs$/), ...pick("netlify/lib", /^stance-.*\.mjs$/)];
}

/** Verbatim excerpt fragments of a record long enough to identify it. */
export const fragmentsOf = (r) => (r.sources || []).flatMap((s) => String(s.excerpt || "").split(/\s*\.\.\.\s*/))
  .map((f) => f.trim().replace(/^["“]+|["”]+$/g, "").slice(0, 50)).filter((f) => f.length > 30);

/** Files (from `texts`: { file: content }) that mention a record. */
export const mentionsOf = (r, texts) => Object.entries(texts)
  .filter(([, t]) => t.includes(r.stance_id) || fragmentsOf(r).some((f) => t.includes(f))).map(([f]) => f);

const order = (id) => createHash("sha256").update(`${SPLIT_VERSION}|${id}`).digest("hex");

export function computeSplit(records, texts) {
  const seen = new Set(records.filter((r) => mentionsOf(r, texts).length).map((r) => r.stance_id));
  const errors = new Set(ERROR_TARGETS);
  const groups = {};
  for (const r of records) {
    if (errors.has(r.stance_id) || seen.has(r.stance_id)) continue;
    (groups[r.position] ||= []).push(r.stance_id);
  }
  const holdout = [];
  for (const pos of Object.keys(groups).sort()) {
    const ids = groups[pos].slice().sort((a, b) => order(a).localeCompare(order(b)));
    holdout.push(...ids.slice(0, Math.ceil(ids.length / 3)));
  }
  const held = new Set(holdout);
  return {
    _note: "Tuning / held-out split of the 77 expansion ground-truth records. Held-out records must not be used to write or adjust any scoring rule, vocabulary entry or stance test; the benchmark (scripts/test-stance-heldout-benchmark.mjs) reports them separately and fails if one is quoted in a stance-rule file. Generated by scripts/gen-stance-heldout-split.mjs — do not edit by hand.",
    split_version: SPLIT_VERSION,
    source: "db/stance-ground-truth-expansion-2026-11.json",
    rule: "Exclude the six wrong-side reads (error-pattern targets) and any record already quoted in scripts/test-stance-*.mjs or netlify/lib/stance-*.mjs; group the rest by human position; hold out the first ceil(n/3) of each group ordered by sha256('heldout-v1|' + stance_id).",
    counts: { records: records.length, holdout: holdout.length, tuning: records.length - holdout.length, not_eligible_error_targets: errors.size, not_eligible_already_seen: [...seen].filter((id) => !errors.has(id)).length },
    holdout: records.map((r) => r.stance_id).filter((id) => held.has(id)),
    tuning: records.map((r) => r.stance_id).filter((id) => !held.has(id)),
  };
}

export function buildSplit() {
  const records = JSON.parse(fs.readFileSync(GT_PATH, "utf8")).records;
  const texts = Object.fromEntries(tuningFiles().map((f) => [f, fs.readFileSync(path.join(root, f), "utf8")]));
  // The benchmark itself lists no record; the split file is not a tuning file.
  delete texts["scripts/test-stance-heldout-benchmark.mjs"];
  return computeSplit(records, texts);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = JSON.stringify(buildSplit(), null, 2) + "\n";
  if (process.argv.includes("--check")) {
    const ok = fs.existsSync(SPLIT_PATH) && fs.readFileSync(SPLIT_PATH, "utf8") === text;
    console.log(ok ? "split is current" : "split is stale");
    process.exit(ok ? 0 : 1);
  }
  if (fs.existsSync(SPLIT_PATH) && !process.argv.includes("--force")) {
    console.log("split exists and is frozen — pass --force to re-split on purpose");
    process.exit(1);
  }
  fs.writeFileSync(SPLIT_PATH, text);
  console.log(JSON.stringify(JSON.parse(text).counts));
}
