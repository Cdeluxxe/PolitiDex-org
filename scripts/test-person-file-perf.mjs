// ── 10 · the stages are documented ──────────────────────────────────────────
section("10 · every mark the app takes is named in the stage list");
{
  must(existsSync(join(ROOT, "pdx-perf.js")), "pdx-perf.js does not exist");
  const PERF = R("pdx-perf.js");
  has(INDEX, '<script defer src="/pdx-perf.js"></script>', "pdx-perf.js is shipped, deferred");

  // The reporter upgrades the head's clock; replacing it would drop every mark
  // taken before it ran.
  eq((PERF.match(/window\.PDXPerf = \{/g) || []).length, 1,
    "pdx-perf.js assigns window.PDXPerf in exactly one place");
  ok(PERF.indexOf("if (!P) {") < PERF.indexOf("window.PDXPerf = {"),
    "that assignment is the fallback for a page with no head clock");
  has(PERF, "if (P.report) return;", "the reporter installs itself once");
  ["report", "waterfall", "dump"].forEach((k) => has(PERF, `P.${k} =`, `PDXPerf.${k} is published`));
  has(PERF, "'pdx:perf'", "each landing stage is announced");
  has(PERF, "pdxperf=1", "the report is opt-in per address");

  const stages = new Set([...PERF.matchAll(/\['([a-z-]+)',\s+'/g)].map((m) => m[1]));
  must(stages.size > 8, `parsed only ${stages.size} documented stages`);
  const taken = new Set();
  [BLOCK, VR, PF].forEach((src) => {
    [...src.matchAll(/(?:perf|P\.mark)\('([a-z-]+)'/g)].forEach((m) => taken.add(m[1]));
  });
  must(taken.size > 4, `found only ${taken.size} perf marks in the app`);
  taken.forEach((n) => ok(stages.has(n), `mark '${n}' is taken but not documented in pdx-perf.js's stage list`));

  // The four numbers the pass is judged on.
  ["time to first paint", "time to roster", "time to first voting-record page",
    "time to brief off-loading"].forEach((h) => has(PERF, h, `the headline "${h}" is reported`));
}

