#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// test-person-file-perf.mjs — the cold /p/<pid> record request starts in the head
// ─────────────────────────────────────────────────────────────────────────────
// A cold open of /p/<pid> used to reach the voting record LAST, behind four
// stages that have nothing to do with it:
//
//   1. ~2.12 MB of index.html parsed (with ~2.6 MB of parser-blocking script
//      executing mid-parse),
//   2. 97 deferred modules executed in document order — person-file.js is ~80
//      files in, and a deferred script cannot run until parsing completes,
//   3. person-file.js's roster wait (window._pdxRosterState; EARLY 2000ms,
//      CEILING 15000ms),
//   4. only then open() → warm() → GET /api/voting-record/member/<pid>.
//
// None of stages 1-3 are inputs to that request: the pid is in
// location.pathname from the first byte and the endpoint is keyed by pid alone.
// So the request now starts from an inline script in the head — the earliest
// executable moment in the document — and is handed to PDXVotingRecord to adopt.
//
// That split puts the SAME contract in two files that cannot import each other,
// which is what this harness exists to hold:
//
//   1. ONE REQUEST, EARLIEST. The block is inline (not deferred, not external),
//      sits ahead of every module, fires for /p/<pid> only, and issues exactly
//      one fetch with its own 12s deadline.
//   2. THE PID TABLES MATCH. Its inline mirrors equal their sources — the
//      voting-record retirements (PDX_PID_ALIASES in stance-helpers.js and
//      db/vr-pid-aliases.json) and the roster bridges (PDX_PROFILE_ALIAS in
//      profile-evidence.js) — and are applied in the order the arrival path
//      applies them. A mirror that drifts prefetches the wrong member's record;
//      a missing profile bridge prefetches a pack the opened file never reads,
//      which is how /p/scott_chew cost two requests to show chew_h68's file.
//   3. THE URL IS THE ONE fetchMember BUILDS. The query is generated by
//      PDXVotingRecord._query({ pageSize: 100 }) — the harness runs the real
//      function — because a prefetch under any other key is a second request,
//      not a head start.
//   4. THE SESSION KEY AND TTL MATCH. index.html reads what voting-record.js
//      writes; the key format and TTL are asserted identical in both files.
//   5. ADOPTION IS A SINGLE HAND-OVER. fetchMember claims the box once and only
//      on a full URL match, so no filtered query can be answered with the
//      baseline page and no second caller can double-count it.
//   6. THE RECORD DOES NOT WAIT ON THE ROSTER. bootAdopt warms before the wait.
//   7. LOADING IS NEVER THE ONLY TOP STATE. The brief's wait has a finite
//      deadline, the hero repaints on the record's own arrival, and "absent from
//      the formal index" is not reported as "empty file".
//   8. THE STAGES ARE DOCUMENTED. Every perf mark the app takes is named in
//      pdx-perf.js's stage list, so the waterfall cannot drift from its own map.
//   9. THE FIRST PAINT IS NOT COVERED UP. A cold arrival opens the modal on a
//      loading shell, and that shell repeats the first-byte header's name, office
//      and formal rows instead of drawing a spinner over them. The header itself
//      is hidden only once the real file is mounted.
//  10. THE FILE DOES NOT WAIT ON THE FULL ROSTER. An address the app (or the
//      edge's stamp) can already resolve opens now; only "we carry nobody by that
//      name" waits for the roster flag.
//  11. FOUR NUMBERS, ONE LINE. pdx-perf.js prints navStart → crawl visible → vote
//      sent → vote back → name on file, once, on /p/<pid> only, to the console.
//
//   node scripts/test-person-file-perf.mjs

import { existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => readFileSync(join(ROOT, f), "utf8");

let passed = 0;
const failures = [];
const ok = (c, m) => { if (c) passed++; else failures.push(m); };
const eq = (a, b, m) => ok(a === b, `${m} — expected ${JSON.stringify(b)}, got ${JSON.stringify(a)}`);
const has = (h, n, m) => ok(String(h).includes(n), `${m} — missing ${JSON.stringify(n)}`);
const hasnt = (h, n, m) => ok(!String(h).includes(n), `${m} — still contains ${JSON.stringify(n)}`);
const section = (t) => console.log(`\n   ── ${t}`);
// A harness whose probe target was renamed away is stale, not passing.
const must = (c, m) => { if (c) return; console.error(`✗ person-file perf: STALE HARNESS — ${m}`); process.exit(2); };

const INDEX = R("index.html");
const VR = R("voting-record.js");
