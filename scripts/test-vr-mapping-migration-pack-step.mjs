#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// test-vr-mapping-migration-pack-step.mjs — a promote may not ship without the
// pack-generation step
// ─────────────────────────────────────────────────────────────────────────────
// The offline pack's blob key and its URL both carry a fingerprint of
// vr_measure_issues (`mappingVersion()` in netlify/lib/vr-pack.ts), so a mapping
// write retires every pack built from the old mapping by making its key
// unreachable. Nothing has to be bumped by hand. That is the good news and it is
// also the failure mode: a step nobody performs is a step nobody notices has
// stopped working.
//
// Federal wave F4 is the case. It promoted H.R. 6644 | housing to PRIMARY with a
// one-boolean UPDATE. The row count did not move, no file said the word "pack",
// and the pack kept serving isPrimary: false for six hours — long enough for a
// reader to meet "Not about this issue" on a row the database said was a housing
// vote. The generation scheme fixes the mechanism. This file fixes the checklist:
//
//   EVERY MIGRATION THAT WRITES vr_measure_issues MUST DECLARE THE PACK STEP,
//   on one comment line, or CI fails:
//
//     -- pack-generation: derived — the fingerprint moves with these rows;
//     --   confirm with scripts/test-vr-pack-key-version.mjs after the wave lands.
//
//   or, for the rare wave that has to invalidate by hand instead:
//
//     -- pack-generation: purge — <what is purged from the vr-packs store, and why
//     --   the derived fingerprint was not enough>
//
// WHY A DECLARATION AND NOT A DERIVED CHECK. What CI can compute — does the
// fingerprint cover the columns the pack serves — is already computed, by
// test-vr-pack-key-version.mjs. What it cannot compute is whether the human who
// wrote a promote KNEW that a pack of every affected member is now retired and
// that the next read pays a rebuild. That is what the line asserts, and a line
// nobody can add absent-mindedly (it names one of two modes and, for `purge`,
// what is purged) is the cheapest instrument that asserts it.
//
// AND THE PRINTER, NOT ONLY THE PRINTOUT. Almost every mapping migration here was
// generated by a script, so section 3 sweeps the generators as well: each one that
// emits a mapping write is named either as active — and must print the declaration
// itself, so a wave starts with the step rather than remembering it — or as retired,
// because its output is an applied migration that may not be edited. A generator on
// neither list fails. That sweep is jurisdiction-neutral for the same reason the
// fingerprint is: vr_measure_issues does not record who wrote a row, so the Utah
// lanes retire packs exactly the way F4's one-boolean promote did, and section 4
// requires the § Utah checklist to say so in its own run-list.
//
// GRANDFATHERED BY DATE, NOT BY LIST. The 95 mapping migrations already applied
// to the branch predate the rule and are immutable — an applied migration may
// never be edited, so requiring the line inside them would be requiring an
// illegal edit. Anything timestamped at or after PACK_STEP_CUTOFF is subject. No
// exemption list exists, because an exemption list is a place to hide.
//
//   node scripts/test-vr-mapping-migration-pack-step.mjs
//
// Reads the migration directory and the runbook. No database, no network.

import { readdirSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(ROOT, p), "utf8");

let passed = 0;
const failures = [];
const ok = (cond, msg) => { if (cond) passed++; else failures.push(msg); };
const eq = (a, b, msg) =>
  ok(a === b, `${msg} — expected ${JSON.stringify(b)}, got ${JSON.stringify(a)}`);
const has = (hay, needle, msg) =>
  ok(String(hay).indexOf(needle) >= 0, `${msg} — "${needle}" missing`);
const section = (t) => console.log(`\n   ── ${t}`);
const must = (cond, msg) => { if (!cond) { console.error(`\n  ✗ ${msg}\n`); process.exit(1); } };

// The day the rule ships. Everything before it is grandfathered (and immutable);
// everything from it on is subject. One constant, named in the runbook.
const PACK_STEP_CUTOFF = "20261022000000";

const MIG_DIR = "netlify/database/migrations";

// ── The rule, as three small functions ───────────────────────────────────────
// Comments are stripped before asking "does this WRITE the mapping table", so a
// migration that only talks about vr_measure_issues in its prose — a rationale, a
// reference to an earlier wave — is not dragged in. The marker is then looked for
// in the ORIGINAL text, because the marker is itself a comment.
const stripComments = (sql) =>
  String(sql)
    .split("\n")
    .map((line) => line.replace(/--.*$/, ""))
    .join("\n");

const WRITE_RE =
  /\b(?:insert\s+into|update|delete\s+from|truncate(?:\s+table)?|merge\s+into)\s+(?:only\s+)?(?:public\s*\.\s*)?"?vr_measure_issues"?/i;

export const writesMapping = (sql) => WRITE_RE.test(stripComments(sql));

// The declaration. One line, `-- pack-generation: <derived|purge>`, followed by
// the operator's own words. `purge` additionally has to name the store or the
// helper it purges through, so the word cannot be used as a synonym for "handled".
const MARKER_RE = /^[ \t]*--[ \t]*pack-generation:[ \t]*(derived|purge)\b(.*)$/im;

export const packStepOf = (sql) => {
  const m = MARKER_RE.exec(String(sql));
  if (!m) return { declared: false, mode: "", reason: "no `-- pack-generation:` line" };
  const mode = m[1].toLowerCase();
  if (mode === "purge" && !/vr-packs|deletePack/.test(String(sql))) {
    return {
      declared: false,
      mode,
      reason: "`purge` must name the vr-packs store or deletePack — what is being purged",
    };
  }
  return { declared: true, mode, reason: "" };
};

// Subject to the rule = writes the mapping table AND is timestamped at or after
// the cutoff.
export const isSubject = (file, sql) =>
  (file.match(/^(\d{14})_/) || [])[1] >= PACK_STEP_CUTOFF && writesMapping(sql);

// ═════════════════════════════════════════════════════════════════════════════
section("1 · every mapping migration from the cutoff on declares the pack step");
// ═════════════════════════════════════════════════════════════════════════════
const files = readdirSync(join(ROOT, MIG_DIR)).filter((f) => f.endsWith(".sql")).sort();
must(files.length > 100, `only ${files.length} migrations found — is ${MIG_DIR} the right path?`);

let mappingWrites = 0, subject = 0, declared = 0;
const missing = [];
const modes = { derived: 0, purge: 0 };
for (const f of files) {
  const sql = read(join(MIG_DIR, f));
  if (writesMapping(sql)) mappingWrites++;
  if (!isSubject(f, sql)) continue;
  subject++;
  const step = packStepOf(sql);
  if (step.declared) { declared++; modes[step.mode]++; }
  else missing.push(`${f}: ${step.reason}`);
}
eq(missing.length, 0,
  "a migration writes vr_measure_issues and does not declare the pack-generation step" +
  (missing.length ? ` — ${missing[0]}` : ""));
console.log(`      ${files.length} migrations · ${mappingWrites} write the mapping table · ` +
  `${subject} subject to the rule (from ${PACK_STEP_CUTOFF}) · ${declared} declared ` +
  `(${modes.derived} derived, ${modes.purge} purge)`);

// ═════════════════════════════════════════════════════════════════════════════
section("2 · the rule has teeth — the F4 shape, with and without the line");
// ═════════════════════════════════════════════════════════════════════════════
// Synthetic bodies, because the only honest way to prove a gate rejects something
// is to hand it something it must reject. The promote below is F4's own shape: one
// UPDATE, one boolean, no new row.
const PROMOTE = `
-- Federal wave F9 — S. 1234 | housing: secondary → PRIMARY
UPDATE vr_measure_issues
   SET is_primary = true
 WHERE measure_id = 4242 AND issue_key = 'housing';
`;
const FUTURE = "20991231000000_vr_federal_wave_f9.sql";

ok(writesMapping(PROMOTE), "an is_primary UPDATE counts as a mapping write");
ok(isSubject(FUTURE, PROMOTE), "and a future-dated promote is subject to the rule");
eq(packStepOf(PROMOTE).declared, false,
  "a promote with no pack-generation line is REJECTED — this is the CI failure a wave sees");

const WITH_LINE = PROMOTE.replace(
  "-- Federal wave",
  "-- pack-generation: derived — one is_primary flip moves the fingerprint; every\n" +
  "--   affected member's pack retires and rebuilds on next read. Confirmed with\n" +
  "--   scripts/test-vr-pack-key-version.mjs.\n-- Federal wave"
);
const step = packStepOf(WITH_LINE);
ok(step.declared, "the same promote WITH the line passes");
eq(step.mode, "derived", "and is recorded as the derived mode");

eq(packStepOf(PROMOTE.replace("-- Federal", "-- pack-generation: purge — handled\n-- Federal")).declared,
  false, "`purge` that names nothing to purge is not a declaration");
ok(packStepOf(
  PROMOTE.replace("-- Federal",
    "-- pack-generation: purge — deletePack() swept for the 63 mapped members\n-- Federal")
).declared, "`purge` that names how it purges is");

section("   · and does not fire on what it must not fire on");
const PROSE_ONLY = `
-- This wave leaves vr_measure_issues alone; see the F4 note about is_primary.
INSERT INTO vr_measures (id, title) VALUES (1, 'x');
`;
ok(!writesMapping(PROSE_ONLY), "naming the mapping table in a comment is not writing it");
ok(!isSubject(FUTURE, PROSE_ONLY), "so a measures-only migration is not subject");
ok(!isSubject("20260921000000_vr_three_primary_lane_promotes.sql", PROMOTE),
  "and an already-applied promote is grandfathered — an applied migration may not be edited");

section("   · the detector recognises the mapping waves already in the tree");
// If WRITE_RE ever stops matching real SQL, section 1 goes quietly green over an
// empty set. This is the tripwire for that.
ok(mappingWrites > 80,
  `only ${mappingWrites} migrations detected as mapping writes — the detector has gone blind`);
for (const f of ["20261018000000_vr_federal_wave_f4.sql",
                 "20260921000000_vr_three_primary_lane_promotes.sql",
                 "20260920000000_vr_s2_border_security_primary_lane.sql"])
  ok(writesMapping(read(join(MIG_DIR, f))), `${f} is detected as a mapping write`);

// ═════════════════════════════════════════════════════════════════════════════
section("3 · the generators carry the line, so a wave starts with it");
// ═════════════════════════════════════════════════════════════════════════════
// Section 1 catches a migration that shipped without the declaration. That is one
// step too late to be a checklist: by then the header is written and the reviewer
// is reading prose, not a form. Nearly every mapping migration in this tree was
// PRINTED by a script, so the honest place for the line is the printer — a wave
// that starts from a generated header starts with the step already in it, and the
// curator's job is to confirm it rather than to remember it.
//
// The rule is jurisdiction-neutral because the fingerprint is. mappingVersion()
// digests vr_measure_issues, and that table does not record which jurisdiction
// wrote a row: a Utah committee wave retires every affected member's pack exactly
// the way federal wave F4's one-boolean promote did.
//
// AND IT IS A PARTITION, NOT A SEARCH. Every script that emits a mapping write is
// named below in exactly one list, with the reason. A generator that appears in
// neither fails this section — which is the only way "nobody classified the new
// one" is louder than silence.
const SCRIPT_DIR = "scripts";

// Emits SQL that writes the mapping table. Asked of the script's own source, so a
// generator is caught by what it prints.
const EMITS_RE = /(?:insert\s+into|update|delete\s+from)\s+vr_measure_issues/i;

// ACTIVE — can still print a NEW migration, so each must print the declaration.
const ACTIVE = [
  "vr-gen-federal-wave-f6-migration.mjs",
  "vr-gen-federal-wave-f7-migration.mjs",
  "vr-gen-federal-wave-f9-migration.mjs",
  "vr-gen-federal-wave-f11-migration.mjs",
  // The two state lanes. Utah's remaining sessions are a curator pass each
  // (runbook, "Still blocked after wave 3"), so both of these have waves left.
  "vr-utah-ingest.mjs",
  "vr-utah-committee-mapping.mjs",
  // The Utah executive lane. Wave E1 covered 2024GS and 2025GS; the sessions
  // before that, and any later one, are a wave each, so it has waves left.
  "vr-utah-exec-ingest.mjs",
  // The skeleton every future wave starts from, whatever the jurisdiction.
  "vr-mapping-draft.mjs",
];

// RETIRED — its output is an APPLIED migration. Teaching it the line would change
// a file that already shipped (and for some, one that a test byte-compares against
// what shipped), and an applied migration may never be edited. They are listed
// rather than skipped by a pattern: this is a record of a decision, not a hole.
const RETIRED = {
  "vr-gen-house-migration.mjs": "119th House pull — applied",
  "vr-gen-senate-migration.mjs": "119th Senate pull — applied",
  "vr-gen-phase-a-vote-migration.mjs": "Phase A 117th/118th landmarks — applied",
  "vr-gen-landmark-vote-migration.mjs": "landmark pass — applied",
  "vr-gen-israel-vote-migration.mjs": "Support-for-Israel vertical — applied",
  "vr-gen-gun-vote-migration.mjs": "gun-policy pass — applied",
  "vr-gen-elections-vote-migration.mjs": "elections pass — applied",
  "vr-gen-election-vehicle-migration.mjs": "election-vehicle pass — applied",
  "vr-gen-secure-america-migration.mjs": "SAVE/RISAA/ISASA pass — applied",
  "vr-gen-waiver-cra-migration.mjs": "CRA waiver pass — applied",
  "vr-gen-fiscal-enforcement-migration.mjs": "fiscal/enforcement pass — applied",
  "vr-gen-consolidated-approps-migration.mjs": "consolidated-approps pass — applied",
  "vr-gen-federal-depth-migration.mjs": "federal formal-depth pass — applied",
  "vr-gen-federal-wave-f2-migration.mjs": "wave F2 — applied",
  "vr-gen-federal-wave-f3-migration.mjs": "wave F3 — applied",
  "vr-gen-federal-wave-f4-migration.mjs": "wave F4 — applied (the wave that taught us this)",
};

// NOT A GENERATOR — reads mapping SQL, prints none. It names the statements in its
// own parser and its own prose, which is why the detector sees it at all.
const READERS = {
  "vr-pending-mapping-overlay.mjs":
    "parses a pending migration to measure it; writes nothing and emits no SQL",
};

// The marker as the generator will PRINT it: pull the emitted comment out of the
// source line and hold it to the same regex a migration is held to, so a generator
// cannot pass on a misspelt mode or a line that would not survive CI.
const emittedMarker = (src) => {
  for (const line of String(src).split("\n")) {
    if (line.indexOf("pack-generation:") < 0) continue;
    const at = line.indexOf("--");
    if (at < 0) continue;
    const text = line.slice(at).replace(/\\?["'`]\s*\)?\s*;?\s*$/, "").replace(/\\n.*$/, "");
    if (MARKER_RE.test(text)) return text;
  }
  return "";
};

const emitters = readdirSync(join(ROOT, SCRIPT_DIR))
  .filter((f) => f.endsWith(".mjs") && !f.startsWith("test-"))
  .filter((f) => EMITS_RE.test(read(join(SCRIPT_DIR, f))))
  .sort();
must(emitters.length > 15,
  `only ${emitters.length} mapping-SQL generators found — the detector has gone blind`);

const unclassified = emitters.filter(
  (f) => ACTIVE.indexOf(f) < 0 && !RETIRED[f] && !READERS[f]);
eq(unclassified.join(", "), "",
  "every script that emits a mapping write is classified active, retired or a reader");

const silent = [];
for (const f of ACTIVE) {
  const src = read(join(SCRIPT_DIR, f));
  ok(EMITS_RE.test(src), `${f} still emits mapping SQL — if it stopped, move it to RETIRED`);
  const marker = emittedMarker(src);
  if (!marker) { silent.push(f); continue; }
  passed++;
  eq(packStepOf(marker).mode, "derived",
    `${f} prints the derived declaration (a generator cannot know a purge is needed)`);
}
eq(silent.join(", "), "",
  "an ACTIVE generator prints mapping SQL and not the pack-generation declaration");

for (const [f, why] of Object.entries(RETIRED))
  ok(why.length > 8 && EMITS_RE.test(read(join(SCRIPT_DIR, f))),
    `${f} is retired with a reason, and still the generator this list means`);
for (const [f, why] of Object.entries(READERS))
  ok(why.length > 8, `${f} is on the readers list with a reason`);

console.log(`      ${emitters.length} scripts emit mapping SQL · ${ACTIVE.length} active, all declaring · ` +
  `${Object.keys(RETIRED).length} retired (applied output) · ${Object.keys(READERS).length} reader`);

section("   · the teeth: an unclassified generator, and a silent active one");
// Same shape as section 2 — a gate is only proven by what it rejects.
const NEW_GEN = 'const sql = ["INSERT INTO vr_measure_issues (measure_id) VALUES (1);"];\n';
ok(EMITS_RE.test(NEW_GEN), "a brand-new generator is detected by what it prints");
ok(ACTIVE.indexOf("vr-gen-federal-wave-f99-migration.mjs") < 0 &&
   !RETIRED["vr-gen-federal-wave-f99-migration.mjs"] &&
   !READERS["vr-gen-federal-wave-f99-migration.mjs"],
  "…and, being on no list, is REJECTED until someone classifies it");
eq(emittedMarker(NEW_GEN), "", "a generator that prints no declaration reads as silent");
eq(emittedMarker('L.push("-- pack-generation: handled — trust me");\n'), "",
  "…and so does one that invents a third mode");
ok(emittedMarker('  L.push("-- pack-generation: derived — the fingerprint moves with these rows");') !== "",
  "the emitted form the wave generators use is recognised");

// ═════════════════════════════════════════════════════════════════════════════
section("4 · the checklist and the docs name the step");
// ═════════════════════════════════════════════════════════════════════════════
const RUNBOOK = read("db/vr-ingest-runbook.md");
has(RUNBOOK, "pack key must change", "the runbook still carries the sentence");
has(RUNBOOK, "-- pack-generation:", "…and shows the line a migration must carry");
has(RUNBOOK, "test-vr-mapping-migration-pack-step.mjs", "…and names this gate");
has(RUNBOOK, PACK_STEP_CUTOFF, "…and records the cutoff, so the grandfathering is not folklore");
has(RUNBOOK, "derived", "…and the derived mode");
has(RUNBOOK, "purge", "…and the purge mode");
has(RUNBOOK, "jurisdiction-neutral",
  "…and says the rule is not federal-only, which is the half F4's fix left implied");

// THE UTAH HALF OF THE CHECKLIST. The federal wave's run-list has ended on the
// pack line since the scheme shipped; the state lane's did not, and a checklist
// that only one jurisdiction reads is a checklist one promote can walk around.
// Asked of the § Utah half of the document rather than of the whole file, so a
// federal mention cannot answer for it.
const UTAH = RUNBOOK.slice(RUNBOOK.indexOf("## § Utah"));
must(UTAH.length > 5000, "could not find the § Utah half of db/vr-ingest-runbook.md");
has(UTAH, "PACK KEY MUST CHANGE", "the Utah run-list ends on the pack key line too");
has(UTAH, "test-vr-pack-key-version.mjs", "…and names the check that confirms it moved");
has(UTAH, "test-vr-mapping-migration-pack-step.mjs", "…and this gate");
has(UTAH, "pack-generation", "…and the declaration the Utah generator emits");

// The gate is only a gate if the suite runs it.
const PKG = JSON.parse(read("package.json"));
has(PKG.scripts.test, "scripts/test-*.mjs",
  "npm test must glob scripts/test-*.mjs, or this file is a file nobody runs");

// ═════════════════════════════════════════════════════════════════════════════
if (failures.length) {
  console.error(`\n  ✗ ${failures.length} failure(s):\n`);
  for (const f of failures) console.error(`    • ${f}`);
  console.error(`\n  ${passed} passed, ${failures.length} failed\n`);
  process.exit(1);
}
console.log(`\n   ${passed} checks passed`);
console.log("✓ vr-mapping-migration-pack-step: a promote declares what it does to the packs\n");
