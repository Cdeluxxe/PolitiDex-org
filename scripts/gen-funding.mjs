#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-funding.mjs — committee (PAC, party, candidate) money per roster person
// ─────────────────────────────────────────────────────────────────────────────
// The general form of gen-aipac-pac.mjs. That generator sums three named
// pro-Israel PACs for the AIPAC chip; this one sums EVERY committee that
// reported a direct contribution to a roster member's campaign, and files each
// committee under the kind FEC's own committee master gives it. It reads FEC's
// rows by the same rules (fec-core.mjs): transaction type 24K, no memo entries,
// no earmarked conduit money, refunds netted, a committee kept only when its net
// is above zero.
//
//   node scripts/gen-funding.mjs \
//     --pas2 <2024 itpas2.txt> --pas2 <2026 itpas2.txt> \
//     --cm <2024 cm.txt> --cm <2026 cm.txt> \
//     --legislators <legislators-current.json> --legislators <legislators-historical.json> \
//     [--check]
//
// Inputs (all public, none committed — like gen-aipac-pac.mjs, this one is left
// out of scripts/generators.mjs because its --check needs them):
//   itpas2.txt   fec.gov/files/bulk-downloads/<year>/pas2<yy>.zip
//   cm.txt       fec.gov/files/bulk-downloads/<year>/cm<yy>.zip
//   legislators  unitedstates.github.io/congress-legislators
//
// Writes db/person-funding.json, served per person by
// netlify/functions/person-coverage.mts and drawn on the person file as its own
// "Committee money (FEC)" section. The AIPAC chip does not read it and is
// unchanged.
//
// WHAT IT IS NOT. Not individual donors (FEC's itemized individual file is a
// separate, far larger download and is not read here), not independent
// expenditures (super PAC spending is not a contribution), and not a score.
// Figures are FEC's as reported, summed over the cycles named.
// ─────────────────────────────────────────────────────────────────────────────
import { ROOT, writeOrCheck } from "./coverage-core.mjs";
import { rosterBioguide, fecCandidates, netContributions, dropNonPositive, sumCycles, committeeMaster } from "./fec-core.mjs";

const CYCLES = ["2024", "2026"];
const OUT = "db/person-funding.json";
export const TOP = 10;

// The kind a committee is filed under, from FEC's committee master codes.
export const KINDS = {
  corporate: "Corporate PAC",
  labor: "Labor union PAC",
  trade: "Trade association PAC",
  membership: "Membership organization PAC",
  cooperative: "Cooperative PAC",
  leadership: "Leadership PAC",
  party: "Party committee",
  candidate: "Another candidate's committee",
  other: "Other PAC",
};
export function kindOf(c) {
  if (!c) return "other";
  if (c.designation === "P" || c.designation === "A") return "candidate";
  if (["X", "Y", "Z"].includes(c.type)) return "party";
  if (c.designation === "D") return "leadership";
  if (c.orgType === "C" || c.orgType === "W") return "corporate";
  if (c.orgType === "L") return "labor";
  if (c.orgType === "T") return "trade";
  if (c.orgType === "M") return "membership";
  if (c.orgType === "V") return "cooperative";
  return "other";
}
const round = (n) => Math.round(n * 100) / 100;

export function build(people, master, roster) {
  const committees = {};
  const out = {};
  for (const [pid, p] of [...people].sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (roster && !roster.has(pid)) continue;
    const rows = Object.entries(p.pacs).map(([cmte, cyc]) => [cmte, round(sumCycles(cyc))]).filter(([, n]) => n > 0);
    if (!rows.length) continue;
    rows.sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
    const byKind = {};
    for (const [cmte, n] of rows) { const k = kindOf(master.get(cmte)); byKind[k] = round((byKind[k] || 0) + n); }
    const top = rows.slice(0, TOP);
    for (const [cmte] of top) {
      const c = master.get(cmte);
      committees[cmte] = [c && c.name ? c.name : cmte, kindOf(c)];
    }
    out[pid] = { fec: p.fec, total: round(rows.reduce((a, r) => a + r[1], 0)), n: rows.length, kinds: byKind, top };
  }
  const sortedCommittees = {};
  for (const k of Object.keys(committees).sort()) sortedCommittees[k] = committees[k];
  return {
    _comment: `GENERATED by scripts/gen-funding.mjs from FEC bulk files (itpas2.txt and cm.txt, cycles ${CYCLES.join(" + ")}) — do not edit by hand. Direct contributions (transaction type 24K, no memos, no earmarks, refunds netted) from committees to each roster member's campaign, as reported to the FEC. people: roster id → { fec: candidate id, total, n: committees with a net above zero, kinds: total by committee kind, top: [[committee id, net]] largest first }; committees: id → [name as FEC prints it, kind]. Not individual donors, not independent expenditures, not a score.`,
    cycles: CYCLES,
    kinds: KINDS,
    source: "https://www.fec.gov/data/browse-data/?tab=bulk-data",
    committees: sortedCommittees,
    people: out,
  };
}

async function main() {
  const args = process.argv.slice(2);
  const many = (flag) => args.flatMap((a, i) => (a === flag ? [args[i + 1]] : []));
  const pas2 = many("--pas2"), cms = many("--cm"), legs = many("--legislators");
  const check = args.includes("--check");
  if (pas2.length !== CYCLES.length || cms.length < 1 || !legs.length) {
    console.error("usage: --pas2 <2024 itpas2.txt> --pas2 <2026 itpas2.txt> --cm <cm.txt> [--cm …] --legislators <json> [...] [--check]");
    process.exit(2);
  }
  const { rosterIds } = await import("./coverage-core.mjs");
  const fecPid = fecCandidates(legs, rosterBioguide(ROOT));
  const people = dropNonPositive(netContributions(pas2, CYCLES, fecPid, (cmte) => cmte));
  const out = build(people, committeeMaster(cms), rosterIds());
  const okNow = writeOrCheck(OUT, JSON.stringify(out) + "\n", { check });
  if (!check) console.error(`${Object.keys(out.people).length} roster people, ${Object.keys(out.committees).length} committees named`);
  process.exit(okNow ? 0 : 1);
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(e.message || e); process.exit(2); });
