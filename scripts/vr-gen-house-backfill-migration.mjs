#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// PolitiDex Voting Record — House roll-call attribution backfill migration
// ─────────────────────────────────────────────────────────────────────────────
// Emits an additive, idempotent migration that fills MISSING member × roll-call
// cells on roll calls the database already holds, from db/vr-house-evs-backfill-seed.json.
//
// WHAT THIS PASS IS, AND WHAT IT DELIBERATELY IS NOT
// It creates no measure, no roll call, no issue mapping, no stated position and no
// profile. Every roll it touches is looked up by natural key and must already exist;
// every measure behind those rolls already carries curated issue mappings. The only
// thing it writes is vr_member_votes rows, and only for members the app already
// profiles and db/vr-roster-admitted.json already admits.
//
// The gap it closes is a seeding artefact, not a data-source one. Rolls were seeded a
// few hand-listed voters at a time — the roll that passed H.R. 1 arrived with 60 of 432
// recorded voters attributed — so a member could hold a stated position on an issue,
// have voted on six mapped measures under it, and still show an empty record. That is
// the shape that reads as "they never acted here" when in fact we simply never wrote
// the cell down.
//
// EVERY CELL IS A RECORDED VOTE, READ OFF THE CLERK'S OWN DOCUMENT
// The seed is pulled from clerk.house.gov/evs/<year>/roll<NNN>.xml — in most cases the
// very URL vr_rollcalls.source_url already cites. Nothing here is inferred from a party,
// a cosponsorship, a neighbouring vote or a pattern. A member who does not appear in the
// Clerk's recorded-vote list gets no row, and a member whose Bioguide does not resolve
// through db/vr-member-map.json is skipped and counted, never guessed.
//
// ON CONFLICT DO NOTHING IS LOAD-BEARING HERE
// Thousands of cells on these rolls are already stored, and the pull re-checked every
// one of them against the Clerk. The insert must not restate the ones that agree, and —
// more importantly — must not be able to overwrite the seventeen that do not. DO NOTHING
// means this backfill physically cannot launder a wrong stored vote away by rewriting
// it, so the disagreement stays visible and stays somebody's decision rather than a
// silent side effect of a densification pass. The seed's discrepancies block lists them
// member by member and this script reprints them into the migration header.
//
//   node scripts/vr-gen-house-backfill-migration.mjs > netlify/database/migrations/<ts>_vr_house_evs_backfill.sql
//
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { assertSeedPidsMatchMap } from "./vr-seed-pid-guard.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEED_PATH = "db/vr-house-evs-backfill-seed.json";
const seed = JSON.parse(readFileSync(join(ROOT, SEED_PATH), "utf8"));
const memberMap = JSON.parse(readFileSync(join(ROOT, "db", "vr-member-map.json"), "utf8"));

// A seeded politicianId is a cached resolution of a Bioguide, and a cached resolution
// can go stale the moment the map is corrected. Refuse rather than repair.
const pidCheck = assertSeedPidsMatchMap(seed, memberMap, SEED_PATH);

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const L = [];

const cells = seed.votes.reduce((a, v) => a + v.memberVotes.length, 0);
const slugs = new Set();
seed.votes.forEach((v) => v.memberVotes.forEach((r) => slugs.add(r.politicianId)));
const keys = new Set();
seed.votes.forEach((v) => v.issueKeys.forEach((k) => keys.add(k)));
const byCongress = {};
seed.votes.forEach((v) => (byCongress[v.congress] = (byCongress[v.congress] || 0) + 1));

L.push("-- ---------------------------------------------------------------------------");
L.push("-- House roll-call attribution backfill — existing rolls, existing mappings");
L.push("-- ---------------------------------------------------------------------------");
L.push(`-- Generated by scripts/vr-gen-house-backfill-migration.mjs from ${SEED_PATH}.`);
L.push("-- Do not hand-edit: regenerate, or roll forward with a new migration.");
L.push("--");
L.push(`-- ${cells} member votes filled across ${seed.votes.length} roll calls already in the record`);
L.push(`-- ${slugs.size} profiled members gain cells · 0 measures created · 0 issue mappings created`);
L.push(`-- 0 roll calls created · 0 stated positions written · 0 profiles added`);
L.push(`-- Congresses: ${Object.entries(byCongress).map(([c, n]) => `${c} (${n} rolls)`).join(", ")}`);
L.push(`-- ${keys.size} curated issue key(s) already on these measures: ${[...keys].sort().join(", ")}`);
L.push("--");
L.push("-- WHY A BACKFILL AND NOT MORE BILLS");
L.push("-- The record's thinness on these issues was never a shortage of legislation. Every one of");
L.push(`-- these ${seed.votes.length} roll calls is already here and each already carries curated issue mappings;`);
L.push("-- what was missing was people. The rolls were seeded a handful of hand-listed voters at");
L.push("-- a time, so a member could hold a stated position on an issue, have cast a recorded");
L.push("-- vote on six mapped measures under it, and still render as though they had never acted.");
L.push("-- One more bill would not have fixed that for a single one of them.");
L.push("--");
L.push("-- WHERE THE CELLS COME FROM");
L.push("-- clerk.house.gov/evs/<year>/roll<NNN>.xml — for most of these rolls, the document");
L.push("-- vr_rollcalls.source_url already cites. Each was identity-verified before a single cell");
L.push("-- was taken from it: rollcall-num, congress, action-date,");
L.push("-- all four totals-by-vote counts against the recorded votes actually listed, the measure");
L.push("-- number (or its parent's, for amendments), recorded-vote count equal to the totals sum,");
L.push(`-- and a Bioguide on every recorded vote. ${seed.rollsConsidered} rolls were checked; ${seed.rollsRejected} were dropped whole.`);
L.push("-- Nothing here is inferred from a party, a cosponsorship, a neighbouring vote or a");
L.push("-- pattern: a member absent from the Clerk's recorded-vote list");
L.push("-- gets no row, and an unresolvable Bioguide is skipped and counted, never guessed.");
L.push("--");
L.push("-- is_party IS RECOMPUTED, NOT INHERITED");
L.push("-- Each cell's is_party is derived from the full chamber tally in the same document the");
L.push("-- vote was read from — the member's own party's yea/nay split on that roll — so it");
L.push("-- describes where they stood among their colleagues on that vote and nothing else. It");
L.push("-- is a stored fact about the roll, not a score, and nothing in the product ranks on it.");
L.push("--");
L.push(`-- ${seed.discrepancies.rows.length} CELLS THIS MIGRATION REFUSES TO TOUCH`);
L.push(`-- ${seed.storedCellsConfirmed} cells already stored on these rolls were re-read against the Clerk and agree.`);
L.push(`-- ${seed.discrepancies.rows.length} do not:`);
seed.discrepancies.rows.forEach((d) => {
  L.push(`--   ${d.year} roll ${d.roll}: ${d.slug} stored '${d.db}', Clerk says '${d.evs}'`);
});
L.push("-- This migration is ON CONFLICT DO NOTHING throughout, so it cannot overwrite them.");
L.push("-- Correcting a stored vote is a deliberate act with its own citation and belongs in its");
L.push("-- own migration, not in the quiet middle of a densification pass.");
L.push("--");
L.push(`-- Seed → member-map agreement: ${pidCheck.checked} cached politicianId(s) re-checked against`);
L.push("-- db/vr-member-map.json at generation time; 0 stale, 0 unresolvable.");
L.push("");
L.push("DO $$");
L.push("DECLARE");
L.push("  rc BIGINT;");
L.push("BEGIN");

for (const v of seed.votes) {
  const where = `${v.chamber} ${v.congress}/${v.session} roll ${v.rollNumber}`;
  L.push("");
  L.push(`  -- ${where} · ${v.measure} · ${v.question} · ${v.voteDate}`);
  L.push(`  --   ${v.issueKeys.join(", ")}`);
  L.push(`  --   ${v.heldBefore} cell(s) already stored; +${v.memberVotes.length} filled from the Clerk`);
  L.push(`  --   ${v.sourceUrl}`);
  L.push("  SELECT id INTO rc FROM vr_rollcalls");
  L.push(`   WHERE chamber = ${q(v.chamber)} AND congress = ${v.congress} AND session = ${v.session}`);
  L.push(`     AND roll_number = ${v.rollNumber} LIMIT 1;`);
  L.push("  IF rc IS NULL THEN");
  L.push(`    RAISE EXCEPTION 'House EVS backfill: ${where} is not in vr_rollcalls. This pass fills cells on rolls that already exist and creates none.';`);
  L.push("  END IF;");
  L.push("  INSERT INTO vr_member_votes (rollcall_id, politician_id, position, is_party) VALUES");
  L.push(
    v.memberVotes
      .map((r) => `    (rc, ${q(r.politicianId)}, ${q(r.position)}, ${r.isParty ? q(r.isParty) : "NULL"})`)
      .join(",\n")
  );
  L.push("  ON CONFLICT (rollcall_id, politician_id) DO NOTHING;");
}

L.push("END $$;");
L.push("");
process.stdout.write(L.join("\n"));
