#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-aipac-tracker-pages.mjs — AIPAC Tracker pages outside its person listing
// ─────────────────────────────────────────────────────────────────────────────
// Some people AIPAC Tracker covers have a page of their own that is not a card
// on its /tracker listing — /tracker/trump, for one — so gen-aipac-tracker.mjs,
// which reads only that listing, cannot place them and their profile read
// "No data on AIPAC Tracker". Those pages are recorded, reviewed against the
// live page, in db/aipac-tracker-pages.json; this writes them into the
// AIPAC_TRACKER_PAGES block of pdx-aipac.js between its BEGIN/END markers.
//
//   node scripts/gen-aipac-tracker-pages.mjs [--check]
//
// A row is refused if its pid is not on the roster, is already placed by the
// listing generator (that match is correct and is not overridden), has a path
// that is not a plain tracker slug, or carries no figure as printed.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BEGIN = "  // BEGIN AIPAC_TRACKER_PAGES (generated by scripts/gen-aipac-tracker-pages.mjs — do not edit by hand)\n";
const END = "  // END AIPAC_TRACKER_PAGES\n";
const check = process.argv.includes("--check");

const rec = JSON.parse(readFileSync(join(ROOT, "db/aipac-tracker-pages.json"), "utf8"));
const w = {}; w.window = w;
vm.runInNewContext(readFileSync(join(ROOT, "cmp-data.js"), "utf8"), w, { filename: "cmp-data.js" });
const roster = w.CMP_DATA || {};
const path = join(ROOT, "pdx-aipac.js");
const src = readFileSync(path, "utf8");
const listed = new Set([...src.slice(src.indexOf("var AIPAC_TRACKER = {"), src.indexOf("// END AIPAC_TRACKER\n"))
  .matchAll(/^    ([a-z0-9_]+): \['/gm)].map((m) => m[1]));

const q = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
const bad = [];
const rows = [...rec.rows].sort((a, b) => (a.pid < b.pid ? -1 : 1)).filter((r) => {
  const why = !roster[r.pid] ? "not a roster id"
    : listed.has(r.pid) ? "already placed by the listing generator"
    : !/^[a-z0-9-]+$/.test(r.path || "") ? "bad path"
    : !/^\d{4}-\d{2}-\d{2}$/.test(r.asOf || "") ? "bad asOf"
    : !r.printed || !/^\$\d[\d,.]*[KMB]?\+?$/.test(r.display || "") || !r.spoken ? "missing figure" : "";
  if (why) bad.push(`${r.pid}: ${why}`);
  return !why;
});
if (bad.length) { console.error(bad.join("\n")); process.exit(1); }

const block = BEGIN +
  "  // AIPAC Tracker pages that are not cards on its /tracker listing, so the\n" +
  "  // listing generator cannot place them. Per roster person: [the page path\n" +
  "  // under /tracker/, the headline figure as a short line, the same figure in\n" +
  "  // words for the accessible name, the date it was read]. From\n" +
  "  // db/aipac-tracker-pages.json; the tracker's figures, not this site's.\n" +
  "  var AIPAC_TRACKER_PAGES = {\n" +
  rows.map((r) => `    ${r.pid}: [${q(r.path)}, ${q(r.display)}, ${q(r.spoken)}, ${q(r.asOf)}]`).join(",\n") +
  "\n  };\n" + END;
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a < 0 || b < a) { console.error("pdx-aipac.js has no AIPAC_TRACKER_PAGES markers"); process.exit(1); }
const next = src.slice(0, a) + block + src.slice(b + END.length);
if (check) { if (next !== src) { console.error("AIPAC_TRACKER_PAGES block is stale"); process.exit(1); } console.error("AIPAC_TRACKER_PAGES block is current"); }
else { writeFileSync(path, next); console.error(`${rows.length} tracker page(s) written`); }
