#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-same-text.mjs — same-text families, for the scorer, the drawer and the
// bill page
// ─────────────────────────────────────────────────────────────────────────────
// WHAT THIS WRITES
//
//   voting-record.js   the block between the SAME_TEXT markers: which measures
//                      carry the same operative text, which of them are counted,
//                      each one's outcome and page, and the Related list. The
//                      record client reads it at intake (noteMember) to hold a
//                      repeat vote out of every scored list unless it is that
//                      member's only record of that position on the text, and the
//                      issue drawer prints its History and Related sections from it.
//
//   bill-official.json's `same` — the same table, for the bill panel on /b/
//                      pages, which do not load voting-record.js. Written by
//                      gen-bill-docs.mjs, which calls sameTextTable() below, so a
//                      pass that changes a bill page cannot leave the table behind.
//
// WHERE IT READS FROM. db/vr-text-families.json (the curated families) and the
// bill documents gen-bill-docs.mjs builds: each member's outcome is its page's
// own status and the record's own vote action, never composed; Related is every
// other bill page that lists at least two of the family's topics.
//
// USAGE
//   node scripts/gen-same-text.mjs           # rewrite the voting-record.js block
//   node scripts/gen-same-text.mjs --check   # exit 1 if it is stale
// ─────────────────────────────────────────────────────────────────────────────
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { billDocs } from "./gen-bill-docs.mjs";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const START = "  // ── SAME_TEXT (generated by scripts/gen-same-text.mjs — do not edit by hand) ──";
const END = "  // ── /SAME_TEXT ──";

const GROUP = { enacted: "enacted", vetoed: "failed", failed: "failed", passed_both: "passed", passed_house: "passed",
  passed_senate: "passed", adopted: "passed", confirmed: "passed" };
export const billHref = (sitting, number) => `/b/${sitting}/${encodeURIComponent(number)}`;

// The record's own vote action, cut to its question and tally: "Motion to
// discharge … rejected by Yea-Nay Vote. 46 - 51." → "discharge rejected 46-51".
function voteOf(h) {
  for (const a of h || []) {
    const x = String(a.x || ""), t = /(\d+)\s*-\s*(\d+)/.exec(x);
    if (!t) continue;
    const tally = `${t[1]}-${t[2]}`;
    let what = "";
    if (/Motion to discharge .* rejected/i.test(x)) what = "discharge rejected";
    else if (/discharged by Yea-Nay/i.test(x)) what = "discharged";
    else if (/Motion to proceed .* rejected/i.test(x)) what = "motion to proceed rejected";
    else if (/Failed of passage/i.test(x)) what = "failed of passage";
    else if (/Agreed to|Passed/i.test(x)) what = "passed";
    else continue;
    return { date: a.d, what, tally };
  }
  return null;
}

export function sameTextTable(root, docs) {
  const fam = JSON.parse(fs.readFileSync(path.join(root, "db/vr-text-families.json"), "utf8")).families;
  const out = { families: {}, byMeasure: {} };
  for (const f of fam) {
    const members = f.members.map((m) => {
      const key = `${m.congress}|${m.number}`, d = docs[key];
      if (!d) throw new Error(`gen-same-text: ${key} has no bill document`);
      const votes = [];
      const h = (d.h || []).map((a) => ({ d: a.d, x: a.x }));
      for (let i = 0; i < h.length; i++) { const v = voteOf([h[i]]); if (v) votes.push(v); }
      return {
        key, number: m.number, sitting: String(m.congress), counted: !!m.counted,
        status: GROUP[d.st] || "pending", votes, href: billHref(String(m.congress), m.number),
      };
    });
    const keys = new Set(members.map((m) => m.key));
    const related = Object.values(docs)
      .filter((d) => !keys.has(`${d.s}|${d.n}`))
      .map((d) => ({ d, shared: (d.m || []).map((x) => x.k).filter((k) => f.topics.includes(k)) }))
      .filter((x) => x.shared.length >= 2)
      .map(({ d, shared }) => {
        const last = (d.h || []).map((a) => a.d).filter(Boolean).sort().pop() || "";
        return { key: `${d.s}|${d.n}`, number: d.n, sitting: d.s, title: d.t || "", status: GROUP[d.st] || "pending",
          shared: f.topics.filter((k) => shared.includes(k)), last, href: billHref(d.s, d.n) };
      })
      .sort((a, b) => b.shared.length - a.shared.length || b.last.localeCompare(a.last) || a.key.localeCompare(b.key));
    out.families[f.id] = { label: f.label, topics: f.topics, members, related };
    for (const m of members) out.byMeasure[m.key] = f.id;
  }
  return out;
}

export function renderBlock(table) {
  return `${START}
  // Same operative text, voted on more than once (db/vr-text-families.json). A
  // member's vote on a repeat (counted: false) is held out of every scored list
  // unless it is that member's only record of that position on the text; the
  // drawer lists every vote in its History section instead.
  var SAME_TEXT = ${JSON.stringify(table)};
${END}`;
}

if (import.meta.url === url.pathToFileURL(process.argv[1]).href) {
  const block = renderBlock(sameTextTable(ROOT, billDocs(ROOT)));
  const file = path.join(ROOT, "voting-record.js");
  const src = fs.readFileSync(file, "utf8");
  const a = src.indexOf(START), b = src.indexOf(END);
  if (a < 0 || b < 0) { console.error("✗ voting-record.js has no SAME_TEXT markers"); process.exit(2); }
  const next = src.slice(0, a) + block + src.slice(b + END.length);
  if (process.argv.includes("--check")) {
    if (next !== src) { console.error("✗ voting-record.js's SAME_TEXT block is stale — run node scripts/gen-same-text.mjs"); process.exit(1); }
    console.log("✓ voting-record.js's SAME_TEXT block is current");
  } else {
    fs.writeFileSync(file, next);
    console.log("wrote voting-record.js SAME_TEXT block");
  }
}
