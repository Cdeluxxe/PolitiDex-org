function wrap(text, prefix, width = 74) {
  const out = []; let line = "";
  for (const w of String(text).split(/\s+/)) {
    if (line && (line + " " + w).length > width) { out.push(prefix + line); line = w; } else line = line ? line + " " + w : w;
  }
  if (line) out.push(prefix + line);
  return out;
}

