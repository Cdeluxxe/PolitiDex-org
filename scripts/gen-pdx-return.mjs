#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-pdx-return.mjs — PDXReturn, for documents that do not load the picker
// ─────────────────────────────────────────────────────────────────────────────
// window.PDXReturn is OWNED by voter-hub-location.js and is written there and
// nowhere else. That file is 240 KB and boots a location picker, and a district
// board deliberately does not load it (it has no "where do you vote" answer of
// its own to give). But every board has a door that needs the return intent —
// "Join the People" in the chrome, and "Sign in to start" under SD-3's composer
// — and spelling `next` a second time on the board would be a second answer.
//
// So this copies the ONE IIFE, byte for byte, into /pdx-return.js. It is not a
// second owner: nobody edits pdx-return.js, the suite fails on any drift, and a
// change to PDXReturn is made in voter-hub-location.js and re-copied here.
//
//   node scripts/gen-pdx-return.mjs          write pdx-return.js
//   node scripts/gen-pdx-return.mjs --check  exit 1 if it would change
// ─────────────────────────────────────────────────────────────────────────────

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OPEN = "window.PDXReturn = (function () {";
const CLOSE = "\n  })();";

export function returnSlice(src) {
  const at = src.indexOf(OPEN);
  if (at < 0) throw new Error("gen-pdx-return: voter-hub-location.js no longer declares window.PDXReturn");
  const end = src.indexOf(CLOSE, at);
  if (end < 0) throw new Error("gen-pdx-return: the PDXReturn IIFE has no closing line");
  return src.slice(at, end + CLOSE.length);
}

export function renderReturn(src = readFileSync(join(ROOT, "voter-hub-location.js"), "utf8")) {
  return (
    "/* ═══════════════════════════════════════════════════════════════════════════\n" +
    "   pdx-return.js — GENERATED by scripts/gen-pdx-return.mjs. DO NOT EDIT.\n" +
    "   ───────────────────────────────────────────────────────────────────────────\n" +
    "   window.PDXReturn, copied byte for byte from voter-hub-location.js, which\n" +
    "   owns it. Loaded by the district boards that do not load that file, so\n" +
    "   their sign-in doors carry the same `next` intent /find already uses.\n" +
    "   ═══════════════════════════════════════════════════════════════════════════ */\n" +
    "(function () {\n" +
    "  if (window.PDXReturn) return;\n" +
    "  " + returnSlice(src) + "\n" +
    "})();\n"
  );
}

function main() {
  const check = process.argv.includes("--check");
  const p = join(ROOT, "pdx-return.js");
  const body = renderReturn();
  const cur = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (cur === body) { console.log("gen-pdx-return: up to date"); return; }
  if (check) { console.log("gen-pdx-return: pdx-return.js is out of date — run node scripts/gen-pdx-return.mjs"); process.exit(1); }
  writeFileSync(p, body);
  console.log("gen-pdx-return: wrote pdx-return.js");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
