#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-reader-rationale.mjs — the bill panel's rationale scrubber, for bill.html
// ─────────────────────────────────────────────────────────────────────────────
// window._pdxReaderRationale is OWNED by receipt-cards.js and is written there
// and nowhere else. It is the one function that decides whether a stored
// mapping rationale may be shown to a reader: it drops every sentence that is a
// curators' note (weights, flags, filing) and leaves the reader's sentence
// untouched. bill-detail.js prints the "More" text under a topic only through
// it, and prints nothing when it is absent.
//
// receipt-cards.js is 239 KB of share-card machinery, and bill.html — the /b/
// document — does not load it. So the panel on a /b/ page never had the
// scrubber, and the longer text behind "More" never appeared there.
//
// This copies the scrubber's ONE contiguous block — tidyRemainder through
// readerRationale, byte for byte — into /reader-rationale.js. It is not a second
// owner: nobody edits reader-rationale.js, the suite fails on any drift, and a
// change to the scrubber is made in receipt-cards.js and re-copied here.
//
//   node scripts/gen-reader-rationale.mjs          write reader-rationale.js
//   node scripts/gen-reader-rationale.mjs --check  exit 1 if it would change
// ─────────────────────────────────────────────────────────────────────────────

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "reader-rationale.js");
const OPEN = "  function tidyRemainder(s) {";
const CLOSE = "    return LEDGER_SENTENCE_RE.test(out) ? '' : out;\n  }\n";

export function rationaleSlice(src) {
  const at = src.indexOf(OPEN);
  if (at < 0) throw new Error("gen-reader-rationale: receipt-cards.js no longer declares tidyRemainder");
  const end = src.indexOf(CLOSE, at);
  if (end < 0) throw new Error("gen-reader-rationale: readerRationale no longer ends where it did");
  const slice = src.slice(at, end + CLOSE.length);
  if (!slice.includes("function readerRationale(raw) {")) throw new Error("gen-reader-rationale: the slice does not hold readerRationale");
  return slice;
}

export function renderRationale(src = readFileSync(join(ROOT, "receipt-cards.js"), "utf8")) {
  return (
    "/* ═══════════════════════════════════════════════════════════════════════════\n" +
    "   reader-rationale.js — GENERATED by scripts/gen-reader-rationale.mjs. DO NOT EDIT.\n" +
    "   ───────────────────────────────────────────────────────────────────────────\n" +
    "   receipt-cards.js's rationale scrubber (tidyRemainder through\n" +
    "   readerRationale), copied byte for byte so bill.html's panel can print the\n" +
    "   longer topic text behind \"More\" without loading 239 KB of share cards.\n" +
    "   Edit receipt-cards.js and re-run the generator; scripts/test-bill-b-more.mjs\n" +
    "   fails on any drift. Defines window._pdxReaderRationale only when\n" +
    "   receipt-cards.js has not already defined it.\n" +
    "   ═══════════════════════════════════════════════════════════════════════════ */\n" +
    "(function () {\n" +
    "  'use strict';\n" +
    "  if (typeof window._pdxReaderRationale === 'function') return;\n" +
    rationaleSlice(src) +
    "  window._pdxReaderRationale = readerRationale;\n" +
    "})();\n"
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = renderRationale();
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (cur !== out) { console.error("✗ reader-rationale.js is stale — run node scripts/gen-reader-rationale.mjs"); process.exit(1); }
    console.log("✓ reader-rationale.js is current");
  } else {
    writeFileSync(OUT, out);
    console.log(`wrote reader-rationale.js (${out.length} bytes)`);
  }
}
