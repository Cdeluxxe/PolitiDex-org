#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// PolitiDex Voting Record — Senate roll-call attribution backfill migration
// ─────────────────────────────────────────────────────────────────────────────
// Emits an additive, idempotent migration that fills MISSING member × roll-call cells
// on Senate roll calls the database already holds, from db/vr-senate-lis-backfill-seed.json.
//
// The House twin of this script (scripts/vr-gen-house-backfill-migration.mjs) closes a
// seeding gap. This one closes an identity gap as well: the ingest resolves a member
// only through db/vr-member-map.json, that map is derived from the curated portrait
// shelf, and the shelf carried no photo for fifty-five sitting senators — the chairs
// and ranking members of Appropriations, Armed Services, Agriculture, Commerce, Energy
// & Natural Resources, Environment & Public Works, Finance, HELP, Homeland Security,
// Intelligence and Veterans' Affairs among them. Those senators could not be attributed
// a vote at all, however many roll calls were ingested, so their profiles read as
// though they had barely voted while their colleagues showed a full record.
//
// It creates no measure, no roll call, no issue mapping, no stated position and no
// profile. Every roll it touches is looked up by natural key and must already exist;
// every measure behind those rolls already carries curated issue mappings.
//
// EVERY CELL IS A RECORDED VOTE, READ OFF THE SENATE'S OWN DOCUMENT
// The seed is pulled from senate.gov's LIS roll-call XML. Identity runs through three
// published identifiers and no name matching: <lis_member_id> → Bioguide (via the
// congress-legislators datasets) → profile slug (via the member map). An LIS id that
// does not resolve is skipped and counted, never guessed.
//
// ON CONFLICT DO NOTHING IS LOAD-BEARING HERE
// Thousands of cells on these rolls are already stored and the pull re-checked every
// one of them against the Senate's document. The insert must not restate the ones that
// agree and must not be able to overwrite the ones that do not, so a disagreement stays
// visible instead of being laundered away by a densification pass.
//
//   node scripts/vr-gen-senate-lis-backfill-migration.mjs > netlify/database/migrations/<ts>_vr_senate_lis_backfill.sql
//
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { assertSeedPidsMatchMap } from "./vr-seed-pid-guard.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEED_PATH = "db/vr-senate-lis-backfill-seed.json";
const seed = JSON.parse(readFileSync(join(ROOT, SEED_PATH), "utf8"));
const memberMap = JSON.parse(readFileSync(join(ROOT, "db", "vr-member-map.json"), "utf8"));

// A seeded politicianId is a cached resolution of a Bioguide, and a cached resolution
// can go stale the moment the map is corrected. Refuse rather than repair.
const pidCheck = assertSeedPidsMatchMap(seed, memberMap, SEED_PATH);

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const L = [];

const cells = seed.votes.reduce((a, v) => a + v.memberVotes.length, 0);
const slugs = new Set();
seed.votes.forEach((v) => v.memberVotes.forEach((r) => slugs.add(r.politicianId)));
const keys = new Set();
seed.votes.forEach((v) => v.issueKeys.forEach((k) => keys.add(k)));
const byCongress = {};
seed.votes.forEach((v) => (byCongress[v.congress] = (byCongress[v.congress] || 0) + 1));

L.push("-- ---------------------------------------------------------------------------");
L.push("-- Senate roll-call attribution backfill — existing rolls, existing mappings");
L.push("-- ---------------------------------------------------------------------------");
L.push(`-- Generated by scripts/vr-gen-senate-lis-backfill-migration.mjs from ${SEED_PATH}.`);
L.push("-- Do not hand-edit: regenerate, or roll forward with a new migration.");
L.push("--");
L.push(`-- ${cells} member votes filled across ${seed.votes.length} roll calls already in the record`);
L.push(`-- ${slugs.size} profiled members gain cells · 0 measures created · 0 issue mappings created`);
L.push("-- 0 roll calls created · 0 stated positions written · 0 profiles added");
L.push(`-- Congresses: ${Object.entries(byCongress).map(([c, n]) => `${c} (${n} rolls)`).join(", ")}`);
L.push(`-- ${keys.size} curated issue key(s) already on these measures: ${[...keys].sort().join(", ")}`);
L.push("--");
L.push("-- WHY THE SENATE WAS THIN");
L.push("-- Not for want of roll calls: every one of these is already here and already carries");
L.push("-- curated issue mappings. The ingest attributes a vote only to a member in");
L.push("-- db/vr-member-map.json, that map is read out of the curated portrait shelf, and the");
L.push("-- shelf had no photo for fifty-five sitting senators — including the chairs and ranking");
L.push("-- members of Appropriations, Armed Services, Agriculture, Commerce, Energy & Natural");
L.push("-- Resources, Environment & Public Works, Finance, HELP, Homeland Security, Intelligence");
L.push("-- and Veterans' Affairs. A senator with no face could not be attributed a vote at all,");
L.push("-- so the people who run the committees were the people whose records looked emptiest.");
L.push("--");
L.push("-- WHERE THE CELLS COME FROM");
L.push("-- senate.gov's LIS roll-call XML — the Secretary of the Senate's own document. Each was");
L.push("-- identity-verified before a cell was taken from it: congress, session, vote_number, the");
L.push("-- measure the document says it is about (or its parent, or — for a nomination filed under");
L.push("-- a human label — the nominee's surname AND the office they were confirmed to), the");
L.push("-- document's own yea/nay/present/absent counts against the members it actually lists, an");
L.push(`-- LIS id on every member, and a vote_cast vocabulary we recognise. ${seed.rollsConsidered} rolls were checked;`);
L.push(`-- ${seed.rollsRejected} were dropped whole:`);
seed.rejectedRolls.rows.forEach((r) => {
  L.push(`--   ${r.congress}/${r.session} roll ${r.roll ?? "(none stored)"}${r.measure ? ` · ${r.measure}` : ""}: ${r.why.join("; ")}`);
});
L.push(`-- A further ${seed.rollsAlreadyComplete} verified roll(s) are already complete and appear here not at all: every`);
L.push("-- member their document lists is a cell we already hold. Kept + refused + complete closes");
L.push("-- on the number considered, so nothing was dropped without saying so.");
L.push("--");
L.push("-- IDENTITY RUNS THROUGH PUBLISHED IDENTIFIERS, NOT NAMES");
L.push("-- <lis_member_id> → Bioguide (congress-legislators, current and historical) → profile");
L.push("-- slug (db/vr-member-map.json). No name matching, no state-and-party inference. An LIS id");
L.push("-- that does not resolve is skipped and counted, never guessed.");
L.push("--");
L.push("-- is_party IS RECOMPUTED, NOT INHERITED");
L.push("-- Each cell's is_party is derived from the full chamber tally in the same document the");
L.push("-- vote was read from — the member's own party's yea/nay split on that roll — so it");
L.push("-- describes where they stood among their colleagues on that vote and nothing else. It");
L.push("-- is a stored fact about the roll, not a score, and nothing in the product ranks on it.");
L.push("--");
L.push(`-- ${seed.discrepancies.rows.length} CELL(S) THIS MIGRATION REFUSES TO TOUCH`);
L.push(`-- ${seed.storedCellsConfirmed} cells already stored on these rolls were re-read against the Senate's`);
L.push(`-- document and agree. ${seed.discrepancies.rows.length} do not:`);
seed.discrepancies.rows.forEach((d) => {
  L.push(`--   ${d.congress}/${d.session} roll ${d.roll}: ${d.slug} stored '${d.db}', document says '${d.lis}'`);
});
L.push("-- This migration is ON CONFLICT DO NOTHING throughout, so it cannot overwrite them.");
L.push("-- Correcting a stored vote is a deliberate act with its own citation and belongs in its");
L.push("-- own migration, not in the quiet middle of a densification pass.");
L.push("--");
L.push(`-- Seed → member-map agreement: ${pidCheck.checked} cached politicianId(s) re-checked against`);
L.push("-- db/vr-member-map.json at generation time; 0 stale, 0 unresolvable.");
L.push("");
L.push("DO $$");
L.push("DECLARE");
L.push("  rc BIGINT;");
L.push("BEGIN");

for (const v of seed.votes) {
  const where = `${v.chamber} ${v.congress}/${v.session} roll ${v.rollNumber}`;
  L.push("");
  L.push(`  -- ${where} · ${v.measure} · ${v.question} · ${v.voteDate}`);
  L.push(`  --   ${v.issueKeys.join(", ")}`);
  L.push(`  --   ${v.heldBefore} cell(s) already stored; +${v.memberVotes.length} filled from the Senate's document`);
  L.push(`  --   ${v.sourceUrl}`);
  L.push("  SELECT id INTO rc FROM vr_rollcalls");
  L.push(`   WHERE chamber = ${q(v.chamber)} AND congress = ${v.congress} AND session = ${v.session}`);
  L.push(`     AND roll_number = ${v.rollNumber} LIMIT 1;`);
  L.push("  IF rc IS NULL THEN");
  L.push(`    RAISE EXCEPTION 'Senate LIS backfill: ${where} is not in vr_rollcalls. This pass fills cells on rolls that already exist and creates none.';`);
  L.push("  END IF;");
  L.push("  INSERT INTO vr_member_votes (rollcall_id, politician_id, position, is_party) VALUES");
  L.push(
    v.memberVotes
      .map((r) => `    (rc, ${q(r.politicianId)}, ${q(r.position)}, ${r.isParty ? q(r.isParty) : "NULL"})`)
      .join(",\n")
  );
  L.push("  ON CONFLICT (rollcall_id, politician_id) DO NOTHING;");
}

L.push("END $$;");
L.push("");
process.stdout.write(L.join("\n"));
