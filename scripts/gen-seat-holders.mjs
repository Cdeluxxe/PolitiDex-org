#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-seat-holders.mjs — who holds every seat that has a board
// ─────────────────────────────────────────────────────────────────────────────
// Writes netlify/lib/seat-holders.mjs: one row per composer seat (the keys of
// COMPOSER_SEATS in netlify/lib/district-board-voice-core.mjs), naming the
// roster's sitting member — the pid the general room keys new comments to —
// and every PREVIOUS holder this table has recorded for that seat.
//
// THE ROSTER, THE SAME JOINS THE BOARDS USE. A State House or State Senate seat
// asks window.pdxSeatedMemberFor(seat, n); a U.S. House seat asks
// window._pdxUsHouseSeat('Utah', n); the governor and the two U.S. Senate seats
// come from gen-district-boards.mjs's own plan. The name is cmp-data.js's.
//
// A ROSTER CHANGE IS HISTORY, NOT AN EDIT. The table on disk is read first and
// rolled forward with rollHolders(): an outgoing holder moves into `previous`,
// so their general thread stays reachable, and the incoming one starts empty.
// Run it after the roster moves; never hand-edit a pid.
//
//   node scripts/gen-seat-holders.mjs          write the table
//   node scripts/gen-seat-holders.mjs --check  exit 1 if it would change
// ─────────────────────────────────────────────────────────────────────────────
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { makeSandbox } from "./gen-hero-showcase.mjs";
import { planBoards } from "./gen-district-boards.mjs";
import { COMPOSER_SEATS } from "../netlify/lib/district-board-voice-core.mjs";
import { rollHolders } from "../netlify/lib/general-room-core.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => readFileSync(join(ROOT, f), "utf8");
export const OUT = "netlify/lib/seat-holders.mjs";

function loadRoster() {
  const win = makeSandbox();
  const ctx = vm.createContext(win);
  for (const f of ["cmp-data.js", "voter-hub-location.js", "seated-member.js"]) vm.runInContext(R(f), ctx, { filename: f });
  return win;
}

// seat → { pid, name } for every composer seat the roster names.
export function rosterHolders() {
  const win = loadRoster();
  const RO = win.CMP_DATA || {};
  const statewide = {};
  for (const b of planBoards().boards) if (b.statewide) statewide[b.seat] = b.pid;
  const out = {};
  for (const seat of Object.keys(COMPOSER_SEATS)) {
    let pid = "";
    const m = /^ut-(statehouse|statesenate|house)-(\d+)$/.exec(seat);
    if (m && m[1] === "house") pid = win._pdxUsHouseSeat("Utah", Number(m[2])) || "";
    else if (m) pid = win.pdxSeatedMemberFor(seat, Number(m[2])) || "";
    else pid = statewide[seat] || "";
    if (pid && RO[pid]) out[seat] = { pid, name: String(RO[pid].name || pid) };
  }
  return out;
}

async function onDisk() {
  try {
    const mod = await import(join(ROOT, OUT) + `?t=${Date.now()}`);
    return mod.SEAT_HOLDERS || {};
  } catch {
    return {};
  }
}

export function render(table) {
  const lines = [
    "// @generated by scripts/gen-seat-holders.mjs — do not edit by hand; run it after the roster moves.",
    "// seat → the sitting member (the pid general comments are keyed to now) and",
    "// every previous holder, newest first, whose general thread stays readable.",
    "export const SEAT_HOLDERS = {",
  ];
  for (const seat of Object.keys(table).sort()) {
    const h = table[seat];
    lines.push(`  ${JSON.stringify(seat)}: ${JSON.stringify({ pid: h.pid, name: h.name, previous: h.previous || [] })},`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

async function main() {
  const next = render(rollHolders(await onDisk(), rosterHolders()));
  let cur = "";
  try { cur = R(OUT); } catch { cur = ""; }
  if (process.argv.includes("--check")) {
    if (cur !== next) { console.error(`gen-seat-holders: ${OUT} is out of date`); process.exit(1); }
    console.log("gen-seat-holders: up to date");
    return;
  }
  writeFileSync(join(ROOT, OUT), next);
  console.log(`gen-seat-holders: wrote ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
