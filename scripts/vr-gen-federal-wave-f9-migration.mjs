//    propagate into a member-vote insert.
//
// 3. EVERY vr_measure_issues ROW CARRIES A pack-generation COMMENT. The pack
//    fingerprint moves with these rows, so the comment sits beside each row rather
//    than once in the header.
//
// 4. THE DECLINES ARE EMITTED AS COMMENTS, IN FULL. A key considered on this text
//    and refused is part of the record; a later wave reading only the SQL has to be
//    able to see that the question was asked.
