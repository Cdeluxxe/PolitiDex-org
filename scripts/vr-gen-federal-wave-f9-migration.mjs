const wrap = (text, width, lead) => {
  const words = String(text).split(/\s+/);
  const lines = []; let cur = "";
  for (const w of words) {
    if (cur && (cur + " " + w).length > width) { lines.push(cur); cur = w; } else cur = cur ? cur + " " + w : w;
  }
  if (cur) lines.push(cur);
  return lines.map((l) => lead + l).join("\n");
};

