#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// gen-roster-changes.mjs — the roster-seat lane of the public "what changed" feed
// ─────────────────────────────────────────────────────────────────────────────
// The roster seat files (roster-seats/<state>.js, scripts/gen-roster-seats.mjs)
// say who holds each seat today, but not what moved. This keeps two committed
// files:
//   db/roster-seat-snapshot.json  every seat row as of the last run
//   db/roster-changes.json        a dated log of what differed between runs:
//                                 a person added to or removed from a state's
//                                 seat file, or one of their seat fields changed
//
//   node scripts/gen-roster-changes.mjs [--date YYYY-MM-DD]   log + re-snapshot
//   node scripts/gen-roster-changes.mjs --check               exit 1 when the
//                                 seat files differ from the snapshot
//   node scripts/gen-roster-changes.mjs --git-history <base-rev>
//                                 one-off seeding: replay every commit after
//                                 <base-rev> that touched roster-seats/, each
//                                 change dated by its commit, then snapshot
//
// Registered in scripts/generators.mjs after gen-roster-seats.mjs, so the
// freshness run logs a seat change the same pass that writes it. --check reads
// only the repo. netlify/functions/changes-feed.mts serves the newest entries,
// each labelled with the seat file it came from. Read-only to readers.
// ─────────────────────────────────────────────────────────────────────────────
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import vm from "node:vm";
import { ROOT, sortKeys, writeOrCheck } from "./coverage-core.mjs";

const SNAP = "db/roster-seat-snapshot.json";
const LOG = "db/roster-changes.json";
export const MAX_ENTRIES = 1000;
export const FIELDS = ["name", "office", "state", "district", "position", "party", "rank"];

const titleCase = (slug) => slug.split("-").map((w) => (w === "of" ? w : w[0].toUpperCase() + w.slice(1))).join(" ");

// One seat file's source → { pid: row }.
export function rowsOf(src) {
  const w = {}; w.window = w;
  vm.runInNewContext(src, w, { filename: "seat.js" });
  const out = {};
  for (const [pid, r] of Object.entries(w.PDX_SEAT_ROSTER || {})) {
    const row = {};
    for (const f of FIELDS) if (r[f] != null && r[f] !== "") row[f] = r[f];
    out[pid] = row;
  }
  return out;
}

// Every seat file → { state: { pid: row } }. `read(state)` returns a file's source.
export function seatsFrom(states, read) {
  const out = {};
  for (const s of states) { const src = read(s); if (src != null) out[s] = rowsOf(src); }
  return out;
}
const currentStates = (root = ROOT) => readdirSync(join(root, "roster-seats")).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)).sort();

// Snapshot A → snapshot B, as log entries dated `date`.
export function diff(a, b, date) {
  const out = [];
  for (const state of [...new Set([...Object.keys(a), ...Object.keys(b)])].sort()) {
    const A = a[state] || {}, B = b[state] || {};
    for (const pid of [...new Set([...Object.keys(A), ...Object.keys(B)])].sort()) {
      const was = A[pid], now = B[pid];
      const base = { date, pid, state, stateName: titleCase(state) };
      if (!was && now) out.push({ ...base, change: "added", name: now.name || pid, office: now.office || "", seat: now.state || "" });
      else if (was && !now) out.push({ ...base, change: "removed", name: was.name || pid, office: was.office || "", seat: was.state || "" });
      else {
        const fields = FIELDS.filter((f) => String(was[f] ?? "") !== String(now[f] ?? ""));
        if (fields.length) out.push({ ...base, change: "updated", name: now.name || pid, office: now.office || "", seat: now.state || "", fields, before: Object.fromEntries(fields.map((f) => [f, was[f] ?? null])), after: Object.fromEntries(fields.map((f) => [f, now[f] ?? null])) });
      }
    }
  }
  return out;
}

const render = (log) => JSON.stringify(log, null, 1) + "\n";
const emptyLog = () => ({
  _comment: "GENERATED by scripts/gen-roster-changes.mjs — do not edit by hand. Dated changes to the roster seat files (roster-seats/<state>.js): a person added to or removed from a state's seat file, or a seat field (name, office, seat, district, position, party, rank) changed, newest first. The roster-seat lane of the public /changes feed.",
  changes: [],
});

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const flag = (f) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : null; };
  const now = seatsFrom(currentStates(), (s) => readFileSync(join(ROOT, "roster-seats", s + ".js"), "utf8"));
  const snapText = JSON.stringify(sortKeys(now)) + "\n";

  if (check) {
    const prev = existsSync(join(ROOT, SNAP)) ? readFileSync(join(ROOT, SNAP), "utf8") : null;
    if (prev !== snapText) { console.error("roster seat snapshot is stale (a seat file changed since the last log entry)"); process.exit(1); }
    if (!existsSync(join(ROOT, LOG))) { console.error(`${LOG} is missing`); process.exit(1); }
    process.exit(0);
  }

  const log = existsSync(join(ROOT, LOG)) ? JSON.parse(readFileSync(join(ROOT, LOG), "utf8")) : emptyLog();
  let added = [];
  const base = flag("--git-history");
  if (base) {
    const git = (...a) => execFileSync("git", a, { cwd: ROOT, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
    const revs = git("rev-list", "--reverse", `${base}..HEAD`, "--", "roster-seats/").split("\n").filter(Boolean);
    const at = (rev) => {
      const files = git("show", `${rev}:roster-seats/`).split("\n").filter((f) => /^[a-z-]+\.js$/.test(f)).map((f) => f.slice(0, -3));
      return seatsFrom(files, (s) => git("show", `${rev}:roster-seats/${s}.js`));
    };
    let prev = at(base);
    for (const rev of revs) {
      const next = at(rev);
      const date = git("show", "-s", "--format=%ad", "--date=short", rev).trim();
      added = diff(prev, next, date).concat(added);
      prev = next;
    }
    added = diff(prev, now, flag("--date") || new Date().toISOString().slice(0, 10)).concat(added);
  } else {
    const prev = existsSync(join(ROOT, SNAP)) ? JSON.parse(readFileSync(join(ROOT, SNAP), "utf8")) : null;
    if (prev) added = diff(prev, now, flag("--date") || new Date().toISOString().slice(0, 10));
  }
  log.changes = added.concat(log.changes || []).slice(0, MAX_ENTRIES);
  writeOrCheck(LOG, render(log), { check: false });
  writeOrCheck(SNAP, snapText, { check: false });
  console.error(`${added.length} seat change(s) logged`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
