function inlineOf(doc, needle) {
  const at = doc.indexOf(needle);
  if (at < 0) return null;
  const open = doc.lastIndexOf("<script", at);
  const gt = doc.indexOf(">", open);
  const close = doc.indexOf("</script>", at);
  if (open < 0 || gt < 0 || close < 0) return null;
  return doc.slice(gt + 1, close);
}

