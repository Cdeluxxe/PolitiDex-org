#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// Tests for stances.html — THE SEVENTH SHELL, and the room for browsing by issue
// ─────────────────────────────────────────────────────────────────────────────
// Browsing PolitiDex by ISSUE was two homepage sections that both claimed the
// job: #stance-library (the desk — search, chips, shelves, per-issue detail) and
// #all-spotlights (the sixty-card Spotlight collection with its own scope chips,
// its own topic chips and its own search field). Two shelves, two search boxes,
// two labels in each nav, and no address for either one: both were fragments of
// a 2.25 MB front page, so "send me the issue browser" meant sending somebody
// the whole homepage plus a scroll instruction.
//
// So /stances is the room, and the homepage keeps one line that opens it.
//
// The failure modes, every one of which ships silently:
//
//   1. /stances RESOLVES TO THE FRONT PAGE. Without the rewrite — or with it
//      declared beneath something that also matches — the room is 2.1 MB of
//      homepage and the reader never reaches a shelf.
//   2. A RELATIVE PATH BECOMES AN HTML-AS-JS BUG. /stances/ is served 200 at a
//      trailing-slash path, so src="stance-library.js" resolves to
//      /stances/stance-library.js, matches the rewrite, and hands the browser
//      this document to parse as JavaScript: a blank room, no error naming why.
//   3. THE ENGINE GETS DUPLICATED. The brief's first rule was "engines stay
//      where they are". A room that inlines stance-library.js or spotlight-hub.js
//      instead of loading it is a second copy that drifts from the first.
//   4. THE HOMEPAGE KEEPS THE SHELF. If #all-spotlights, the library body host
//      or either module's <script> is still on '/', the split bought nothing:
//      the grid is still in the front page's first paint.
//   5. A DOOR GOES NOWHERE. Every in-app gesture that used to scroll — the
//      Explore rows, the Hot Topics fallback, digital-library.js's three
//      buttons, the Spotlight engine's two library hops — has to become a
//      navigation, and the two module names the homepage no longer ships have
//      to stay callable there or those call sites throw.
//   6. THE COPY CHAIN BECOMES A FAN. Two blocks are copied verbatim out of
//      index.html. Edited in place, a fix to the origin stops reaching here and
//      nothing fails.
//   7. A LOCKER GRID APPEARS. The brief forbids a second workspace here: the
//      receipts are ONE line, generated by the engine that always generated it,
//      pointed at /evidence instead of at a hash.
//   8. A SCORE OR A PARTY SORT APPEARS. Every count in this room is coverage.
//   9. THE SERVICE WORKER SERVES A ROOM WITH NO DESK, or pairs a new homepage
//      whose library is a door against a cached stance-library.js that expects
//      a body host to paint into.
//  10. THE SITEMAP GETS IT WRONG — either not listing a public browse room, or
//      listing the two private workspaces beside it.
//
// This harness gates all ten, in nine sections:
//
//   1. THE REWRITE — /stances and /stances/ at 200, after every earlier shell,
//      no wildcard, and no other address moved.
//   2. THE DOCUMENT — its banner, its canonical, root-absolute paths, every
//      inline block parses, and the two budgets.
//   3. THE COPY CHAIN — two slices byte-identical to index.html's.
//   4. THE ENGINES ARE SHARED, NOT COPIED.
//   5. THE SEAMS — every in-page gesture is an address, and Back still works.
//   6. THE DENYLIST — what this room must never carry.
//   7. THE HOMEPAGE IS A DOOR — no shelf, no grid, no module, one line.
//   8. THE SHIMS, BOOTED — the two names the homepage keeps, and what they
//      resolve to.
//   9. THE SERVICE WORKER AND THE SITEMAP.
//
//   node scripts/test-stances-shell.mjs
//
// No database, no network, no browser. Exit code is non-zero on any failure.
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => readFileSync(join(ROOT, f), "utf8");

const ST = R("stances.html");
const INDEX = R("index.html");
const SW = R("sw.js");
const TOML = R("netlify.toml");
const SITEMAP = R("sitemap.xml");
const SL_JS = R("stance-library.js");
const SH_JS = R("spotlight-hub.js");
const SPOT_ENGINE = R("spotlight-engine.js");

// Every "must not contain" runs against a comment-stripped view: this document's
// doctrine block NAMES the modules it deliberately does not carry, and a comment
// can neither satisfy nor violate a contract. Comments are blanked rather than
// removed so line numbers survive for anything that reports one.
const blank = (m) => String(m).replace(/[^\n]/g, " ");
const htmlBare = (s) => String(s).replace(/<!--[\s\S]*?-->/g, blank);
const cssBare = (s) => String(s).replace(/\/\*[\s\S]*?\*\//g, blank);
const jsBare = (s) => cssBare(s).replace(/^[ \t]*\/\/.*$/gm, blank);
const ST_BARE = htmlBare(ST);
const ST_CODE = jsBare(ST_BARE);
const INDEX_BARE = htmlBare(INDEX);
const INDEX_CODE = jsBare(INDEX_BARE);
const ENGINE_CODE = jsBare(SPOT_ENGINE);

let passed = 0;
const failures = [];
const ok = (cond, msg) => { if (cond) passed++; else failures.push(msg); };
const eq = (a, b, msg) => ok(a === b, `${msg} — expected ${JSON.stringify(b)}, got ${JSON.stringify(a)}`);
const has = (hay, needle, msg) => ok(String(hay).indexOf(needle) >= 0, `${msg} — "${needle}" missing`);
const lacks = (hay, needle, msg) => ok(String(hay).indexOf(needle) < 0, `${msg} — "${needle}" present and must not be`);
const section = (t) => console.log(`\n   ── ${t}`);

// ═════════════════════════════════════════════════════════════════════════════
// 1 · THE REWRITE
// ═════════════════════════════════════════════════════════════════════════════
section("1 · /stances is its own address");

const RULES = [...TOML.matchAll(/^\[\[redirects\]\]\s*\n((?:^[ \t]{2}\S.*\n)+)/gm)].map((m) => {
  const body = m[1];
  const field = (k) => (body.match(new RegExp(`^\\s*${k}\\s*=\\s*"?([^"\\n]+)"?`, "m")) || [])[1];
  return { from: field("from"), to: field("to"), status: field("status") };
});
const ruleIndex = (from) => RULES.findIndex((r) => r.from === from);
// Netlify is first-match-wins, so the only question a static test can answer is
// "which rule wins for this path".
const resolveAddr = (path) => {
  for (const r of RULES) {
    if (!r.from) continue;
    if (r.from.endsWith("/*")) { if (path.startsWith(r.from.slice(0, -1))) return r; }
    else if (r.from === path) return r;
  }
  return null;
};

ok(RULES.length > 0, "rewrite: netlify.toml declares at least one [[redirects]] rule");
for (const addr of ["/stances", "/stances/"]) {
  const hit = resolveAddr(addr);
  ok(hit && hit.to === "/stances.html" && String(hit.status) === "200",
    `rewrite: ${addr} is served /stances.html at 200 (got ${hit ? hit.to + " " + hit.status : "no matching rule"})`);
}

// THE ORDER. Both rules are exact paths, so nothing above them can swallow them
// today; the assertion is that the declaration order still protects them the day
// one of the rules above gains a wildcard.
{
  const p = ruleIndex("/p/*"), b = ruleIndex("/ballot"), m = ruleIndex("/me");
  const s = ruleIndex("/stances"), ss = ruleIndex("/stances/");
  ok(p >= 0 && b >= 0 && m >= 0 && s >= 0 && ss >= 0,
    "rewrite: /p/*, /ballot, /me, /stances and /stances/ are all declared");
  ok(s > b && s > m && s > p,
    `rewrite: /stances is declared after /p/*, /ballot and /me (indices p=${p} ballot=${b} me=${m} stances=${s})`);
  ok(ss > s, "rewrite: /stances/ is declared after /stances");
}

// NO WILDCARD. What a reader is looking at in this room is a QUERY (?issue=,
// ?scope=, ?q=), never a segment, so there is nothing beneath /stances for a
// rule to own — and a query string does not participate in rule matching at
// all, so none of the three needs a rule or can be broken by one.
ok(!RULES.some((r) => r.from && /^\/stances/.test(r.from) && r.from.includes("*")),
  "rewrite: no /stances* wildcard rule exists — an issue is a query, not a segment");

// ONE SPELLING. /library was the other candidate for THIS room and was not
// taken, so no /library rule may answer with stances.html — two addresses
// serving one document is the canonical splitting in half.
//
// THE PROBE USED TO BE WIDER THAN THE CLAIM, and the Digital Library split found
// that out. It rejected ANY /library* rule with status 200 regardless of what
// that rule pointed AT, so the day /library became a real address for a real
// other document — library.html, the archive room, which is where the searchable
// browse grid and the Legislation catalog live now — this failed while the
// sentence above it stayed true. What matters is the destination: the stance
// shelf answers at /stances and nowhere else. /library answering with
// library.html is not a second spelling of this room, it is a first spelling of
// a different one.
const LIB_200 = RULES.filter((r) => r.from && /^\/library/.test(r.from) && String(r.status) === "200");
ok(!LIB_200.some((r) => String(r.to) === "/stances.html"),
  "rewrite: a /library rule answers with stances.html — one spelling for this room, used everywhere");
ok(!RULES.some((r) => r.from && /^\/library/.test(r.from) && String(r.to) === "/stances.html"),
  "rewrite: /library redirects or rewrites to the stance shelf under any status");

// THE ADDRESSES THIS SPLIT MUST NOT STEAL.
for (const [addr, expect] of [
  ["/p/lee", "/person.html"],
  ["/i/guns", "/issue.html"],
  ["/issue/guns", "/spotlight.html"],
  ["/ballot", "/ballot.html"],
  ["/me", "/me.html"],
  ["/evidence", "/evidence.html"],
]) {
  const hit = resolveAddr(addr);
  ok(hit && hit.to === expect,
    `rewrite: ${addr} still resolves to ${expect} (got ${hit ? hit.to : "no matching rule"})`);
}
// A near-miss is NOT this address.
for (const addr of ["/stanceslibrary", "/stances/housing"]) {
  const hit = resolveAddr(addr);
  ok(!hit || hit.to !== "/stances.html",
    `rewrite: ${addr} is not answered by /stances.html (got ${hit ? hit.to : "no matching rule"})`);
}
ok(resolveAddr("/") === null, "rewrite: '/' has no rewrite rule — the front page is still index.html");

// ═════════════════════════════════════════════════════════════════════════════
// 2 · THE DOCUMENT
// ═════════════════════════════════════════════════════════════════════════════
section("2 · the banner, the canonical, root-absolute paths, the budgets");

// THE BANNER, which sw.js's SUB_SHELL_BANNER_RE reads to refuse a cached '/'
// whose body is actually this document. It has to be inside the sniff window.
const BANNER_RE = /\b(person|issue|spotlight|ballot|stances|evidence)\.html\s*—\s*THE\s+(?:SECOND|THIRD|FOURTH|FIFTH|SEVENTH|EIGHTH)\s+SHELL\b/;
const bm = BANNER_RE.exec(ST.slice(0, 4096));
ok(bm && bm[1] === "stances",
  "banner: stances.html declares itself the seventh shell inside the first 4096 characters");
has(ST, "/stances IS ITS OWN DOCUMENT", "banner: the banner names the address it serves");
ok(!BANNER_RE.test(INDEX), "banner: index.html carries no shell banner — that is what makes the guard a discriminator");

// A PUBLIC BROWSE ROOM, so unlike /ballot and /me it is indexable and carries a
// real canonical — on the www host, which is the one the apex 301s to.
has(ST, '<link rel="canonical" href="https://politidex.fyi/stances" />',
  "head: the canonical is politidex.fyi/stances");
has(ST, '<meta property="og:url" content="https://politidex.fyi/stances" />',
  "head: og:url matches the canonical");
ok(/<title>[^<]*PolitiDex[^<]*<\/title>/.test(ST), "head: the title names PolitiDex");
lacks(ST, 'name="robots"', "head: no robots meta — a public browse room is indexed");
lacks(ST, "application/ld+json",
  "head: no JSON-LD — index.html's WebSite block describes the front page, and a browse room is not it");

// EVERY SAME-ORIGIN PATH IS ROOT-ABSOLUTE. /stances/ is served 200, so a bare
// src would be answered with this document and parsed as JavaScript.
const attrs = [...ST_BARE.matchAll(/\b(?:src|href)\s*=\s*"([^"]*)"/g)].map((m) => m[1]);
const relative = attrs.filter((v) => v && !/^(?:\/|https?:|#|mailto:|data:|\/\/)/.test(v));
eq(relative.length, 0,
  `paths: every same-origin src/href in stances.html is root-absolute (offenders: ${relative.join(", ")})`);

const TAGS = [...ST.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)]
  .map((m) => ({ attrs: m[1] || "", body: m[2] }));
const inlineBlocks = TAGS.filter((t) => !/\bsrc\s*=/.test(t.attrs) && t.body.trim());
ok(inlineBlocks.length >= 2,
  `paths: stances.html carries its inline blocks (${inlineBlocks.length} found)`);
let parseFails = [];
for (const b of inlineBlocks) { try { new vm.Script(b.body); } catch (e) { parseFails.push(e.message); } }
eq(parseFails.length, 0, `paths: every inline <script> block in stances.html parses (${parseFails[0] || ""})`);

// Two tripwires, not targets. The document is CHROME plus the two copied blocks;
// a budget going red is the split being undone one <script> at a time.
const gz = gzipSync(Buffer.from(ST, "utf8")).length;
ok(gz < 24 * 1024, `budget: stances.html is ${(gz / 1024).toFixed(1)} KB gzipped (ceiling 24 KB)`);
const localSrcs = TAGS.map((t) => (t.attrs.match(/\bsrc\s*=\s*["']([^"']+)["']/) || [])[1])
  .filter((s) => s && !/^(?:https?:)?\/\//.test(s));
ok(localSrcs.length <= 34,
  `budget: stances.html loads ${localSrcs.length} local scripts (ceiling 34 — sixteen of them are State Senate waves)`);
ok(localSrcs.every((s) => s.charAt(0) === "/"), "budget: every local script src is root-absolute");

// ═════════════════════════════════════════════════════════════════════════════
// 3 · THE COPY CHAIN
// ═════════════════════════════════════════════════════════════════════════════
section("3 · the two copied blocks are byte-identical to index.html's");

// A chain, not a fan: each block records the file and the line range it came
// from, so a fix to the origin surfaces as ONE test failure per document
// instead of as a silent divergence nobody is looking for. When index.html
// shifts, the header comment in stances.html and this table move TOGETHER.
const lines = (s) => String(s).split("\n");
const slice = (src, a, b) => lines(src).slice(a - 1, b).join("\n");
//   AND ONCE MORE, UP BY 783, for the pass that took the curator's tools OFF
// the front page rather than gating them there. The Bulk Import / Database
// Expansion tool, the Politician Manager, the <template> that wrapped them, the
// head CSS lock, the allow-list, the gate and the four gated nav rows all left
// index.html for admin.html at /admin, and the front page lost 783 lines net.
// Every one of those cuts is above this block, which is the only fact the pin
// cares about; not a character of the block itself changed. Re-derived by
// locating the run, as always — the arithmetic agreed afterwards, which is the
// order that catches a bad pin rather than confirming one.
//   AND ONE MORE MOVE, FOR THE HOMEPAGE DISTRICT VOICE GATE. The front page grew
// a hero card pointing a stranger at /voice, its styles, and the standing read
// that swaps the verb on it — 116 lines above the CSS pin and 117 above the
// script block, all of them above both. Re-derived the only way this pin is ever
// allowed to move: by locating in index.html the run that this document actually
// carries, not by adding the delta to the old start. The arithmetic agreed
// afterwards, and the declared ranges in the copies moved in the same edit.
const COPIES = [
  { from: "index.html", src: INDEX, a: 20473, b: 20497, what: "the .pdxis-stance* pill rules" },
  { from: "index.html", src: INDEX, a: 20516, b: 20636, what: "the PDXStance vocabulary" },
];
// Both index.html ranges have now moved THREE TIMES, and the third ran the other
// way. The Digital Library split took #digital-library out of index.html but left
// a longer note where it stood and added a paragraph to the head forwarder, so
// the front page GREW by twelve lines in two places ABOVE both blocks and both
// ranges slid DOWN by twenty-four — to 20913–20937 and 20956–21077. A pin that
// only ever drifts one direction is a pin nobody re-derives.
//
// Before that, both index.html ranges moved TWICE. First by −2021 for the three-room
// split (People's Mandate, District Voice and Follow the Money became /mandate,
// /voice and /money, and the agenda wall they took with them sat above both of
// these blocks), and again by a further −1572 when the Community Exchange left
// for /community and the homepage's money surfaces — the Follow the Money card
// grid, the #N-by-funding board and the Wealth Transparency leaderboard — were
// deleted or moved to /money. Both departures sat above these two blocks, so
// both ranges slid up together by the same amount.
//
// RE-DERIVED BY LOCATING THE RUN VERBATIM, NEVER BY SUBTRACTING A DIFF. The
// numbers below came from searching index.html for the longest run that still
// appears byte-identical in stances.html, not from arithmetic on the old pair.
// That distinction is not pedantry: a sibling suite once carried a range that
// arithmetic had walked INSIDE an unrelated block, and it kept passing green
// because the assertion only ever compared two copies of whatever happened to
// live at those lines. The pill rules came back as 25 lines and the vocabulary
// as 122 — both unchanged in length, which is the check that the run found is
// the run meant.
//
// A FOURTH MOVE, AGAIN DOWNWARD, AGAIN BY THE SAME 114 LINES for both ranges.
// The Home-hygiene pass edited only the front page, and only above these two
// blocks: a head CSS lock for the admin expansion tools, a short H.R.1 teaching
// card above Door 1, a <template> wrapper that keeps the admin sections out of
// the document, and the restored <script> tag whose loss had been painting
// toggleFollowMoney's source under the footer. The pill rules came back as 25
// lines and the vocabulary as 122, both at their full length, which is again the
// check that the run found is the run meant.
//
// A FIFTH MOVE, DOWNWARD BY EXACTLY ONE LINE. The pass that gave /my-stances,
// /me, /ballot and this document one reader for "sides this person holds" added
// a single <script src="/stance-sides.js"> tag to index.html's shell, and that
// tag sits above both of these blocks. Nothing else on the front page changed.
// The pill rules came back at their full 25 lines at what was then 20210–20234,
// and neither
// the line above nor the line below appears in stances.html, so that run is
// maximal as well as unchanged — which is the pair of facts a pin is for.
//
// THE VOCABULARY PIN LOST A LINE OFF ITS TAIL, AND THAT IS A CORRECTION, NOT A
// SHIFT. Searching for the old 122-line run came back with TWO answers,
// 20252–20373 and 20253–20374, because the block is fenced by a blank line at
// each end and a blank line is shared by every document that has one. Reading
// the boundaries settles it: 20252 is blank, 20253 is <script>, 20373 is
// </script>, 20374 is blank. So the run of SUBSTANCE is 20253–20373 and it is
// 121 lines; the historical 122 had always carried the trailing blank, and the
// pin now names the <script>…</script> run and nothing else. A pin whose range
// ends on whitespace is a pin that can slide a line in either direction and
// still come up green, which is the failure mode this whole table exists to
// avoid. The same correction was made to the PDXSaved pin in
// scripts/test-me-document.mjs during this pass, for the same reason.
//
// evidence.html, spotlight.html and person.html copy this same vocabulary block
// and their pins still declare it as 20252–20373 — one line early at the head,
// carrying the leading blank instead of the trailing one. Those suites are
// green, because that is exactly the slop described above. Correcting them is a
// deliberate separate pass over every pin those three documents carry, not a
// drive-by from this one, and it is recorded here so the next author reads the
// disagreement as known rather than as a clue.
//
// THE NINE-LINE MOVE. `/pdx-finance.js` — the module behind the second
// letterhead money pill, the personal-disclosure one — took a script tag and an
// eight-line load-order note into index.html at line 15020, above both of these
// blocks and above every other pin into this document. Both runs slid down by
// nine and neither changed: the pill rules are at 20219–20243 and the vocabulary
// at 20262–20382, each located verbatim and each still maximal at its own
// boundaries. The one-line disagreement with evidence.html, spotlight.html and
// person.html described above is unchanged — those pins moved by the same nine
// and kept their leading blank.
//
// THE THIRTEEN-LINE MOVE, UPWARD. The person-file Money trim deleted the
// fabricated transparency card from the profile modal, which took the 💰 Follow
// This Money Trail button with it — and with the button gone, the thirteen lines
// of index.html at ~16090 that defined window.toggleFollowMoney and explained why
// it had outlived the funding leaderboard had no caller left. Removing them
// pulled everything below UP by thirteen: the pill rules are now 20206-20230 and
// the vocabulary 20249-20369, each located verbatim and each still maximal at its
// own boundaries. The one-line disagreement with the other three documents is
// unchanged — they moved by the same thirteen and kept their leading blank.
//
// THE TWELVE-LINE MOVE, DOWNWARD. The Voice-hub pass gave window.pdxMapConfirm a
// twelve-line block that spends the saved return intent after a location save, so
// somebody who set a location in order to use District Voice lands back on /voice
// instead of on the finder. That block sits at ~18832, above both of these runs.
// The pill rules are now 20218–20242 and the vocabulary 20261–20381, each located
// by searching index.html for the run that appears byte-identical in stances.html
// and each unchanged in length (25 and 121), which is the check that the run found
// is the run meant. The arithmetic agreed afterwards; it was not the source. The
// one-line disagreement with evidence.html, spotlight.html and person.html is
// unchanged — those pins moved by the same twelve and kept their leading blank.
for (const c of COPIES) {
  const header = new RegExp(`COPIED VERBATIM FROM ${c.from.replace(".", "\\.")} LINES ${c.a}[^0-9]{1,3}${c.b}`);
  ok(header.test(ST), `copy: stances.html declares ${c.what} as ${c.from} ${c.a}–${c.b}`);
  const body = slice(c.src, c.a, c.b);
  ok(body.trim().length > 0, `copy: ${c.from} ${c.a}–${c.b} is a non-empty slice`);
  ok(ST.indexOf(body) >= 0,
    `copy: ${c.what} in stances.html is byte-identical to ${c.from} ${c.a}–${c.b} — ` +
    "if the origin moved, move the declared range and this pin together");
}
// The vocabulary is a copy on BOTH documents, which is the point of pinning it:
// index.html still declares its own.
has(INDEX_CODE, "window.PDXStance", "copy: index.html still declares PDXStance — this split did not take it");
has(ST_CODE, "window.PDXStance", "copy: stances.html declares PDXStance for the desk to read");
// .pdxis-callout* is NOT copied — it styles the profile modal's Spotlight rail,
// and there is no profile modal on this document.
lacks(cssBare(ST_BARE), ".pdxis-callout", "copy: the profile-modal callout rules were not dragged along");

